#!/usr/bin/env python3
"""Gaussian estimate with the full covariance AND the joint lattice of the class values.

The summed class vector of the four blocks lies in a coset v0 + Lambda of a lattice. ssxx.gauss takes the product of
the per-class spacings as the covolume; the true lattice (from the compressions of composite N) can be much sparser,
and the probability of hitting the target is covol(Lambda) * phi_Sigma(t - mu) on the hyperplane fixed by the row sums.

    python3 search/gauss_lat.py N g [g2] --rows a,b,c,d [--bordered] [--K 4000]
"""
import argparse, math, sys
from math import gcd, log10, pi
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).resolve().parent))
from bnw import Struct

KINDS = ["L", "L", "A", "A"]


def hnf_basis(vecs, dim):
    """basis (rows, upper triangular, python ints) of the lattice generated by integer vectors"""
    B = []                                   # list of rows; B[i] has pivot column piv[i]
    piv = []
    for v in vecs:
        v = [int(x) for x in v]
        i = 0
        while True:
            # find first nonzero column of v
            j = next((c for c in range(dim) if v[c] != 0), None)
            if j is None:
                break
            # find basis row with pivot j
            if j in piv:
                k = piv.index(j)
                b = B[k]
                # extended gcd on (b[j], v[j])
                a0, a1 = b[j], v[j]
                if a1 % a0 == 0:
                    q = a1 // a0
                    v = [x - q * y for x, y in zip(v, b)]
                    continue
                g, s, t = egcd(a0, a1)
                nb = [s * x + t * y for x, y in zip(b, v)]          # pivot g
                nv = [(a0 // g) * y - (a1 // g) * x for x, y in zip(b, v)]   # pivot 0
                B[k] = nb
                v = nv
                continue
            else:
                # insert new row with pivot j
                if v[j] < 0:
                    v = [-x for x in v]
                B.append(v); piv.append(j)
                break
    order = sorted(range(len(B)), key=lambda k: piv[k])
    return [B[k] for k in order], [piv[k] for k in order]


def egcd(a, b):
    x0, x1, y0, y1 = 1, 0, 0, 1
    while b:
        q, a, b = a // b, b, a % b
        x0, x1 = x1, x0 - q * x1
        y0, y1 = y1, y0 - q * y1
    return a, x0, y0


def estimate(st, rows, bordered, K=4000, seed=1, nd=400):
    rng = np.random.default_rng(seed)
    tg = -4 if bordered else 0
    lN, mus, covs, base, diffs = 0.0, [], [], None, []
    for kind, r in zip(KINDS, rows):
        n = st.counts(kind).get(r, 0)
        if bordered and r == 0:
            n //= 2
        if n == 0:
            return None
        lN += log10(n)
        V = np.rint(st.values(kind, st.sample(kind, r, K, rng))).astype(np.int64)
        mus.append(V.mean(0)); covs.append(np.cov(V.T.astype(float), bias=True))
        base = V[0] if base is None else base + V[0]
        idx = rng.integers(1, len(V), nd)
        diffs.extend(list(V[idx] - V[0]))
    C = st.C
    mu = sum(mus); Sg = sum(covs)
    var = np.diag(Sg)
    fixed = [c for c in range(C) if var[c] <= 1e-9]
    for c in fixed:
        if abs(tg - mu[c]) > 1e-6:
            return None
    free = [c for c in range(C) if var[c] > 1e-9]
    c0 = free[1:]                       # drop one class: the row sums fix a linear combination
    D = [[int(d[c]) for c in c0] for d in diffs]
    B, piv = hnf_basis(D, len(c0))
    if len(B) < len(c0):
        return ("rank", len(B), len(c0))
    covol = 1
    for k, b in enumerate(B):
        covol *= b[piv[k]]
    # membership of the target in base + Lambda (back-substitution on the triangular basis)
    t = [int(tg - base[c]) for c in c0]
    for k, b in enumerate(B):
        j = piv[k]
        if t[j] % b[j]:
            return ("coset", lN)
        q = t[j] // b[j]
        t = [x - q * y for x, y in zip(t, b)]
    if any(t):
        return ("coset", lN)
    gprod = 1
    for c in c0:
        vals = [int(d[c0.index(c)]) for d in D]
        g = 0
        for x in vals:
            g = gcd(g, x)
        gprod *= max(g, 1)
    d = (tg - mu)[c0]
    Sk = Sg[np.ix_(c0, c0)]
    sign, logdet = np.linalg.slogdet(Sk)
    quad = float(d @ np.linalg.solve(Sk, d))
    dens = (-0.5 * len(c0) * math.log(2 * pi) - 0.5 * logdet - 0.5 * quad) / math.log(10)
    covol = abs(covol)
    return lN + dens + log10(covol), lN + dens + log10(gprod), log10(covol) - log10(gprod)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("N", type=int); ap.add_argument("gens", type=int, nargs="+")
    ap.add_argument("--rows", required=True); ap.add_argument("--bordered", action="store_true")
    ap.add_argument("--K", type=int, default=4000)
    a = ap.parse_args()
    st = Struct(a.N, a.gens, plain=not a.bordered)
    rows = tuple(int(x) for x in a.rows.split(","))
    r = estimate(st, rows, a.bordered, a.K)
    if r is None or isinstance(r[0], str):
        print(f"N = {a.N} H = <{a.gens}> rows {rows}: {r}"); return
    lat, full, idx = r
    print(f"N = {a.N} H = <{a.gens}> rows {rows}: classes {st.C}, log10 E lattice {lat:.2f}, full-cov {full:.2f}, "
          f"lattice index 10^{idx:.2f}")


if __name__ == "__main__":
    main()
