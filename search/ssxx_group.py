def field_mult(p, k):
    if (p, k) in L.PRIMITIVE:
        return L.field_mult_matrix(p, k)
    import skew_field
    return skew_field.primitive_companion(p, k) % p


def group(N, p, k):
    q = p ** k
    if N % q or (N // q) % p == 0:
        raise ValueError("need p^k || N")
    m = N // q
    mods = [p] * k + ([m] if m > 1 else [])
    return L.AbGroup(mods), q, m


def diag_perm(G, p, k, m, Mf, e, u):
    n = len(G.mods)
    A = np.eye(n, dtype=np.int64)
    A[:k, :k] = L.mat_pow_mod(Mf, e, p) if e else np.eye(k, dtype=np.int64)
    if m > 1:
        A[k, k] = u % m
    return G.perm_from_matrix(A)


def perm_order(P):
    x = P.copy(); n = 1
    ident = np.arange(len(P))
    while not np.array_equal(x, ident):
        x = P[x]; n += 1
    return n


class GStruct:
    """The two orbit structures (H for C, D; <H, -1> for A, B) on G with common classes."""

    def __init__(self, N, p, k, gens):
        self.N, self.p, self.k, self.gens = N, p, k, gens
        self.G, self.q, self.m = group(N, p, k)
        Mf = field_mult(p, k)
        perms = [diag_perm(self.G, p, k, self.m, Mf, e, u) for e, u in gens]
        self.perms = perms
        self.stA = L.Structure(self.G, perms)
        self.stL = L.Structure(self.G, perms + [self.G.neg()])
        assert np.array_equal(self.stA.cls, self.stL.cls)
        self.C = self.stA.C

    def st(self, kind):
        return self.stL if kind == "L" else self.stA

    def counts(self, kind):
        st = self.st(kind)
        return {r: int(round(st.pool(r))) for r in range(-self.N, self.N + 1) if st.pool(r) > 0.5}

    def patterns(self):
        okL = {r for r in self.counts("L") if r > 0}; okA = {r for r in self.counts("A") if r > 0}
        out = []
        for a in sorted(okL):
            for b in sorted(okL):
                if b < a: continue
                for c in sorted(okA):
                    d2 = 4 * self.N - a * a - b * b - c * c
                    if d2 < c * c: continue
                    d = math.isqrt(d2)
                    if d * d == d2 and d in okA:
                        out.append((a, b, c, d))
        return out

    def enum(self, kind, r):
        st = self.st(kind)
        d = W.WORK / "ssxxg"; d.mkdir(exist_ok=True)
        tag = "_".join(f"{e}-{u}" for e, u in self.gens).replace(".", "-").replace("+", "_")
        base = d / f"g{self.N}_{self.p}^{self.k}_{tag}_{kind}_{r}"
        vals, masks = base.with_suffix(".v"), base.with_suffix(".m")
        if not vals.exists():
            inp = base.with_suffix(".in")
            S = np.rint(st.S).astype(np.int32)
            with open(inp, "wb") as f:
                f.write(struct.pack("4i", st.O, self.C, r, 0))
                f.write(np.asarray(st.sizes, np.int32).tobytes()); f.write(S.tobytes())
            subprocess.run([W.bin("bnw_enum"), str(inp), str(vals) + ".tmp", str(masks) + ".tmp"], check=True,
                           capture_output=True)
            os.replace(str(vals) + ".tmp", vals); os.replace(str(masks) + ".tmp", masks)
        return np.fromfile(vals, np.int16).reshape(-1, self.C), np.fromfile(masks, np.uint64)


def group_developed(x, G):
    diff = G.index(G.coords[None, :, :] - G.coords[:, None, :])      # diff[g, h] = h - g
    return np.asarray(x, np.int64)[diff]


def complex_hadamard_group(seqs, G):
    A, B, C, D = (group_developed(x, G) for x in seqs)
    N = G.v
    if not (np.array_equal(A, A.T) and np.array_equal(B, B.T)):
        raise ValueError("A, B not symmetric")
    if not np.array_equal(A @ A.T + B @ B.T + C @ C.T + D @ D.T, 4 * N * np.eye(N, dtype=np.int64)):
        raise ValueError("sum X X^T != 4N I")
    R = np.zeros((N, N), np.int64); R[np.arange(N), G.neg()] = 1
    DR = D @ R
    Kr = np.block([[(A + B) // 2, (C + DR) // 2], [(C.T + DR) // 2, -(A + B) // 2]])
    Ki = np.block([[(A - B) // 2, (C - DR) // 2], [-(C.T - DR) // 2, (A - B) // 2]])
    n = 2 * N
    if not np.all(np.abs(Kr) + np.abs(Ki) == 1):
        raise ValueError("entries")
    re = Kr @ Kr.T + Ki @ Ki.T; im = Ki @ Kr.T - Kr @ Ki.T
    if not (np.array_equal(re, n * np.eye(n, dtype=np.int64)) and not im.any()):
        raise ValueError("K K* != 2N I")
    return Kr, Ki


def generators(N, p, k):
    """Diagonal automorphisms (w^e, u) of odd order, one per generated cyclic subgroup."""
    q = p ** k; m = N // q
    out, subs = {}, set()
    units = [u for u in range(1, m) if gcd(u, m) == 1] if m > 1 else [1]
    for e in range(0, q - 1):
        oe = (q - 1) // gcd(q - 1, e) if e else 1
        if oe % 2 == 0: continue
        for u in units:
            ou, x = 1, u % max(m, 1)
            while m > 1 and x != 1:
                x = x * u % m; ou += 1
            if ou % 2 == 0: continue
            o = oe * ou // gcd(oe, ou)
            if o == 1: continue
            sub = frozenset(((j * e) % (q - 1), pow(u, j, m) if m > 1 else 0) for j in range(o))
            if sub in subs: continue
            subs.add(sub)
            out[(e, u)] = o
    return out


def run(N, p, k, maxo=44, maxpairs=2e10, log=None, K=2):
    gens = generators(N, p, k)
    # one representative per (orbit count); try the ones with the most orbits within maxo first? cheapest first
    cand = []
    seen_keys = set()
    G0, q, m = group(N, p, k)
    for (e, u), o in sorted(gens.items(), key=lambda kv: kv[1]):
        try:
            gs = GStruct(N, p, k, [(e, u)])
        except Exception:
            continue
        if gs.stA.O > maxo or gs.stA.O > 62 or gs.stL.O > 62:
            continue
        key = (tuple(sorted(gs.stA.sizes.tolist())), gs.C, tuple(sorted(np.bincount(gs.stA.cls[gs.stA.cls >= 0]).tolist())))
        if key in seen_keys:
            continue
        seen_keys.add(key)
        cand.append((gs.stA.O, o, e, u, gs))
    print(f"N = {N} = {p}^{k} x {m}: {len(cand)} inequivalent single-generator structures with <= {maxo} orbits",
          flush=True)
    for O, o, e, u, gs in sorted(cand, key=lambda r: r[0]):
        for pat in gs.patterns():
            sizes = [gs.counts(kd).get(r, 0) for kd, r in zip(ssxx.KINDS, pat)]
            order = ssxx.best_pairing(sizes)
            if ssxx.pair_cost(sizes, order) > maxpairs:
                continue
            t0 = time.time()
            lists, masks = [], []
            for kd, r in zip(ssxx.KINDS, pat):
                V, M = gs.enum(kd, r); lists.append(V); masks.append(M)
            sols, total = join4([lists[i] for i in order], gs.C, K, None, target=0)
            print(f"  H = <(w^{e}, {u})> order {o}, {O} orbits: rows {pat}, lists {sizes}, {total} solutions "
                  f"({time.time() - t0:.1f}s)", flush=True)
            for sol in sols:
                idx = [0] * 4
                for pos, i in enumerate(order):
                    idx[i] = sol[pos]
                seqs = []
                for i, (kd, j) in enumerate(zip(ssxx.KINDS, idx)):
                    st = gs.st(kd)
                    y = np.array([-1 if (int(masks[i][j]) >> b) & 1 else 1 for b in range(st.O)])
                    seqs.append(y[st.orb])
                complex_hadamard_group(seqs, gs.G)
                rec = {"N": N, "group": [int(x) for x in gs.G.mods], "field": [p, k], "generator": [e, u],
                       "subgroup_order": o, "rowsums": [int(x.sum()) for x in seqs],
                       "sequences": ["".join("+" if v > 0 else "-" for v in x) for x in seqs]}
                if log:
                    with open(log, "a") as f:
                        f.write(json.dumps(rec) + "\n")
                print(f"  verified: complex Hadamard matrix of order {2 * N} over {gs.G.mods.tolist()}", flush=True)
                return rec
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd"); ap.add_argument("N", type=int); ap.add_argument("p", type=int); ap.add_argument("k", type=int)
    ap.add_argument("--maxo", type=int, default=44); ap.add_argument("--maxpairs", type=float, default=2e10)
    ap.add_argument("--log")
    a = ap.parse_args()
    r = run_gl2(a.N, a.maxo, a.maxpairs, a.log) if a.cmd == "gl2" else run(a.N, a.p, a.k, a.maxo, a.maxpairs, a.log)
    print(f"N = {a.N}: {'FOUND' if r else 'nothing'}")



