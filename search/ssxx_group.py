#!/usr/bin/env python3
"""Szöllősi's (ssxx) array over non-cyclic abelian groups G = GF(p^k) x Z_m (search/ssxx.py does G = Z_N).

Theorem 4 of arXiv:2603.09572 holds for group-developed matrices over any abelian group G of odd order N: with
X_{g,h} = x(h - g), all such matrices commute, R (the matrix of g -> -g) satisfies R X^T = X R, D R is symmetric,
and A, B symmetric (a(-g) = a(g)) with A A^T + B B^T + C C^T + D D^T = 4N I give the quaternary Hadamard matrix

    K = [[X, Y], [Y*, -X*]],   X = (A + B)/2 + i (A - B)/2,   Y = (C + D R)/2 + i (C - D R)/2

of order 2N (checked exactly for every hit). Symmetry: H generated by diagonal automorphisms g = (w^e, u), w a
primitive element of GF(p^k) acting by multiplication on Z_p^k and u in Z_m^*, of odd order (so -1 is not in H);
C, D are constant on H-orbits and A, B on <H, -1>-orbits; the condition holds on the <H, -1>-classes. Lists are
complete (search/bnw_enum.c) and joined exactly (search/join4x.c), as in ssxx.py.

    python3 search/ssxx_group.py run N p k [--maxo 44] [--maxpairs 2e10] [--log FILE]
"""
import argparse, itertools, json, math, os, struct, subprocess, sys, time
from math import gcd
from pathlib import Path
