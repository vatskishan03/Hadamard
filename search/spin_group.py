def mat_order(M, p):
    I = np.eye(2, dtype=np.int64)
    X, k = M % p, 1
    while not np.array_equal(X, I):
        X, k = (X @ M) % p, k + 1
        if k > p * p:
            return None
    return k


def gl2(p):
    out = []
    for a, b, c, d in itertools.product(range(p), repeat=4):
        if (a * d - b * c) % p:
            out.append(np.array([[a, b], [c, d]], dtype=np.int64))
    return out


class SpinG:
    def __init__(self, p, q, hgens, mu):
        """hgens: list of (M, u); mu: (M, u)"""
        self.p, self.q, self.v = p, q, p * p * q
        G = L.AbGroup([p, p, q])
        self.G = G
        def perm(Mu):
            M, u = Mu
            A = np.zeros((3, 3), dtype=np.int64)
            A[:2, :2] = M
            A[2, 2] = u
            return G.perm_from_matrix(A)
        self.hp = [perm(x) for x in hgens]
        self.mup = perm(mu)
        self.stH = L.Structure(G, self.hp)
        self.stK = L.Structure(G, self.hp + [self.mup])
        stH, stK = self.stH, self.stK
        neg = G.neg()
        rep = np.array([np.flatnonzero(stK.orb == o)[0] for o in range(stK.O)])
        partner = stK.orb[neg[rep]]
        if np.any(partner[1:] == np.arange(1, stK.O)):
            raise AssertionError('a K-orbit is closed under negation')
        repH = np.array([np.flatnonzero(stH.orb == o)[0] for o in range(stH.O)])
        if np.any(stH.orb[neg[repH]][1:] == np.arange(1, stH.O)):
            raise AssertionError('an H-orbit is closed under negation')
        # mu must permute the H-orbits with order 3 (mu^3 maps every H-orbit to itself)
        m3 = self.mup[self.mup[self.mup]]
        if not np.array_equal(stH.orb[m3], stH.orb):
            raise AssertionError('mu^3 does not fix the H-orbits')
        if np.array_equal(stH.orb[self.mup], stH.orb):
            raise AssertionError('mu fixes the H-orbits')
        self.pairs = [(o, int(partner[o])) for o in range(1, stK.O) if o < partner[o]]
        self.M = np.zeros((stK.C, stH.O, stH.O))
        mu2 = self.mup[self.mup]
        for c, s in enumerate(stK.reps):
            for img in (s, self.mup[s], mu2[s]):
                self.M[c] += stH.S[stH.cls[img]]
        self.M = (self.M + self.M.transpose(0, 2, 1)) / 2
        self.SA = (stK.S + stK.S.transpose(0, 2, 1)) / 2
        self.b = math.isqrt((4 * self.v - 1) // 3)
        assert 1 + 3 * self.b ** 2 == 4 * self.v, 'v is not hexagonal'

    def A_vectors(self, s):
        Y = np.zeros((len(s), self.stK.O))
        Y[:, 0] = 1
        for j, (o, q) in enumerate(self.pairs):
            Y[:, o] = s[:, j]
            Y[:, q] = -s[:, j]
        return Y

    def estimate(self, samples=3000, rng=None):
        rng = rng or np.random.default_rng(1)
        nA = len(self.pairs)
        s = np.where(rng.random((samples, nA)) < 0.5, 1.0, -1.0)
        VA = self.stK.class_values(self.A_vectors(s))
        NB = self.stH.pool(self.b)
        if NB == 0:
            return None
        YB = self.stH.sample(self.b, samples, rng)
        VB = np.einsum('bo,cop,bp->bc', YB, self.M, YB, optimize=True)
        V = VA + VB
        lp = []
        for c in range(self.stK.C):
            var, m = V[:, c].var(), V[:, c].mean()
            if var < 1e-9:
                if abs(m) > 1e-6:
                    return None
                continue
            lp.append((-0.5 * log10(2 * pi * var) - m ** 2 / (2 * var) / math.log(10) + log10(4)))
        lp.sort()
        return nA * log10(2) + log10(NB) + sum(lp[1:]), nA * log10(2), log10(NB)

    def sequences(self, A, B):
        a = A.astype(np.int64)[self.stK.orb]
        b = B.astype(np.int64)[self.stH.orb]
        c = b[self.mup]
        d = b[self.mup[self.mup]]
        return [a, b, c, d]


def group_elems(perms, v):
    ident = tuple(range(v))
    G = {ident}
    fr = [np.arange(v)]
    while fr:
        x = fr.pop()
        for p in perms:
            y = p[x]
            t = tuple(y.tolist())
            if t not in G:
                G.add(t)
                fr.append(y)
    return [np.array(g) for g in G]


def fibre_values_group(Gp, perms, U, shifts, skew, maxvars=18):
    v = Gp.v
    els = group_elems(perms, v)
    orb, nO = L.closure_partition(v, perms)
    U = sorted(int(u) for u in U)
    cos = -np.ones(v, dtype=np.int64)
    reps = []
    for x in range(v):
        if cos[x] < 0:
            c = [int(Gp.index(Gp.coords[x] + Gp.coords[u])) for u in U]
            for y in c:
                cos[y] = len(reps)
            reps.append(c)
    nc = len(reps)
    corb = -np.ones(nc, dtype=np.int64)
    corbits = []
    for c in range(nc):
        if corb[c] < 0:
            o = sorted({int(cos[g[reps[c][0]]]) for g in els})
            for d in o:
                corb[d] = len(corbits)
            corbits.append(o)
    neg = Gp.neg()
    OFF = 1 << 15
    total = {0: 1 << OFF}          # rowsum -> bitset of (value + OFF)
    done = set()
    for oi, o in enumerate(corbits):
        if oi in done:
            continue
        done.add(oi)
        c0 = o[0]
        negc = int(corb[cos[neg[reps[c0][0]]]])
        paired = skew and negc != oi
        if paired:
            done.add(negc)
        pts = reps[c0]
        pos = {x: i for i, x in enumerate(pts)}
        trans = {}
        for g in els:
            d = int(cos[g[pts[0]]])
            if d not in trans:
                trans[d] = g
        pulled = []
        for d in o:
            gi = np.argsort(trans[d])
            for s in shifts:
                pulled.append(int(gi[s]))
        perms_s = [np.array([pos[int(Gp.index(Gp.coords[x] + Gp.coords[s]))] for x in pts]) for s in pulled]
        vars_ = sorted({int(orb[x]) for x in pts})
        col = {}
        if skew and not paired:
            free = []
            for ov in vars_:
                x0 = int(np.flatnonzero(orb == ov)[0])
                if x0 == 0 or ov in col:
                    continue
                nv = int(orb[neg[x0]])
                col[ov] = (len(free), 1)
                col[nv] = (len(free), -1)
                free.append(ov)
        else:
            free = list(vars_)
            col = {ov: (i, 1) for i, ov in enumerate(free)}
        if len(free) > maxvars:
            return None
        S = np.array(list(itertools.product((1, -1), repeat=len(free))), dtype=np.int64).reshape(-1, len(free))
        X = np.empty((len(S), len(pts)), dtype=np.int64)
        for i, x in enumerate(pts):
            if x == 0:
                X[:, i] = 1
            else:
                j, sg = col[int(orb[x])]
                X[:, i] = sg * S[:, j]
        val = np.zeros(len(S), dtype=np.int64)
        for pm in perms_s:
            val += (X * X[:, pm]).sum(1)
        mult = 2 if paired else 1
        rs = np.zeros(len(S), dtype=np.int64) if paired else len(o) * X.sum(1)
        out = set(zip((mult * val).tolist(), rs.tolist()))
        new = {}
        for (dv, dr) in out:
            for r0, bits in total.items():
                r1 = r0 + dr
                sh = bits << dv if dv >= 0 else bits >> (-dv)
                new[r1] = new.get(r1, 0) | sh
        total = new
    res = {}
    for rs, bits in total.items():
        vals, i = set(), 0
        b = bits
        while b:
            low = (b & -b).bit_length() - 1
            vals.add(low - OFF)
            b &= b - 1
        res[rs] = vals
    return res


def fmt(Mu):
    M, u = Mu
    return f'{M[0,0]},{M[0,1]},{M[1,0]},{M[1,1]};{u}'


def parse(s):
    m, u = s.split(';')
    a, b, c, d = (int(x) for x in m.split(','))
    return (np.array([[a, b], [c, d]], dtype=np.int64), int(u))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('cmd', choices=('rank', 'search', 'check'))
    ap.add_argument('p', type=int)
    ap.add_argument('q', type=int)
    ap.add_argument('h', nargs='?')
    ap.add_argument('mu', nargs='?')
    ap.add_argument('--maxorbits', type=int, default=130)
    ap.add_argument('--minorbits', type=int, default=20)
    ap.add_argument('--restarts', type=int, default=10 ** 9)
    ap.add_argument('--steps', type=int, default=3000)
    ap.add_argument('--seed', type=int, default=1)
    ap.add_argument('--limit', type=int, default=400)
    a = ap.parse_args()
    p, q = a.p, a.q
    if a.cmd == 'rank':
        rng = np.random.default_rng(1)
        G = L.AbGroup([p, p, q])
        mats = gl2(p)
        key = lambda M, u: (tuple(int(x) for x in M.ravel()), u)
        def mul(x, y):
            return ((x[0] @ y[0]) % p, x[1] * y[1] % q)
        def powers(x):
            out, y = [], (np.eye(2, dtype=np.int64), 1)
            while True:
                y = mul(y, x)
                out.append(y)
                if key(*y) == key(np.eye(2, dtype=np.int64), 1):
                    return out
        units = list(range(1, q))
        elems = [(M, u) for M in mats for u in units]
        cube = {key(*x): key(*mul(mul(x, x), x)) for x in elems}
        seenH, tried = set(), 0
        for x in elems:
            pw = powers(x)
            if len(pw) % 2 == 0 or len(pw) == 1:
                continue
            Hset = frozenset(key(*y) for y in pw)
            if Hset in seenH:
                continue
            seenH.add(Hset)
            A = np.zeros((3, 3), dtype=np.int64); A[:2, :2] = x[0]; A[2, 2] = x[1]
            hperm = G.perm_from_matrix(A)
            orbH, nO = L.closure_partition(G.v, [hperm])
            if not (a.minorbits <= nO <= a.maxorbits):
                continue
            seenK = set()
            for y in elems:
                ky = key(*y)
                if ky in Hset or cube[ky] not in Hset:
                    continue
                A2 = np.zeros((3, 3), dtype=np.int64); A2[:2, :2] = y[0]; A2[2, 2] = y[1]
                orbK, nK = L.closure_partition(G.v, [hperm, G.perm_from_matrix(A2)])
                kk = tuple(orbK.tolist())
                if kk in seenK:
                    continue
                seenK.add(kk)
                try:
                    sp = SpinG(p, q, [x], y)
                except AssertionError:
                    continue
                e = sp.estimate(rng=rng)
                tried += 1
                rec = dict(v=sp.v, H=fmt(x), Horder=len(pw), mu=fmt(y), OH=sp.stH.O, OK=sp.stK.O, classes=sp.stK.C,
                           pairs=len(sp.pairs), logE=None if e is None else round(e[0], 2),
                           logNA=None if e is None else round(e[1], 1), logNB=None if e is None else round(e[2], 1))
                print(json.dumps(rec), flush=True)
                if tried >= a.limit:
                    return
        return
    if a.cmd == 'check':
        # exact fibre test (spin_fibre.py, generalised): on every class whose K-orbit generates a proper subgroup U,
        # the attainable P_A(s) and T_B(s) must meet; both are sums over the cosets of U (bitset DP)
        sp = SpinG(p, q, [parse(x) for x in a.h.split('|')], parse(a.mu))
        G = sp.G
        Kp = sp.hp + [sp.mup]
        Kels = group_elems(Kp, G.v)
        dead = False
        for c, s in enumerate(sp.stK.reps):
            gens = {int(g[s]) for g in Kels}
            U, grow = {0}, True
            while grow:
                grow = False
                for u in list(U):
                    for g_ in gens:
                        w = int(G.index(G.coords[u] + G.coords[g_]))
                        if w not in U:
                            U.add(w)
                            grow = True
            if len(U) == G.v:
                continue
            sh = [s, int(sp.mup[s]), int(sp.mup[sp.mup[s]])]
            PA = fibre_values_group(G, Kp, U, [s], True)
            TB = fibre_values_group(G, sp.hp, U, sh, False)
            if PA is None or TB is None:
                print(f'class {c} (|U| = {len(U)}): too many free signs per coset, skipped')
                continue
            pa = set().union(*PA.values())
            tb = TB.get(sp.b, set()) | TB.get(-sp.b, set())
            m = sorted(x for x in pa if -x in tb)
            print(f'class {c} (|U| = {len(U)}): P_A in {sorted(pa)[:8]}; T_B from {min(tb) if tb else None}; '
                  f'matching {m[:5]}')
            dead |= not m
        print('RESULT', 'infeasible' if dead else 'passes')
        return
    hg = [parse(x) for x in a.h.split('|')]
    sp = SpinG(p, q, hg, parse(a.mu))
    stH, stK = sp.stH, sp.stK
    print(f'v={sp.v} OH={stH.O} OK={stK.O} classesK={stK.C} pairs={len(sp.pairs)} b={sp.b}', flush=True)
    M2 = np.rint(2 * sp.M).astype(np.int32)
    S2 = np.rint(2 * sp.SA).astype(np.int32)
    assert np.allclose(M2, 2 * sp.M) and np.allclose(S2, 2 * sp.SA)
    B0s = stH.sample(sp.b, 4096, np.random.default_rng(a.seed)).astype(np.int32)
    path = os.path.join(W.tmpdir(), f'spinG_{sp.v}_{a.seed}.bin')
    with open(path, 'wb') as f:
        np.array([stH.O, stK.C, stK.O, len(sp.pairs)], np.int32).tofile(f)
        stK.csize.astype(np.int32).tofile(f)
        stH.sizes.astype(np.int32).tofile(f)
        M2.tofile(f)
        S2.tofile(f)
        np.array(sp.pairs, np.int32).ravel().tofile(f)
        B0s[0].tofile(f)
        np.array([len(B0s)], np.int32).tofile(f)
        B0s.tofile(f)
    t0 = time.time()
    out = subprocess.run([W.bin(os.environ.get('SPIN_LS', 'spin_ls2')), path, str(a.restarts), str(a.steps), str(a.seed)],
                         stdout=subprocess.PIPE, text=True)
    os.remove(path)
    print(f'[{time.time() - t0:.0f}s]', flush=True)
    sol = [ln for ln in out.stdout.splitlines() if ln.startswith('SOL')]
    if not sol:
        return
    tok = sol[0].split()
    ia, ib = tok.index('A'), tok.index('B')
    A = np.array(tok[ia + 1:ib], dtype=float)
    B = np.array(tok[ib + 1:], dtype=float)
    seqs = sp.sequences(A, B)
    add, neg = sp.G.translate, sp.G.neg()
    # group-developed Goethals-Seidel over G
    diff = np.array([sp.G.index(sp.G.coords - sp.G.coords[g]) for g in range(sp.v)])   # diff[g, h] = h - g
    mats = [x[diff] for x in seqs]
    R = np.zeros((sp.v, sp.v), dtype=np.int64)
    R[np.arange(sp.v), neg] = 1
    A_, B_, C_, D_ = mats
    Hm = np.block([[A_, B_ @ R, C_ @ R, D_ @ R], [-B_ @ R, A_, D_.T @ R, -C_.T @ R],
                   [-C_ @ R, -D_.T @ R, A_, B_.T @ R], [-D_ @ R, C_.T @ R, -B_.T @ R, A_]]).astype(np.float64)
    n = 4 * sp.v
    had = np.array_equal(Hm @ Hm.T, n * np.eye(n))
    skew = np.array_equal(Hm + Hm.T, 2 * np.eye(n))
    print(f'FOUND: Hadamard={had} skew={skew}', flush=True)
    if had and skew:
        with open(W.hits(), 'a') as f:
            f.write(json.dumps(dict(n=sp.v, group=[p, p, q], H=a.h, spin_multiplier=a.mu, hadamard=True, skew=True,
                                    method=f'spin_group seed={a.seed} steps={a.steps}',
                                    seqs=[''.join('+' if x > 0 else '-' for x in s) for s in seqs])) + '\n')


if __name__ == '__main__':
    main()
