"""Certificate of a skew-Hadamard matrix of order 8v from a SOL line of tri_join (written for the port of rounds 37 to 39; not in the sources).
usage: python3 tri_cert.py v k g "SOL r=R A B C D"      (or just the four blocks)     v = 1 + k(k + 1)/2 prime, g the primitive root given to tri_join
The blocks of tri_join are quaternary exponent strings in coset order (position 0 = the point 0, position j + 1 = the coset g^j H, H the subgroup of order k generated by g^((v - 1)/k)); `../qdrv.shape` and `../certify.py` use the
orbits ordered by their least element, so the digits are permuted, `../certify.py` checks the quaternary and negacyclic conditions and writes ../out/cert_<8v>.json, and the SHA-256 of the matrix is added with the builder of ../../../verify/verify.py
(as `../plugcert.py` does for the plug-in).  Example: python3 tri_cert.py 67 11 2 "SOL r=0 0130021 0003122 0001223 0032210"  (a control, order 536)."""
import sys, os, json, hashlib, subprocess
HERE = os.path.dirname(os.path.abspath(__file__)); NEG = os.path.abspath(os.path.join(HERE, '..'))
sys.path.insert(0, NEG); sys.path.insert(0, os.path.join(HERE, '..', '..', '..', 'verify'))
from qdrv import shape
import verify as V
v, k, g = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3])
toks = [t for t in sys.argv[4].split() if t != 'SOL' and not t.startswith('r=')]
assert len(toks) == 4, 'four blocks expected'
e = (v - 1) // k
assert v - 1 == e * k and pow(g, e * k, v) == 1
H = [pow(g, e * i, v) for i in range(k)]
orb = [0] * v
for j in range(e):
    gj = pow(g, j, v)
    for x in H: orb[gj * x % v] = j + 1
assert all(len(t) == e + 1 for t in toks), 'a block has e + 1 = %d digits' % (e + 1)
gens = [pow(g, e, v)]
d = shape(v, gens)
strs = [''.join(t[orb[r]] for r in d['reps']) for t in toks]
print('multiplier generator', gens, 'orbits', d['n'])
print('orbit exponents (qdrv order):', ' '.join(strs))
r = subprocess.run([sys.executable, os.path.join(NEG, 'certify.py'), str(v), json.dumps(gens), ' '.join(strs)], cwd=NEG, capture_output=True, text=True)
print(r.stdout.strip())
if r.returncode: sys.exit(r.stderr)
path = os.path.join(NEG, 'out', f'cert_{8 * v}.json')
cert = json.load(open(path))
Hm, _ = V.BUILDERS[cert['construction']](cert)
h = hashlib.sha256()
for ch in V.csv_chunks(Hm): h.update(ch)
cert['sha256'] = h.hexdigest()
json.dump(cert, open(path, 'w'))
print('sha256', cert['sha256'], '->', path)
