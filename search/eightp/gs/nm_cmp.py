from gs_samp import make_shape, parse_allocs
from gl1 import L1
from prod_5912 import SHAPE, TOKENS, LA, LC, level1
from nm_5912 import CHUNK


class Lat:
    """integer lattice: incremental echelon basis (python ints), B[i] has its pivot in column i"""
    def __init__(self, d): self.d = d; self.B = [None] * d
    def add(self, v):
        v = [int(x) for x in v]
        for i in range(self.d):
            if v[i] == 0: continue
            b = self.B[i]
            if b is None:
                self.B[i] = v if v[i] > 0 else [-x for x in v]; return
            while v[i] != 0:
                qd = b[i] // v[i]; b = [x - qd * y for x, y in zip(b, v)]; b, v = v, b
            self.B[i] = b if b[i] > 0 else [-x for x in b]
    def det(self):
        p = 1
        for i in range(self.d):
            if self.B[i] is None: return 0
            p *= self.B[i][i]
        return p


class Fibres:
    """level-2 fibres of the instances of the shape sh (numpy version of gl2.c: row-sum filter on the t-sums, then the 14 keys of every t-sign vector)"""
    def __init__(self, sh):
        self.sh = sh; self.n = sh.N; self.q = sh.r; self.eps = sh.eps; self.T = sh.T2
        kI = [int(k) for k in sh.repsPM if k != 0]; kQ = [int(k) for k in sh.repsQ]
        self.ipp = np.array([sh.shift[k] for k in kI]); self.qpp = np.array([sh.shift[k] for k in kQ]); self.qmm = np.array([sh.shneg[k] for k in kQ])
        K = sh.kCD; self.pos = [np.array(K.pos[i], int) for i in range(K.nu)]; self.sig = [np.array([int(K.sig[p]) for p in K.pos[i]]) for i in range(K.nu)]
        self.nu = K.nu; self.nI = len(kI); self.nQ = len(kQ)

    def tau_sets(self, S, E):
        """per block: the t-variable orbits (defect-free ones), their weights, and the allowed t-sums of the exact row-sum filter"""
        vars_, wj = [], []
        for b in range(4):
            v = [o for o in range(self.nu) if E[b][int(self.pos[o][0])] == 0]
            vars_.append(v); wj.append([int(self.sig[o].sum()) for o in v])
        sgm = [int(S[b].sum()) for b in range(4)]
        tset = []
        for b in range(4):
            cur = {0}
            for w in wj[b]: cur = {x + w for x in cur} | {x - w for x in cur}
            tset.append(sorted(cur))
        rem0 = self.T - sum(x * x for x in sgm); q = self.q
        allow = [set() for _ in range(4)]
        if rem0 >= 0:
            for ta in tset[0]:
                for tb in tset[1]:
                    r1 = rem0 - q * (ta * ta + tb * tb)
                    if r1 < 0: continue
                    for tc in tset[2]:
                        r2 = r1 - q * tc * tc
                        if r2 < 0: continue
                        for td in tset[3]:
                            if q * td * td == r2: allow[0].add(ta); allow[1].add(tb); allow[2].add(tc); allow[3].add(td)
        return vars_, wj, allow

    def fibre(self, s, e, v, w, allowset, fixfirst):
        """keys (m x 14) of all t-sign vectors with allowed t-sum (the last variable fixed if fixfirst: the gauge t -> -t, as in gl2.c)"""
        nv = len(v); nb = nv - (1 if fixfirst and nv > 0 else 0)
        idx = np.arange(1 << nb, dtype=np.int64)
        sg = 1 - 2 * ((idx[:, None] >> np.arange(nb)[None, :]) & 1)
        if fixfirst and nv > 0: sg = np.concatenate([sg, np.ones((len(idx), 1), int)], 1)
        sg = sg[np.isin(sg @ np.array(w), list(allowset))] if len(allowset) else sg[:0]
        t = np.zeros((len(sg), self.n), np.int64)
        for j, o in enumerate(v): t[:, self.pos[o]] = sg[:, j:j + 1] * self.sig[o][None, :]
        keys = np.zeros((len(sg), self.nI + self.nQ), np.int64)
        for a in range(self.nI): keys[:, a] = int((s * s[self.ipp[a]]).sum()) + self.q * (t * t[:, self.ipp[a]]).sum(1)
        for j in range(self.nQ): keys[:, self.nI + j] = t @ (s[self.qpp[j]] + self.eps * s[self.qmm[j]])
        return keys

    def instance(self, S, E):
        """the four fibres of an instance (None if one is empty)"""
        v, w, allow = self.tau_sets(S, E); nv = [len(x) for x in v]; fixk = 2
        for b in range(4):
            if nv[b] > nv[fixk]: fixk = b
        fibs = [self.fibre(S[b], E[b], v[b], w[b], allow[b], b == fixk) for b in range(4)]
        return None if min(len(k) for k in fibs) == 0 else fibs


def lattice_of_diffs(fibs, maxrows=500):
    """lattice generated by the differences inside each fibre (at most maxrows rows of each)"""
    L = Lat(fibs[0].shape[1]); rng = np.random.default_rng(0)
    for k in fibs:
        idx = np.arange(len(k)) if len(k) <= maxrows else rng.choice(len(k), maxrows, replace=False)
        for j in idx[1:]: L.add(k[j] - k[idx[0]])
    return L


def predict(fibs, L, cols):
    """log10 of the predicted number of quadruples with sum 0 on the coordinates cols"""
    Lp = Lat(len(cols))
    for b in L.B:
        if b is not None: Lp.add([b[j] for j in cols])
    if Lp.det() == 0: return -math.inf
    mu = sum(k.mean(0) for k in fibs)[cols]; C = sum(np.cov(k.T, bias=True) for k in fibs)[np.ix_(cols, cols)]
    w, U = np.linalg.eigh(C); x = U.T @ (-mu)
    logd = -0.5 * float((x ** 2 / w).sum()) - 0.5 * float(np.log(2 * math.pi * w).sum())
    return (logd + sum(math.log(len(k)) for k in fibs)) / math.log(10) + math.log10(Lp.det())


def main():
    outp = sys.argv[1]; nsamp = int(sys.argv[2]); maxchunks = int(sys.argv[3]) if len(sys.argv) > 3 else 10 ** 9
    sh = make_shape(*SHAPE); l1 = L1(sh); allocs = parse_allocs(TOKENS, LA, LC); fb = Fibres(sh); nk = fb.nI + fb.nQ; pcache = {}
    chunks = collections.OrderedDict()
    for line in open(outp + '.jsonl'):
        r = json.loads(line); chunks.setdefault((r['seed'], r['rd'], r['i'] // CHUNK), []).append(r)
    obs, prd = collections.defaultdict(float), collections.defaultdict(float); cur = None; t0 = time.time()
    for nch, ((seed, rd, ci), rs) in enumerate(chunks.items()):
        if nch >= maxchunks: break
        if len(rs) < CHUNK: continue
        if cur != (seed, rd):                                     # regenerate the instances of the round (as nm_5912.py)
            al, cnt, S, E = level1(sh, l1, allocs, pcache, np.random.default_rng([seed, rd]), rd, rs[0]['maxinst']); cur = (seed, rd)
            S, E = S.astype(np.int64), E.astype(np.int64)
        om = rs[0]['omit']; inc0 = [j for j in range(nk) if j not in om]; subsets = [Z for k in range(len(om) + 1) for Z in itertools.combinations(range(len(om)), k)]
        for r in rs:
            assert (r['nm'] or 0) // 2 == len(r['NM']), 'residual list cut at GL2_NMCAP'
            for res in r['NM']:
                for Z in subsets:
                    if all(res[z] == 0 for z in Z): obs[len(Z)] += 1
        idxs = [r['i'] for r in rs][::max(1, len(rs) // nsamp)][:nsamp]; acc = collections.defaultdict(float)
        for i in idxs:
            fibs = fb.instance(S[i], E[i])
            if fibs is None: continue
            L = lattice_of_diffs(fibs)
            for Z in subsets: acc[len(Z)] += 10 ** predict(fibs, L, sorted(inc0 + [om[z] for z in Z]))
        for k in acc: prd[k] += acc[k] / len(idxs) * len(rs)
        if (nch + 1) % 5 == 0: print(f'[{time.time()-t0:.0f}s] chunks {nch + 1}', {k: (round(obs[k]), round(prd[k], 1)) for k in sorted(obs)}, flush=True)
    print('FINAL by number of satisfied constraints', {nk - len(om) + k: (round(obs[k]), round(prd[k], 1), round(obs[k] / prd[k], 3) if prd[k] else None) for k in sorted(prd)})
    json.dump(dict(obs=dict(obs), prd=dict(prd)), open(outp + '.cmp.json', 'w'))


if __name__ == '__main__': main()
