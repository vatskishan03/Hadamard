"""Coverage of the Table 5 entries v(m), m >= 4 (Cati and Pasechnik, t5.json) by the multiplier-shape sweeps of sweep.py (NOTES.md section 88).
usage: python3 coverage.py
Of the entries with m >= 4: 463 is not census-undecided (its matrix of order 4*463 is in skew/), some have a matrix of order 4v in skew/, 191 and 277 are
the hits of qskew; each of the remaining ones is sorted by the smallest number of orbits n of an odd-order multiplier group H <= Z_v* (generated by one or
two elements, enum_shapes.shapes): n <= 13 (swept exhaustively, all empty except the two hits), n = 15 .. 21 only (beyond the four-list join), or no shape
with n <= 21.  The counts of the sweep (the repository without skew/1892, v = 473, which was added since): 172 entries, 463, 29 with a matrix of order 4v,
142 others, 140 after the two hits (473 and 933 are settled by now), 77 / 18 / 45.  The lines marked (now) take skew/ as it is."""
import os, sys
from enum_shapes import T5, shapes, HERE
SINCE = {473}      # v whose matrix of order 4v (skew/1892) was added after the sweep
skewdirs = {int(d) for d in os.listdir(os.path.join(HERE, '..', '..', 'skew')) if d.isdigit()}
cen = [int(l) for l in open(os.path.join(HERE, '..', 'data', 'skew_census_undecided.txt')) if l.strip() and not l.startswith('#')]
ge4 = sorted(v for v, m in T5.items() if m >= 4)
notcen = [v for v in ge4 if v not in set(cen)]
have4v = [v for v in ge4 if 4 * v in skewdirs and v not in notcen and v not in SINCE]
others = [v for v in ge4 if v not in notcen and v not in have4v]
hits = [v for v in (191, 277) if v in others]
rest = [v for v in others if v not in hits]
print('entries with m >= 4:', len(ge4))
print('not census-undecided:', notcen)
print('with a matrix of order 4v in skew/ (at the time of the sweep):', len(have4v))
print('others:', len(others), ' hits among them:', hits, ' remaining:', len(rest))
c13 = []; c21 = []; c0 = []
for v in rest:
    if shapes(v, 13): c13.append(v)
    elif shapes(v, 21): c21.append(v)
    else: c0.append(v)
print('a multiplier shape with at most 13 orbits:', len(c13))
print('only shapes with 15 to 21 orbits:', len(c21), c21)
print('no shape with at most 21 orbits:', len(c0), c0)
print('(now) matrices of order 4v in skew/ among the entries:', len([v for v in ge4 if 4 * v in skewdirs]), ' 473 and 933 in the remaining:', 473 in rest, 933 in rest)
