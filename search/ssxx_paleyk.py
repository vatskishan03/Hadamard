#!/usr/bin/env python3
"""Paley-product structures for complex Hadamard matrices of order 2N with an extra multiplier group on Z_m.

The structure of search/ssxx_paley.py (N = m q, H_0 = {h : h = 1 (mod m), h a square in GF(q)}, every block
u (x) delta + w (x) J + z (x) chi) with H = <H_0, K> for an odd-order subgroup K of Z_m^* acting on Z_m alone: u, w and
z are constant on the K-orbits of Z_m. With q prime the multiplier group of Z_N is generated by the elements
h = k (mod m), h = 1 (mod q) for the generators k of K, and the generator of H_0.

Skeletons are now unions of K-orbits (of <K, -1>-orbits for A and B), so for large m the lists are small enough to
search every skeleton exactly: the w-orbit choices with the counting identity (q + 1) N_w - 4 N_- = 4m are listed by a
product over blocks, stage 1 joins the +-1 orbit values of y on sum PAF_y = 0, stage 2 joins the z orbit values on
(II) and (III) (search/ssxx_paley.py), and every hit is lifted and checked. Symmetry reduction: block signs only, so
the counts below are counts of skeletons and of stage-1 solutions with signs normalised, not orbits.

    python3 search/ssxx_paleyk.py N q k [k2] [--log FILE] [--all]
"""
import argparse, itertools, json, sys, time
import numpy as np
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ssxx_paley as SP


def closure(gens, m):
    S = {1}
    while True:
        T = S | {s * g % m for s in S for g in gens}
        if T == S:
            return sorted(S)
        S = T


class PaleyK:
    def __init__(self, N, q, kgens):
        self.P = SP.Paley(N, q)
        P = self.P
        m, self.q, self.eps = P.m, q, P.eps
        self.m, self.h = m, P.h
        self.K = closure(kgens, m)
        assert len(self.K) % 2 == 1, "K must have odd order"
        oid = -np.ones(m, np.int64); orbs = []
        for a in range(m):
            if oid[a] < 0:
                O = sorted({a * k % m for k in self.K})
                for b in O:
                    oid[b] = len(orbs)
                orbs.append(O)
        self.orbs, self.oid = orbs, oid
        self.neg = [int(oid[(-O[0]) % m]) for O in orbs]          # orbit of -O
        # <K, -1>-classes for the symmetric blocks: pairs {O, -O} (or a single self-negative orbit)
        self.sclasses = []
        seen = set()
        for i in range(len(orbs)):
            if i in seen:
                continue
            j = self.neg[i]
            seen |= {i, j}
            self.sclasses.append((i,) if i == j else (i, j))
        # full multiplier group generators of Z_N: k (mod m), 1 (mod q), and P.gen
        Nn = P.N
        self.gens = [P.gen] + [next(x for x in range(Nn) if x % m == k % m and x % q == 1) for k in kgens]

    # ---------- skeleton enumeration ----------
    def block_options(self, sym, maxw):
        """w-sets of one block as tuples of orbit indices with their position count; for eps = -1 the
        self-negative orbits of A and B (z = -z there) are w-orbits."""
        out = []
        if sym:
            forced = [c for c in self.sclasses if len(c) == 1 and self.eps == -1]
            free = [c for c in self.sclasses if c not in forced]
            base = sum(len(self.orbs[i]) for c in forced for i in c)
            for r in range(len(free) + 1):
                for sub in itertools.combinations(free, r):
                    n = base + sum(len(self.orbs[i]) for c in sub for i in c)
                    if n <= maxw:
                        out.append((tuple(sorted(forced + list(sub))), n))
        else:
            for r in range(len(self.orbs) + 1):
                for sub in itertools.combinations(range(len(self.orbs)), r):
                    n = sum(len(self.orbs[i]) for i in sub)
                    if n <= maxw:
                        out.append((tuple(sub), n))
        return out

    def skeletons(self, nw, nm):
        """all (w-classes per block, values per class) with N_w positions, N_- of them of magnitude q - 2; the sign
        of each block's first w-class is +"""
        q = self.q
        sym_opts = self.block_options(True, nw)
        free_opts = self.block_options(False, nw)
        by_n = {}
        for o in free_opts:
            by_n.setdefault(o[1], []).append(o[0])
        for a in sym_opts:
            for b in sym_opts:
                rest = nw - a[1] - b[1]
                if rest < 0:
                    continue
                for nc, Cl in by_n.items():
                    Dl = by_n.get(rest - nc, [])
                    for c in Cl:
                        for d in Dl:
                            sets = [a[0], b[0], c, d]
                            # classes (sym) or orbits (free) per block, with their position counts
                            units = []
                            for k, S in enumerate(sets):
                                for cl in S:
                                    idx = cl if k < 2 else (cl,)
                                    units.append((k, idx, sum(len(self.orbs[i]) for i in idx)))
                            # magnitudes with weighted minus count nm, then signs (first unit of each block +)
                            for mags in itertools.product((q, q - 2), repeat=len(units)):
                                if sum(u[2] for u, mg in zip(units, mags) if mg == q - 2) != nm:
                                    continue
                                firsts = {}
                                free_sign = []
                                for t, u in enumerate(units):
                                    if u[0] in firsts:
                                        free_sign.append(t)
                                    else:
                                        firsts[u[0]] = t
                                for sg in itertools.product((1, -1), repeat=len(free_sign)):
                                    signs = [1] * len(units)
                                    for t, s_ in zip(free_sign, sg):
                                        signs[t] = s_
                                    yield [(u[0], u[1], mg * s_) for u, mg, s_ in zip(units, mags, signs)]

    # ---------- lists ----------
    def ylist(self, k, wunits, sym):
        m = self.m
        Y0 = np.zeros(m, np.int8)
        used = set()
        for kk, idx, val in wunits:
            if kk != k:
                continue
            for i in idx:
                Y0[self.orbs[i]] = val; used.add(i)
        if sym:
            free = [c for c in self.sclasses if not set(c) & used]
        else:
            free = [(i,) for i in range(len(self.orbs)) if i not in used]
        S = SP.allpm(len(free))
        if not used:                          # block negation: fix the first free value
            S = S[S[:, 0] == 1] if len(free) else S
        Y = np.repeat(Y0[None, :], len(S), axis=0)
        for j, c in enumerate(free):
            for i in c:
                Y[:, self.orbs[i]] = S[:, j:j + 1]
        return Y

    def zlist(self, y, sym, fix_first=False):
        m, eps = self.m, self.eps
        zorbs = [i for i in range(len(self.orbs)) if abs(int(y[self.orbs[i][0]])) == 1]
        if sym:
            free = []
            for c in self.sclasses:
                if c[0] not in zorbs:
                    continue
                if len(c) == 1 and eps == -1:
                    raise ValueError("z on a self-negative orbit of a symmetric block")
                free.append(c)
        else:
            free = [(i,) for i in zorbs]
        S = SP.allpm(len(free))
        if fix_first and len(free):
            S = S[S[:, 0] == 1]
        Z = np.zeros((len(S), m), np.int8)
        for j, c in enumerate(free):
            Z[:, self.orbs[c[0]]] = S[:, j:j + 1]
            if len(c) == 2:
                Z[:, self.orbs[c[1]]] = eps * S[:, j:j + 1]
        return Z

    def stage2(self, ys, K=1, threads=None):
        P = self.P
        h, q, eps = self.h, self.q, self.eps
        U, Wv = zip(*[P.uw(y) for y in ys])
        R = np.zeros(h, np.int64)
        for u, w in zip(U, Wv):
            for s in range(1, h + 1):
                R[s - 1] += SP.corr(u, w, s) + SP.corr(w, u, s) + q * SP.corr(w, w, s)
        S3 = list(range(1, h + 1)) if eps == -1 else list(range(0, h + 1))
        sizes = [int(np.sum(np.abs(y) == 1)) for y in ys]
        big = 2 + int(np.argmax(sizes[2:]))
        keys, Zs = [], []
        for k in range(4):
            Z = self.zlist(ys[k], k < 2, fix_first=(k == big))
            Zi = Z.astype(np.int64)
            Pz = SP.pafs(Zi, h)
            Cc = np.stack([eps * SP.corr(U[k][None, :], Zi, s) + SP.corr(Zi, U[k][None, :], s) for s in S3], axis=1)
            keys.append(np.concatenate([Pz, Cc], axis=1).astype(np.int16)); Zs.append(Z)
        tgt = np.concatenate([R, np.zeros(len(S3), np.int64)]).astype(np.int16)
        total, sols = SP.join(keys, tgt, K, threads)
        return total, [[Zs[k][ids[k]] for k in range(4)] for ids in sols], U, Wv


def run(N, q, kgens, log=None, all_=False, threads=None):
    PK = PaleyK(N, q, kgens)
    P = PK.P
    m, h = PK.m, PK.h
    t0 = time.time()
    adm = [(a, b) for a, b in SP.admissible(m, q) if P.eps == 1 or a >= 2]
    print(f"N={N} = {m} x {q}, K = {PK.K} on Z_{m} ({len(PK.orbs)} orbits, {len(PK.sclasses)} classes), "
          f"generators {PK.gens}; admissible (N_w, N_-): {adm}", flush=True)
    nsk = n1 = n2 = 0
    found = []
    for nw, nm in adm:
        for sk in PK.skeletons(nw, nm):
            nsk += 1
            lists = [PK.ylist(k, sk, k < 2) for k in range(4)]
            keys = [SP.pafs(Y, h).astype(np.int16) for Y in lists]
            tot, sols = SP.join(keys, np.zeros(h, np.int16), 10 ** 6, threads)
            n1 += tot
            for ids in sols:
                ys = [lists[k][ids[k]].astype(np.int64) for k in range(4)]
                tot2, zs, U, Wv = PK.stage2(ys, K=1, threads=threads)
                n2 += tot2
                if tot2:
                    seqs = [P.lift(U[k], Wv[k], zs[0][k].astype(np.int64)) for k in range(4)]
                    rows = SP.record_hit(P, seqs, None)
                    rec_seqs = ["".join('+' if v > 0 else '-' for v in x) for x in seqs]
                    print(f"  HIT N={N}: verified complex Hadamard matrix of order {2 * N}; rows {rows}", flush=True)
                    if log:
                        with open(log, 'a') as f:
                            f.write(json.dumps({"N": N, "gens": PK.gens, "subgroup_order": len(PK.K) * (q - 1) // 2,
                                                "paley": [m, q], "K": PK.K, "rowsums": rows,
                                                "sequences": rec_seqs}) + "\n")
                    found.append(seqs)
                    if not all_:
                        print(f"RESULT N={N} K={kgens}: FOUND [{time.time() - t0:.0f}s]", flush=True)
                        return found
    print(f"RESULT N={N} q={q} K={kgens}: {'FOUND' if found else 'no solution (exhaustive)'}; skeletons {nsk}, "
          f"stage-1 solutions {n1}, stage-2 solutions {n2} [{time.time() - t0:.0f}s]", flush=True)
    return found


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("N", type=int); ap.add_argument("q", type=int); ap.add_argument("k", type=int, nargs="+")
    ap.add_argument("--log"); ap.add_argument("--all", action="store_true"); ap.add_argument("--threads", type=int)
    a = ap.parse_args()
    run(a.N, a.q, a.k, a.log, a.all, a.threads)


if __name__ == "__main__":
    main()
