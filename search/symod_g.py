r"""Symmetric OD(4t; mu, 4t - mu) in Balonin form over a finite abelian group G of order t (search/symod_engine.py
has the conditions; search/gsgroup.py the group conventions), invariant under an automorphism group H of odd order.

Same pipeline as search/symod_join.py with gsgroup.py tables and gdfs.c lists:
1. x templates (A symmetric, B scaled by 2, D) of weight mu with PAF sum mu delta, found by join4x (at most --bk),
   reduced modulo the automorphisms generated by H and --norm (they must normalise H), the sign of each block, and
   the translations (by H-fixed elements) and negation of B and of D.
2. Row-sum screen (rho_A^2 + 2 rho_B^2 + rho_D^2 = 4t - mu, orthogonal to the x row sums).
3. y lists (cached) and join4x on (A, 2B, D, {0}); each solution is checked as a symmetric OD.

Usage: python3 search/symod_g.py GROUP "HGENS" mu [--norm "GENS"] [--xsub d] [--bk N] [--k K] [--first] [--dry]
  e.g. python3 search/symod_g.py 5^2 "1,1;0,1" 5 --norm "2,0;0,1|0,1;1,0"
"""
import argparse
import os
import struct
import subprocess
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsgroup import Group, Orbits, read_list, group_matrix, reflection  # noqa: E402
import workdir  # noqa: E402

WORK = workdir.tmpdir()


def balonin_pair(G, codes):
    R = reflection(G)
    out = []
    for var in (1, 2):
        A, B, D = (group_matrix(G, np.where(np.abs(np.array(c)) == var, np.sign(np.array(c)), 0)) for c in codes)
        BR, RB, DR, RD = B @ R, R @ B, D @ R, R @ D
        out.append(np.block([[-A, BR, BR, DR], [BR, RD, A, -RB], [BR, A, -RD, RB], [DR, -RB, RB, A]]))
    return out


def check_design(G, codes, mu):
    P, N = balonin_pair(G, codes)
    n = 4 * G.t
    return bool(np.array_equal(P, P.T) and np.array_equal(N, N.T) and np.all(np.abs(P) + np.abs(N) == 1)
                and np.array_equal(P @ P, mu * np.eye(n, dtype=np.int64))
                and np.array_equal(N @ N, (n - mu) * np.eye(n, dtype=np.int64)) and not np.any(P @ N + N @ P))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('group')
    ap.add_argument('hgens')
    ap.add_argument('mu', type=int)
    ap.add_argument('--norm', default='')
    ap.add_argument('--hb', default='', help='generators of a larger group H_b >= H for the x/b part')
    ap.add_argument('--xsub', type=int, default=0, help='x part on the elements killed by this integer')
    ap.add_argument('--bk', type=int, default=200000)
    ap.add_argument('--k', type=int, default=2)
    ap.add_argument('--first', action='store_true')
    ap.add_argument('--dry', action='store_true')
    ap.add_argument('--maxtpl', type=int, default=10 ** 7)
    ap.add_argument('--gdfs', default=None,
                    help='binary built from gdfs.c (default: compiled into $HADAMARD_WORK/bin on first use)')
    ap.add_argument('--join4x', default=None,
                    help='binary built from join4x.c (default: compiled into $HADAMARD_WORK/bin on first use)')
    a = ap.parse_args()
    os.makedirs(WORK, exist_ok=True)
    G = Group(a.group)
    t, mu = G.t, a.mu
    ident = '/'.join(('1' if k == 1 else ';'.join(','.join('1' if i == j else '0' for j in range(k)) for i in range(k)))
                     for n, k in G.comps)
    hg = [x for x in a.hgens.split('|') if x and x != '1'] or [ident]
    H = G.closure([G.aut_perm(x) for x in hg])
    O = Orbits(G, H)
    if a.hb:
        Hb = G.closure([G.aut_perm(x) for x in hg] + [G.aut_perm(x) for x in a.hb.split('|') if x])
        Ob = Orbits(G, Hb)
        print(f'|H_b|={len(Hb)} H_b-orbits {Ob.no} reps {Ob.npr}', file=sys.stderr)
    else:
        Ob = O
    N = G.closure([G.aut_perm(x) for x in hg] + [G.aut_perm(x) for x in a.norm.split('|') if x])
    print(f'G={a.group} t={t} |H|={len(H)} H-orbits {O.no} reps {O.npr} |N|={len(N)} mu={mu}', file=sys.stderr)
    # N acts on H-orbits (it must normalise H)
    nperms, seenp = [], set()
    for p in N:
        img = O.orb[p[[o[0] for o in O.obs]]]
        for i, o in enumerate(O.obs):
            if len({int(O.orb[p[x]]) for x in o}) != 1:
                sys.exit('--norm does not normalise H')
        k = tuple(int(x) for x in img)
        if k not in seenp:
            seenp.add(k)
            nperms.append(np.array(k))
    fixed = [c for c in range(t) if all(int(h[c]) == c for h in H)]
    bd_perms = []
    for c in fixed:
        for sgn in (1, -1):
            bd_perms.append(np.array([int(O.orb[G.add[o[0] if sgn == 1 else G.neg[o[0]], c]]) for o in O.obs]))
    within = None
    if a.xsub:
        kill = np.all((a.xsub * G.elts) % G.mods_a == 0, axis=1)
        within = [bool(all(kill[x] for x in o)) for o in Ob.obs]
    tag = f'symg_{a.group.replace("^", "p")}_{mu}_{os.getpid()}'

    # 1. templates
    cands = []
    for blk, btype, wmax, scale in (('A', 'sym', mu, 1), ('B', 'plain', mu // 2, 2), ('D', 'plain', mu, 1)):
        var = Ob.variables(btype, None, within)
        tp, lp = os.path.join(WORK, f'{tag}_{blk}.tab'), os.path.join(WORK, f'{tag}_{blk}.lst')
        Ob.write_tables(tp, var, 1, wmax, scale)
        r = subprocess.run([(a.gdfs or workdir.bin('gdfs')), tp, lp], capture_output=True, text=True)
        if r.returncode:
            sys.exit(r.stderr)
        n, D, vec, masks = read_list(lp)
        os.remove(tp); os.remove(lp)
        cands.append((var, vec, masks.reshape(n, 2)))
        print(f'x candidates {blk}: {len(var)} variables, {n}', file=sys.stderr)
    D = Ob.npr + 1
    fb = os.path.join(WORK, f'{tag}_tpl.bin')
    with open(fb, 'wb') as f:
        f.write(struct.pack('5i', len(cands[0][1]), len(cands[1][1]), len(cands[2][1]), 1, D))
        f.write(np.array([0] * Ob.npr + [mu], dtype=np.int16).tobytes())
        for c in cands:
            f.write(np.ascontiguousarray(c[1]).tobytes())
        f.write(b'\0' * (2 * D))
    j = subprocess.run([(a.join4x or workdir.bin('join4x')), fb, str(a.bk), '8000000', '1'], capture_output=True, text=True)
    os.remove(fb)
    sols = np.array([list(map(int, ln.split()[1:5])) for ln in j.stdout.splitlines() if ln.startswith('SOL')],
                    dtype=np.int64).reshape(-1, 4)
    tot = [ln for ln in j.stdout.splitlines() if ln.startswith('TOTAL')]
    print(f'x triples from join4x: {len(sols)} ({tot[0] if tot else "?"})', file=sys.stderr)

    def to_orbits(b, idx):
        var, _, masks = cands[b]
        V = np.zeros((len(idx), O.no), dtype=np.int64)
        pl, mi = masks[idx, 0], masks[idx, 1]
        for jv, v in enumerate(var):
            bp = ((pl >> np.uint64(jv)) & np.uint64(1)).astype(np.int64)
            bm = ((mi >> np.uint64(jv)) & np.uint64(1)).astype(np.int64)
            for o, c in v:
                for x in Ob.obs[o]:
                    V[:, O.orb[x]] = c * (bp - bm)
        return V

    def lexless(X, Y):
        """row-wise X < Y lexicographically"""
        d = X != Y
        idx = np.argmax(d, axis=1)
        r = np.arange(len(X))
        return d.any(axis=1) & (X[r, idx] < Y[r, idx])

    def lexmin(X, Y):
        m = lexless(Y, X)
        Z = X.copy()
        Z[m] = Y[m]
        return Z

    def canon_block(V, sym):
        perms = [np.arange(O.no)] if sym else bd_perms
        best = None
        for pm in perms:
            W = np.zeros_like(V)
            W[:, pm] = V
            for sg in (1, -1):
                best = sg * W if best is None else lexmin(best, sg * W)
        return best

    X3 = [to_orbits(b, sols[:, b]) for b in range(3)]
    keys = None
    for pm in nperms:
        img = []
        for V, sym in zip(X3, (True, False, False)):
            W = np.zeros_like(V)
            W[:, pm] = V
            img.append(canon_block(W, sym))
        K = np.concatenate(img, axis=1)
        keys = K if keys is None else lexmin(keys, K)
    uniq = np.unique(keys, axis=0) if keys is not None and len(keys) else np.zeros((0, 3 * O.no), dtype=np.int64)

    def decode_vec(v):
        s = np.zeros(t, dtype=np.int64)
        for i, x in enumerate(v):
            if x:
                s[O.obs[i]] = x
        return s

    templates = [[decode_vec(row[b * O.no:(b + 1) * O.no]) for b in range(3)] for row in uniq]
    print(f'{len(templates)} x templates up to equivalence', file=sys.stderr)

    # 2. row-sum screen
    def free_sizes(U, btype):
        return [int(sum(O.size[o] for o, c in v)) for v in O.variables(btype, U)]

    def signed_sums(sizes):
        s = {0}
        for z in sizes:
            s = {x + z for x in s} | {x - z for x in s}
        return s

    work = []
    for tpl in templates:
        r = [int(x.sum()) for x in tpl]
        att = [signed_sums(free_sizes(tpl[0], 'sym')), signed_sums(free_sizes(tpl[1], 'plain')),
               signed_sums(free_sizes(tpl[2], 'plain'))]
        rhos = []
        for ra in att[0]:
            for rb in att[1]:
                rem = 4 * t - mu - ra * ra - 2 * rb * rb
                if rem < 0:
                    continue
                rd = int(round(rem ** 0.5))
                for rdd in {rd, -rd}:
                    if rdd * rdd == rem and rdd in att[2] and r[0] * ra + 2 * r[1] * rb + r[2] * rdd == 0:
                        rhos.append((ra, rb, rdd))
        flips = [i for i in range(3) if not tpl[i].any()]

        def orbit_rho(rv):
            out = set()
            for gsg in (1, -1):
                for mask in range(1 << len(flips)):
                    w = [gsg * x for x in rv]
                    for bit, i in enumerate(flips):
                        if mask >> bit & 1:
                            w[i] = -w[i]
                    out.add(tuple(w))
            return min(out)
        rhos = sorted(set(orbit_rho(rv) for rv in rhos))
        if rhos:
            work.append((tpl, rhos))
    print(f'{len(work)} templates pass the row-sum screen', file=sys.stderr)
    if a.dry:
        for tpl, rhos in work[:20]:
            print('TPL', [[(int(g), int(v)) for g, v in enumerate(s) if v] for s in tpl], rhos[:4], len(rhos))
        return

    # 3. y lists and joins
    cache = {}

    def get_list(U, btype, rs):
        key = (btype, U.tobytes(), rs)
        if key in cache:
            return cache[key]
        var = O.variables(btype, U)
        tp, lp = os.path.join(WORK, f'{tag}_y.tab'), os.path.join(WORK, f'{tag}_y.lst')
        O.write_tables(tp, var, 0, rs, 1, U)
        r = subprocess.run([(a.gdfs or workdir.bin('gdfs')), tp, lp], capture_output=True, text=True)
        if r.returncode:
            sys.exit(r.stderr)
        n, D, vec, masks = read_list(lp)
        os.remove(tp); os.remove(lp)
        cache[key] = (n, D, vec, masks, var)
        return cache[key]

    total = 0
    for ti, (tpl, rhos) in enumerate(work[:a.maxtpl]):
        nsol = 0
        for rho in rhos:
            L = [get_list(tpl[0], 'sym', rho[0]), get_list(tpl[1], 'plain', rho[1]), get_list(tpl[2], 'plain', rho[2])]
            if any(x[0] == 0 for x in L):
                continue
            D = L[0][1]
            fn = os.path.join(WORK, f'{tag}_join.bin')
            with open(fn, 'wb') as f:
                f.write(struct.pack('5i', L[0][0], L[1][0], L[2][0], 1, D))
                f.write(b'\0' * (2 * D))
                f.write(np.ascontiguousarray(L[0][2]).tobytes())
                f.write((2 * L[1][2].astype(np.int32)).astype(np.int16).tobytes())
                f.write(np.ascontiguousarray(L[2][2]).tobytes())
                f.write(b'\0' * (2 * D))
            jj = subprocess.run([(a.join4x or workdir.bin('join4x')), fn, str(a.k)], capture_output=True, text=True)
            os.remove(fn)
            ss = [list(map(int, ln.split()[1:5])) for ln in jj.stdout.splitlines() if ln.startswith('SOL')]
            tt = [ln for ln in jj.stdout.splitlines() if ln.startswith('TOTAL')]
            print(f'template {ti} rho {rho}: lists {[x[0] for x in L]} {tt[0] if tt else "?"}', file=sys.stderr)
            for s in ss:
                codes = []
                for U, lst, idx in zip(tpl, L, s[:3]):
                    m = int(lst[3][idx])
                    vals = [-1 if m >> jv & 1 else 1 for jv in range(len(lst[4]))]
                    y = O.seq_from(lst[4], vals)
                    codes.append([int(U[g]) if U[g] else 2 * int(y[g]) for g in range(t)])
                ok = check_design(G, codes, mu)
                print(f'SOL G={a.group} mu={mu} template {ti} rho {rho} checked={ok}')
                for name, c in zip('ABD', codes):
                    print(name, ' '.join(map(str, c)))
                sys.stdout.flush()
                nsol += 1
        total += nsol
        if nsol and a.first:
            break
    print(f'total solutions {total}; {len(cache)} distinct y lists', file=sys.stderr)


if __name__ == '__main__':
    main()
