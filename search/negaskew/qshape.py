"""K-level shape for the quaternary Paley plug-in (round 36, plug lens).
K = product of Z_m (Kmods), H_K = group generated by unit tuples (coordinatewise), q prime = 3 mod 4.
shape file for qp.c:  nu q Ksz / ell / neg / N[j][a][b] (j=0..nu-1) / character periods (re im)[j][a]
"""
import itertools, math, cmath, sys, os, json
from math import gcd


def prim_root(q):
    for g in range(2, q):
        x, ok = 1, True
        seen = set()
        for _ in range(q - 1):
            x = x * g % q
            seen.add(x)
        if len(seen) == q - 1:
            return g
    return 1 if q == 2 else None


def kshape(Kmods, hgens):
    Kmods = list(Kmods)
    d = len(Kmods)
    elems = list(itertools.product(*[range(m) for m in Kmods]))
    idx = {e: i for i, e in enumerate(elems)}
    Ksz = len(elems)
    one = tuple([1] * d)
    H = {one}
    fr = [one]
    hg = [tuple(int(u) % m for u, m in zip(g if hasattr(g, '__len__') else [g] * d, Kmods)) for g in hgens]
    while fr:
        x = fr.pop()
        for g in hg:
            y = tuple(a * b % m for a, b, m in zip(x, g, Kmods))
            if y not in H:
                H.add(y); fr.append(y)
    H = sorted(H)
    neg1 = tuple((m - 1) for m in Kmods)
    assert all(tuple((a * b) % m for a, b, m in zip(h, neg1, Kmods)) != tuple([0] * d) or Ksz == 1 for h in H)
    # -1 in H check: h == -1 coordinatewise (mod each m) would make -k in orbit of k
    for h in H:
        if all((hh + 1) % m == 0 for hh, m in zip(h, Kmods)) and Ksz > 1:
            raise ValueError('-1 in H_K')
    orb = [-1] * Ksz
    reps = []
    zero = idx[tuple([0] * d)]
    order = [zero] + [i for i in range(Ksz) if i != zero]
    for i in order:
        if orb[i] < 0:
            o = len(reps)
            reps.append(i)
            for h in H:
                y = tuple(a * b % m for a, b, m in zip(elems[i], h, Kmods))
                orb[idx[y]] = o
    nu = len(reps)
    ell = [orb.count(o) for o in range(nu)]
    neg = [orb[idx[tuple((-a) % m for a, m in zip(elems[reps[o]], Kmods))]] for o in range(nu)]
    N = [[[0] * nu for _ in range(nu)] for _ in range(nu)]
    for j in range(nu):
        r = elems[reps[j]]
        for i in range(Ksz):
            k = elems[i]
            kk = tuple((a + b) % m for a, b, m in zip(k, r, Kmods))
            N[j][orb[i]][orb[idx[kk]]] += 1
    C = [[0j] * nu for _ in range(nu)]
    for j in range(nu):
        r = elems[reps[j]]
        for i in range(Ksz):
            k = elems[i]
            ph = sum(a * b / m for a, b, m in zip(r, k, Kmods))
            C[j][orb[i]] += cmath.exp(2j * math.pi * ph)
    return dict(Kmods=Kmods, nu=nu, Ksz=Ksz, ell=ell, neg=neg, N=N, C=C, orb=orb, reps=reps, elems=elems, H=H)


def write_shape(sh, q, fname):
    nu = sh['nu']
    with open(fname, 'w') as f:
        f.write(f"{nu} {q} {sh['Ksz']}\n")
        f.write(" ".join(map(str, sh['ell'])) + "\n")
        f.write(" ".join(map(str, sh['neg'])) + "\n")
        for j in range(nu):
            for a in range(nu):
                f.write(" ".join(map(str, sh['N'][j][a])) + "\n")
        for j in range(nu):
            f.write(" ".join(f"{sh['C'][j][a].real:.12f} {sh['C'][j][a].imag:.12f}" for a in range(nu)) + "\n")


def cyc_gens(m, q, hK):
    """generators in Z_{m q} (CRT) of H = H_K x S for K = Z_m (gcd(m,q)=1), H_K generated by the list hK, S = squares of F_q*"""
    v = m * q
    gens = []
    for h in hK:
        # x = h mod m, 1 mod q
        x = next(x for x in range(v) if x % m == h % m and x % q == 1)
        gens.append(x)
    g = prim_root(q)
    s = g * g % q
    if s != 1:
        x = next(x for x in range(v) if x % m == 1 and x % q == s)
        gens.append(x)
    return gens


if __name__ == '__main__':
    Km = json.loads(sys.argv[1]); q = int(sys.argv[2]); hg = json.loads(sys.argv[3]); fn = sys.argv[4]
    sh = kshape(Km, hg)
    write_shape(sh, q, fn)
    print('nu', sh['nu'], 'ell', sh['ell'], 'neg', sh['neg'])
