"""Exact small-list sweep over the composite census structures that survive census_screen.py.

For composite v the Gaussian models are unreliable in both directions (253/<12>: 10^-2 predicted, 19,088 solutions
in lists of 4*10^4; 623/<2>: 10^1.6 predicted, none exist). So every surviving structure gets the same cheap test:
low-energy lists (skew_gen.c), all or 2^17 sampled skew A, and an exact count of the solutions inside the lists
(join4x), pattern by pattern; hits are verified and logged.

  python3 search/lowE_sweep.py [--n N] [--maxo O] [--skip v,...] [--seed S]
      -> $HADAMARD_WORK/lowE_sweep.jsonl, hits in $HADAMARD_WORK/skew_hits.jsonl
"""
import argparse, json, os, sys, time
from collections import defaultdict
from pathlib import Path as _P; sys.path[:0] = [str(_P(__file__).resolve().parent)]
import workdir as W
from paley_product import search


def fixes_point(v, gens):
    """True if the subgroup generated by gens fixes some t != 0 (a product-type structure)."""
    return any(all(t * g % v == t for g in gens) for t in range(1, v))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--n', type=float, default=1e5); ap.add_argument('--steps', type=int, default=3)
    ap.add_argument('--amax', type=float, default=2 ** 17); ap.add_argument('--maxo', type=int, default=49)
    ap.add_argument('--skip', default=''); ap.add_argument('--seed', type=int, default=1)
    a = ap.parse_args()
    skip = {int(x) for x in a.skip.split(',') if x}
    out = W.WORK / 'lowE_sweep.jsonl'
    done = set()
    if out.exists():
        for l in open(out):
            r = json.loads(l); done.add((r['v'], tuple(r['gens']), tuple(r['pattern'])))
    by = defaultdict(list)
    for l in open(W.WORK / 'census_screen.jsonl'):
        r = json.loads(l)
        if r['alive'] and r['O'] <= a.maxo and r['v'] not in skip: by[(r['v'], tuple(r['gens']))].append(r)
    keys = sorted(by, key=lambda k: (not fixes_point(*k[:1], k[1]), -max(r['log10E_gen'] for r in by[k])))
    for v, gens in keys:
        solved = {json.loads(l)['n'] for l in open(W.hits())} if os.path.exists(W.hits()) else set()
        if v in solved: continue
        for r in sorted(by[(v, gens)], key=lambda r: -r['log10E_gen']):
            pat = tuple(r['pattern'][1:] if len(r['pattern']) == 4 else r['pattern'])
            if (v, gens, pat) in done: continue
            t0 = time.time()
            try:
                st, sz, total, found = search(v, list(gens), pat, int(a.n), a.steps, a.amax, a.seed)
            except Exception as e:
                print(f"v={v} H={list(gens)} pattern={pat}: error {e!r}", flush=True); continue
            rec = dict(v=v, gens=list(gens), O=st.O, C=st.C, pattern=list(pat), product=fixes_point(v, gens),
                       log10E_gen=r['log10E_gen'], lists=sz, solutions=total, verified=len(found), seed=a.seed,
                       n=a.n, steps=a.steps, seconds=round(time.time() - t0))
            with open(out, 'a') as f: f.write(json.dumps(rec) + '\n')
            print(json.dumps(rec), flush=True)
            done.add((v, gens, pat))
            if found:
                with open(W.hits(), 'a') as f:
                    for x in found: f.write(json.dumps(x) + '\n')
                break


if __name__ == '__main__':
    main()
