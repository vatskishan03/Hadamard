"""Generic abelian-group shapes for the quaternary skew engine qskew (README.md): the shape file and the Gaussian estimate for any finite abelian group.
G = prod_j (Z/m_j)  (list of coordinate moduli), H = group generated by automorphisms given as permutations of the
element index set (numpy int arrays).  Element index = mixed radix of the coordinate tuple.
Odd |H| is required (then -1 is never in H and g, -g are in different orbits for g != 0)."""
import numpy as np, itertools, math, json, sys
from math import gcd

def elems(mods):
    r = len(mods); v = int(np.prod(mods))
    idx = np.arange(v)
    cols = []
    t = idx.copy()
    for m in mods:
        cols.append(t % m); t = t // m
    return np.stack(cols, axis=1)      # v x r  (coordinate i = digit i)

def encode(C, mods):
    r = len(mods); idx = np.zeros(C.shape[0], dtype=np.int64); mul = 1
    for i, m in enumerate(mods):
        idx += (C[:, i] % m) * mul; mul *= m
    return idx

def perm_from_matrix(mods, Mat):
    """Mat: r x r integer matrix, acts on column vectors (coordinate i taken mod mods[i]); returns permutation of indices"""
    C = elems(mods)
    Cn = (C @ np.array(Mat).T)
    out = encode(Cn, mods)
    assert len(set(out.tolist())) == len(out), "not an automorphism"
    return out

def perm_order(p):
    # order of a permutation
    seen = np.zeros(len(p), bool); o = 1
    for i in range(len(p)):
        if not seen[i]:
            l = 0; j = i
            while not seen[j]:
                seen[j] = True; j = p[j]; l += 1
            o = o * l // gcd(o, l)
    return o

def orbits_of(perms, v):
    orb = -np.ones(v, dtype=np.int64); reps = []
    for g in range(v):
        if orb[g] < 0:
            idx = len(reps); reps.append(g); st = [g]; orb[g] = idx
            while st:
                x = st.pop()
                for p in perms:
                    y = int(p[x])
                    if orb[y] < 0: orb[y] = idx; st.append(y)
    return orb, reps

def group_size(perms, v):
    # size of generated group by closure (small groups): compute via orbit-stabiliser on a few points is messy; do BFS on permutations (as tuples) up to a cap
    ident = tuple(range(v)); seen = {ident}; fr = [ident]
    while fr:
        x = fr.pop()
        for p in perms:
            y = tuple(p[list(x)]) if False else tuple(int(p[i]) for i in x)
            if y not in seen:
                seen.add(y); fr.append(y)
                if len(seen) > 5000: return None
    return len(seen)

def shape_g(mods, perms, fname=None):
    v = int(np.prod(mods)); C = elems(mods)
    orb, reps = orbits_of(perms, v); n = len(reps)
    orb = np.array(orb)
    sz = [int((orb == i).sum()) for i in range(n)]
    negidx = encode((-C) % np.array(mods), mods)
    neg = [int(orb[negidx[reps[i]]]) for i in range(n)]
    N = np.zeros((n, n, n), dtype=np.int64)
    for c in range(1, n):
        s = C[reps[c]]
        sh = encode((C + s) % np.array(mods), mods)
        for g in range(v):
            N[c, orb[g], orb[sh[g]]] += 1
    d = dict(v=v, n=n, orb=orb.tolist(), reps=reps, sz=sz, neg=neg, N=N)
    if fname:
        with open(fname, 'w') as f:
            f.write(f"{v} {n}\n" + " ".join(map(str, sz)) + "\n" + " ".join(map(str, neg)) + "\n")
            for c in range(1, n):
                for a in range(n): f.write(" ".join(map(str, N[c, a])) + "\n")
    return d

