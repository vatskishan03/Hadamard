def prime_parts(v):
    from sympy import factorint
    return sorted(factorint(v).items())

def homocyclic_decomps(p, a, kmax=3):
    """(b,k) with b*k=a, k<=kmax : group (Z/p^b)^k"""
    out = []
    for k in range(1, min(a, kmax) + 1):
        if a % k == 0: out.append((a // k, k))
    return out

def gl_elements_odd(p, b, k, cap=3_000_000):
    """all matrices in GL(k, Z/p^b) of odd order (as k x k int arrays), if the group is small enough, else None"""
    m = p ** b
    tot = m ** (k * k)
    if tot > cap * 40: return None
    res = []
    I = np.eye(k, dtype=np.int64)
    # enumerate matrices with entries mod m, filter det unit
    rng = range(m)
    for ent in itertools.product(rng, repeat=k * k):
        M = np.array(ent, dtype=np.int64).reshape(k, k)
        det = int(round(np.linalg.det(M))) % m if k <= 3 else None
        if det % p == 0: continue
        # order
        X = M.copy(); o = 1
        while not np.array_equal(X % m, I):
            X = (X @ M) % m; o += 1
            if o > 2000: break
        if o % 2 == 1: res.append((M, o))
    return res

def est_d(d):
    n = d['n']; N = d['N']; lg = 0.0
    for c in range(1, n):
        if d['neg'][c] < c: continue
        M = N[c].astype(float)
        sre = sum((M[a, b] + M[b, a]) ** 2 / 2 for a in range(n) for b in range(a + 1, n))
        sim = sum((M[a, b] - M[b, a]) ** 2 / 2 for a in range(n) for b in range(a + 1, n))
        for s2 in (sre, sim):
            tot = 4 * s2
            if tot <= 0: continue
            lg += math.log2(1.0 / math.sqrt(2 * math.pi * tot))
    bits = 7 * (n - 1) + 1
    return bits + lg

def block_diag_perm(parts_mods, part_mats):
    """parts_mods: list of (m,k) per part; part_mats: list of k x k matrices (or None for identity) -> permutation on whole G"""
    mods = []; 
    for (m, k) in parts_mods: mods += [m] * k
    r = len(mods)
    Mat = np.zeros((r, r), dtype=np.int64); off = 0
    for (m, k), M in zip(parts_mods, part_mats):
        if M is None: M = np.eye(k, dtype=np.int64)
        Mat[off:off + k, off:off + k] = np.array(M).reshape(k, k)
        off += k
    return mods, perm_from_matrix(mods, Mat)
