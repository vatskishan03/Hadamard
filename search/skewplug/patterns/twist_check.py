"""Twisted generators are impossible (G-level check, no Paley algebra).  Which groups H = <{1} x S, (h, nu)> (S = squares of F_q*, h a unit of K, nu in F_q*) admit an
H-invariant SKEW sequence A (A(0) = 1, A(-g) = -A(g) for g != 0)?  Such an A exists iff no element of H maps some g != 0 to -g.
Proof that nu must be a square: for a non-square nu, Euler's criterion gives (h, nu)^((q-1)/2) = (h^((q-1)/2), -1), which maps (0, f) to (0, -f).
For every K and q the program tests every generator (h, nu) and prints how many are compatible, split by nu square / non-square, and how many generators
disagree with the criterion 'compatible iff the element (h, nu) of Z_K* x F_q* has odd order' (always 0).
usage (from search/skewplug):  python3 patterns/twist_check.py [small]      'small' = only the K in {Z3, Z5, Z7, Z9, Z15, Z3^2, Z21} and q in {3, 7, 11, 19}: 1512 generators (a few seconds);
without argument: K in {Z3, Z5, Z7, Z9, Z15, Z3^2, Z21, Z25, Z5^2} and q in {3, 7, 11, 19, 23} with |K| q <= 700 (several minutes)."""
import os, sys
import itertools, math
import numpy as np
from math import gcd

def units(m): return [a for a in range(1, m) if gcd(a, m) == 1]


def mult_order(a, m):
    o, x = 1, a % m
    while x != 1 % m: x = x * a % m; o += 1
    return o

def check(Kmods, q):
    n = int(np.prod(Kmods))
    mods = list(Kmods) + [q]
    G = list(itertools.product(*[range(m) for m in mods]))
    idx = {g: i for i, g in enumerate(G)}
    sq = {x * x % q for x in range(1, q)}
    res = {'sq': [0, 0], 'nsq': [0, 0], 'disagree': 0}      # [tested, compatible]; disagree: generators where 'compatible' differs from 'odd order'
    exs = []
    for hu in itertools.product(*[units(m) for m in Kmods]):
        for nu in range(1, q):
            # group generated by (hu, nu) and the squares {1} x S  (S acts trivially on K)
            gens = [(tuple(hu), nu)] + [((1,) * len(Kmods), c) for c in sq]
            def act(gen, g):
                hh, c = gen
                return tuple((g[i] * hh[i]) % Kmods[i] for i in range(len(Kmods))) + ((g[-1] * c) % q,)
            # orbits via union-find; skew-compatible iff for no g != 0 is -g in the orbit of g
            parent = list(range(len(G)))
            def find(x):
                while parent[x] != x: parent[x] = parent[parent[x]]; x = parent[x]
                return x
            for g in G:
                for gen in gens:
                    a, b = find(idx[g]), find(idx[act(gen, g)])
                    if a != b: parent[a] = b
            ok = True
            for g in G:
                if all(x == 0 for x in g): continue
                ng = tuple((-g[i]) % mods[i] for i in range(len(mods)))
                if find(idx[g]) == find(idx[ng]): ok = False; break
            key = 'sq' if nu in sq else 'nsq'
            order = nq = mult_order(nu, q)
            for hh, mm in zip(hu, Kmods): order = order * mult_order(hh, mm) // math.gcd(order, mult_order(hh, mm))
            if ok != (order % 2 == 1): res['disagree'] += 1
            res[key][0] += 1; res[key][1] += int(ok)
            if (not ok) and key == 'sq' and len(exs) < 2: exs.append((hu, nu))
    return res, exs

if __name__ == '__main__':
    small = len(sys.argv) > 1 and sys.argv[1] == 'small'
    tot = {'sq': [0, 0], 'nsq': [0, 0]}; dis = 0
    for Kmods in ([3], [5], [7], [9], [15], [3, 3], [21]) if small else ([3], [5], [7], [9], [15], [3, 3], [21], [25], [5, 5]):
        for q in (3, 7, 11, 19) if small else (3, 7, 11, 19, 23):
            if int(np.prod(Kmods)) * q > 700: continue
            res, exs = check(Kmods, q)
            for k in tot:
                for j in range(2): tot[k][j] += res[k][j]
            dis += res['disagree']
            print(f'K={Kmods} q={q}: nu square: {res["sq"][1]}/{res["sq"][0]} compatible; nu NON-square: {res["nsq"][1]}/{res["nsq"][0]} compatible; disagreements with odd order: {res["disagree"]}; incompatible square gens e.g. {exs}', flush=True)
    print('TOTAL square-nu generators (tested, compatible):', tot['sq'], ' non-square-nu generators (tested, compatible):', tot['nsq'], ' disagreements with "compatible iff odd order":', dis)
