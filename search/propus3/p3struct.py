"""Structure of a cyclic propus search (A symmetric, B repeated, D free) on Z_v with a multiplier group H.

Everything the C engine (p3.c) needs is derived here from first principles and cross-checked against a direct
periodic-autocorrelation computation (`selfcheck`).  Nothing here imports the repository; the repository's
verify/verify.py is used only to certify finished matrices (p3cert.py).

Conventions (as in search/propus.py, NOTES.md section 17):
  * the quadruple is (A, B, B, D) on Z_v with  PAF_A + 2 PAF_B + PAF_D = 4 v delta;
  * A is constant on the orbits of <H, -1> (hence symmetric), B and D on the orbits of H;
  * "classes" are the orbits of <H, -1> on Z_v \\ {0}; a block constant on the orbits of its group has a PAF that is
    constant on the classes, so the condition is C equations  F_A(c) + 2 F_B(c) + F_D(c) = 0;
  * a block is a vector y in {+1,-1}^O (O orbits, orbit 0 = {0}); its class values are the quadratic forms
        F_c(y) = const0[c] + sum_{i<j} T[c][i][j] y_i y_j ,   T = S + S^t,  S[c][i][j] = #{g in orbit i : g + s_c in orbit j}.
"""
import math
from math import gcd
import numpy as np


def subgroup(v, gens):
    """The subgroup of Z_v^* generated by gens (sorted list)."""
    H = {1}
    while True:
        grown = H | {h * g % v for h in H for g in gens}
        if grown == H:
            return sorted(H)
        H = grown


def orbit_labels(v, mults):
    """Orbits of x -> m x (m in mults, a group) on Z_v, ordered by smallest element; orbit 0 = {0}."""
    lab = -np.ones(v, dtype=np.int64)
    k = 0
    for g in range(v):
        if lab[g] < 0:
            for m in mults:
                lab[g * m % v] = k
            k += 1
    return lab, k


class Block:
    """A sign vector y on the orbits of a multiplier group on Z_v, with the class machinery."""

    def __init__(self, v, mults, cls, C, creps):
        self.v = v
        self.mults = sorted(mults)
        self.orb, self.O = orbit_labels(v, self.mults)
        self.sizes = np.bincount(self.orb, minlength=self.O).astype(np.int64)
        self.reps = [int(np.flatnonzero(self.orb == i)[0]) for i in range(self.O)]
        assert self.sizes[0] == 1 and self.orb[0] == 0
        self.C, self.cls, self.creps = C, cls, creps
        S = np.zeros((C, self.O, self.O), dtype=np.int64)
        idx = np.arange(v)
        for c, s in enumerate(creps):
            np.add.at(S[c], (self.orb, self.orb[(idx + s) % v]), 1)
        self.S = S
        self.const0 = np.array([int(np.trace(S[c])) for c in range(C)], dtype=np.int64)
        T = S + S.transpose(0, 2, 1)
        for c in range(C):
            np.fill_diagonal(T[c], 0)
        self.T = T
        self._W = None

    # ----- values ----------------------------------------------------------------------------------------------
    def seq(self, Y):
        """Expand sign vectors (..., O) to sequences on Z_v (..., v)."""
        return np.asarray(Y)[..., self.orb]

    def values(self, Y, chunk=40000):
        """Class values (n, C) of sign vectors Y (n, O): F_c = const0_c + sum_{i<j} T_c[i][j] y_i y_j (exact: small integers
        in float32 matrix products)."""
        Y = np.asarray(Y, dtype=np.float32)
        C, O = self.C, self.O
        Tcat = self.T.reshape(C * O, O).astype(np.float32)            # row (c, i) = T[c][i][:]
        out = np.empty((Y.shape[0], C), dtype=np.int64)
        for s in range(0, Y.shape[0], chunk):
            y = Y[s:s + chunk]
            Z = (y @ Tcat.T).reshape(len(y), C, O)                     # Z[n, c, i] = sum_j T[c][i][j] y_j
            out[s:s + chunk] = np.rint(self.const0[None, :] + 0.5 * (Z * y[:, None, :]).sum(2)).astype(np.int64)
        return out

    # ----- row sums, pools, uniform sampling -------------------------------------------------------------------------
    def _dp(self):
        v, O = self.v, self.O
        W = np.zeros((O + 1, 2 * v + 1))
        W[O, v] = 1.0
        for j in range(O - 1, -1, -1):
            s = int(self.sizes[j])
            W[j, s:] += W[j + 1, :2 * v + 1 - s]
            W[j, :2 * v + 1 - s] += W[j + 1, s:]
        return W

    def pool(self, r):
        if self._W is None:
            self._W = self._dp()
        if abs(r) > self.v:
            return 0
        return int(round(self._W[0, r + self.v]))

    def sample(self, r, n, rng):
        """n uniform sign vectors (n, O) with row sum r."""
        if self._W is None:
            self._W = self._dp()
        W, v = self._W, self.v
        rem = np.full(n, r, dtype=np.int64)
        Y = np.zeros((n, self.O), dtype=np.int8)
        for j in range(self.O):
            s = int(self.sizes[j])
            # choose y_j = +1: remaining target r - s, completions W[j+1][(r-s)+v]
            wp = W[j + 1, np.clip(rem - s + v, 0, 2 * v)]
            wm = W[j + 1, np.clip(rem + s + v, 0, 2 * v)]
            p = wp / (wp + wm)
            plus = rng.random(n) < p
            Y[:, j] = np.where(plus, 1, -1)
            rem = rem - np.where(plus, s, -s)
        assert np.all(rem == 0)
        return Y


class Structure:
    """The three blocks of a propus search on Z_v with multiplier subgroup <gens> (odd order assumed, -1 not in H)."""

    def __init__(self, v, gens):
        self.v = v
        self.H = subgroup(v, gens)
        assert (v - 1) not in self.H, "-1 must not lie in H (B and D would be forced symmetric)"
        Hm = sorted(set(self.H) | {(-h) % v for h in self.H})
        self.Hm = Hm
        lab, k = orbit_labels(v, Hm)
        zero = lab[0]
        labels = sorted(set(lab.tolist()) - {int(zero)})
        remap = {l: i for i, l in enumerate(labels)}
        self.cls = np.array([remap.get(int(c), -1) for c in lab])
        self.C = len(labels)
        self.creps = [int(np.flatnonzero(self.cls == c)[0]) for c in range(self.C)]
        self.csize = np.bincount(self.cls[self.cls >= 0], minlength=self.C)
        self.A = Block(v, Hm, self.cls, self.C, self.creps)        # constant on <H,-1> orbits
        self.B = Block(v, self.H, self.cls, self.C, self.creps)    # constant on H orbits (B and D)
        # PSD matrix: P_x(c') = v + sum_c theta[c'][c] F_c(x)
        th = np.zeros((self.C, self.C))
        g = np.arange(v)
        for cp, w in enumerate(self.creps):
            co = np.cos(2 * np.pi * (g * w % v) / v)
            for c in range(self.C):
                th[cp, c] = co[self.cls == c].sum()
        self.theta = th
        # Mult = Z_v^* / H : coset representatives
        units = [t for t in range(1, v) if gcd(t, v) == 1]
        seen, reps = set(), []
        for t in units:
            if t not in seen:
                reps.append(t)
                seen |= {t * h % v for h in self.H}
        self.mult_reps = reps                     # includes 1 first
        self.neg = v - 1

    def patterns(self):
        v = self.v
        lim = math.isqrt(4 * v)
        out = []
        for ra in range(1, lim + 1, 2):
            for rb in range(1, lim + 1, 2):
                rest = 4 * v - ra * ra - 2 * rb * rb
                if rest < 1:
                    continue
                rd = math.isqrt(rest)
                if rd * rd == rest and rd % 2:
                    out.append((ra, rb, rd))
        return out

    def feasible_patterns(self):
        res = []
        for (ra, rb, rd) in self.patterns():
            pa, pb, pd = self.A.pool(ra), self.B.pool(rb), self.B.pool(rd)
            if min(pa, pb, pd) > 0:
                res.append(dict(rows=(ra, rb, rd), pools=(pa, pb, pd)))
        return res

    def psd(self, F):
        """P(c') for class values F (n, C): the squared modulus of the DFT at the frequency creps[c']."""
        return self.v + F @ self.theta.T

    def perm_of(self, block, t):
        """pi_t on the orbits of `block`: orbit i -> orbit containing t * rep_i  (x_t(g) = x(t g), y'_i = y[pi_t(i)])."""
        return np.array([block.orb[(t * r) % self.v] for r in block.reps], dtype=np.int64)

    def apply_mult(self, block, Y, t):
        return np.asarray(Y)[..., self.perm_of(block, t)]

    def cache_note(self):
        return dict(v=self.v, H=len(self.H), OA=self.A.O, OB=self.B.O, C=self.C)


