def paf(x):
    """Periodic autocorrelation of an integer sequence (or rows) by FFT; exact after rounding."""
    X = np.fft.rfft(np.asarray(x, dtype=np.float64), axis=-1)
    n = np.asarray(x).shape[-1]
    return np.rint(np.fft.irfft(X * np.conj(X), n=n, axis=-1)).astype(np.int64)


def selfcheck(st, rng, trials=200, rowsA=None, rowsB=None):
    """Compare the class-value tables and the PSD matrix with direct computation on random sign vectors."""
    for blk, name in ((st.A, 'A'), (st.B, 'B')):
        Y = (rng.integers(0, 2, size=(trials, blk.O)) * 2 - 1).astype(np.int8)
        F = blk.values(Y)
        P = paf(blk.seq(Y))
        direct = P[:, st.creps]
        assert np.array_equal(F, direct), f'class values of {name} differ from direct PAF'
        # constancy over every shift of the class
        for c in range(st.C):
            cols = np.flatnonzero(st.cls == c)
            assert np.all(P[:, cols] == P[:, [cols[0]]]), f'PAF of {name} is not class-constant'
        # PSD: |DFT|^2 at frequency creps[c'] equals v + theta F
        Z = np.abs(np.fft.fft(blk.seq(Y).astype(np.float64), axis=-1)) ** 2
        Pd = Z[:, st.creps]
        Pm = st.psd(F)
        assert np.abs(Pd - Pm).max() < 1e-6, f'PSD formula mismatch for {name}: {np.abs(Pd - Pm).max()}'
    return True
