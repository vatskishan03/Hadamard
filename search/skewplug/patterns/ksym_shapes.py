"""K-symmetric census shapes (the shapes of the 473 type).  Enumerates every undecided skew census value v = |K| q (search/data/skew_census_undecided.txt minus the orders of skew/; q in {7, 11, 19, 23, 27, 31}, |K| = m in 5..MMAX,
K every abelian type (cyclic coprime products as ONE modulus Z_m, repeated primes as component lists), with an H_K of odd order 3, 5, 7 or 9 generated by one unit tuple (diagonal action on K) or by two subgroups
of order 3, at most NUMAX H_K-orbits (nu) and a non-empty list of allocations (the defect identity is realisable by the orbit weights).  Prints one line per shape and writes the list as JSON
(v, q, m, K, hu, order, nu, number of allocations and slots, E range, number of A pairs).
usage (from search/skewplug):  python3 patterns/ksym_shapes.py OUT.json [NUMAX [MMAX]]       default NUMAX 27, MMAX 200;  e.g.  python3 patterns/ksym_shapes.py runs/shapes.json 21 200   (about 90 s)
The shapes are the inputs of patterns/run_pat.py, run_bb.py, exh_shape.py, rowscan.py and prod_dedup.py (a shape: K, q, hu = the 'K', q, 'hunits' arguments)."""
import sys, os, json, itertools, warnings
from math import gcd
warnings.filterwarnings('ignore')
import numpy as np
from sympy import factorint
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.join(HERE, '..')); sys.path.insert(0, HERE)
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
from sk import SShape
from sk_pat import allocations, m_splits
OUT = sys.argv[1]; NUMAX = int(sys.argv[2]) if len(sys.argv) > 2 else 27
QS = [7, 11, 19, 23, 27, 31]; ORDERS = {3, 5, 7, 9}; MMAX = int(sys.argv[3]) if len(sys.argv) > 3 else 200
vals = [int(l) for l in open(os.path.join(REPO, 'search', 'data', 'skew_census_undecided.txt')) if l.strip() and not l.startswith('#')]
known = set(int(d) // 4 for d in os.listdir(os.path.join(REPO, 'skew')) if d.isdigit())
und = [v for v in vals if v not in known]
print('census values', len(vals), 'undecided now', len(und), flush=True)

def partitions(n, maxpart=None):
    if maxpart is None: maxpart = n
    if n == 0: yield (); return
    for k in range(min(n, maxpart), 0, -1):
        for p in partitions(n - k, k): yield (k,) + p
def abelian_types(m):
    f = factorint(m); lists = []
    for p, e in f.items(): lists.append([[(p, k) for k in part] for part in partitions(e)])
    for combo in itertools.product(*lists): yield [x for c in combo for x in c]
def uorder(u, mod):
    o = 1; x = u % mod
    if mod == 1: return 1
    while x != 1: x = x * u % mod; o += 1
    return o
def closure(mods, gens):
    G = {tuple([1] * len(mods))}; fr = list(G)
    while fr:
        x = fr.pop()
        for g in gens:
            y = tuple((a * b) % m for a, b, m in zip(x, g, mods))
            if y not in G: G.add(y); fr.append(y)
    return frozenset(G)
rows = []
for v in und:
    for q in QS:
        if v % q: continue
        m = v // q
        if m < 5 or m > MMAX: continue          # gcd > 1: K x F_q not cyclic and the shapes are rarely feasible; not enumerated
        for t in abelian_types(m):
            mods = [p ** k for (p, k) in t]
            if len(mods) > 1 and len(set(p for (p, k) in t)) == len(t): mods = [m]      # cyclic K = Z_m (coprime components) as ONE modulus
            # cyclic subgroups of odd order in ORDERS generated by one unit tuple; two-generator (non-cyclic H_K) = products of two distinct order-3/5/7 cyclic subgroups (order 9 = Z3 x Z3 only)
            ranges = [[u for u in range(1, mm) if gcd(u, mm) == 1 and uorder(u, mm) % 2 == 1] for mm in mods]
            subs = {}
            for g in itertools.product(*ranges):
                og = 1
                for u, mm in zip(g, mods): og = og * uorder(u, mm) // gcd(og, uorder(u, mm))
                if og in ORDERS:
                    G = closure(mods, [g])
                    if len(G) == og and G not in subs: subs[G] = [g]
            if len(mods) > 1 or True:
                c3 = [(G, gs[0]) for G, gs in list(subs.items()) if len(G) == 3]
                for (Ga, ga), (Gb, gb) in itertools.combinations(c3, 2):
                    G = closure(mods, [ga, gb])
                    if len(G) == 9 and G not in subs: subs[G] = [ga, gb]
            if len(mods) > 1:      # non-cyclic K: dedup by (order, orbit-size multiset)
                seen_sig = {}; keep = {}
                for G, gens in subs.items():
                    from collections import Counter
                    cnt = Counter(); done_ = set()
                    for el in itertools.product(*[range(mm) for mm in mods]):
                        if el in done_: continue
                        orb = {tuple((a * b) % mm for a, b, mm in zip(el, g, mods)) for g in G}; done_ |= orb; cnt[len(orb)] += 1
                    sig = (len(G), tuple(sorted(cnt.items())))
                    if seen_sig.get(sig, 0) < 2: seen_sig[sig] = seen_sig.get(sig, 0) + 1; keep[G] = gens
                subs = keep
            for G, gens in subs.items():
                # scalar for a single cyclic component, tuples otherwise
                hu = [list(g) for g in gens]
                try:
                    sh = SShape(mods, q, hu)
                except Exception as ex:
                    continue
                nu = sh.kCD.nu
                if nu > NUMAX: continue
                import time as _t; _t0 = _t.time(); print('  shape', v, q, mods, hu, 'nu', nu, flush=True)
                al = allocations(sh)
                if not al: continue
                Es = sorted({sum(a) for a, em in al})
                nsl = sum(len(m_splits(a, em)) for a, em in al)
                rows.append(dict(v=v, q=q, m=m, K=mods, hu=hu, order=len(G), nu=nu, nalloc=len(al), nslots=nsl, Emin=Es[0], Emax=Es[-1], napairs=len(sh.apairs)))
rows.sort(key=lambda r: (r['nu'], r['v']))
json.dump(rows, open(OUT, 'w'), indent=0)
print('shapes', len(rows))
for r in rows:
    print(f"v={r['v']} q={r['q']} K={r['K']} hu={r['hu']} ord={r['order']} nu={r['nu']} nalloc={r['nalloc']} nslots={r['nslots']} E={r['Emin']}..{r['Emax']} Apairs={r['napairs']}")
