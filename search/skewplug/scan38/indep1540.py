"""Independent check of skew/1540 (written by the judge of round 38, no repository code): rebuilds the matrix from certificate.json with its own group arithmetic and Goethals-Seidel array and checks +-1, H H^T = 1540 I, H + H^T = 2I, the row sums, and (optionally) the canonical CSV hash.
usage (in search/skewplug): python3 scan38/indep1540.py ../../skew/1540/certificate.json [../../skew/1540/H1540.csv.gz [sequences.txt]]"""
# Independent check, written by the judge (no repository code): rebuild skew-Hadamard 1540 from certificate.json
import json, gzip, sys, hashlib, io
import numpy as np
cert_path = sys.argv[1]
csv_path = sys.argv[2] if len(sys.argv) > 2 else None
seq_path = sys.argv[3] if len(sys.argv) > 3 else None
c = json.load(open(cert_path))
n = c['v']; assert n == 385 and c['order'] == 4*n
mult = c['multipliers']
# subgroup generated by multipliers
Hset = {1}
frontier = [1]
while frontier:
    x = frontier.pop()
    for m in mult:
        y = (x*m) % n
        if y not in Hset:
            Hset.add(y); frontier.append(y)
Hs = sorted(Hset)
print("subgroup order", len(Hs), "elements", Hs)
assert len(Hs) == c['subgroup_order']
from math import gcd
assert all(gcd(h, n) == 1 for h in Hs)
assert (n-1) not in Hset  # -1 not in H
seqs = []
for blk in c['blocks']:
    x = np.ones(n, dtype=np.int64)
    for r in blk:
        for h in Hs:
            x[(r*h) % n] = -1
    seqs.append(x)
# invariance under H
for x in seqs:
    for h in Hs:
        assert all(x[(h*t) % n] == x[t] for t in range(n))
print("sizes of -1 sets", [int((x == -1).sum()) for x in seqs])
print("row sums", [int(x.sum()) for x in seqs], "sum of squares", sum(int(x.sum())**2 for x in seqs))
assert [int(x.sum()) for x in seqs] == c['rowsums']
A, B, C, D = seqs
# skew first block
assert A[0] == 1 and all(A[(-t) % n] == -A[t] for t in range(1, n))
# periodic autocorrelations
tot = np.zeros(n, dtype=np.int64)
for x in seqs:
    for s in range(n):
        tot[s] += int((x*np.roll(x, -s)).sum())
print("PAF total at 0:", tot[0], " nonzero shifts all zero:", bool((tot[1:] == 0).all()))
assert tot[0] == 4*n and (tot[1:] == 0).all()
# compare with sequences.txt
if seq_path:
    rows = [l.strip() for l in open(seq_path) if l.strip()]
    for x, r in zip(seqs, rows):
        assert len(r) == n
        assert all((1 if ch == '+' else -1) == v for ch, v in zip(r, x)), "sequences.txt differs"
    print("sequences.txt equals expansion of certificate: OK")
def circ(x):
    return np.array([[x[(j-i) % n] for j in range(n)] for i in range(n)], dtype=np.float64)
Am, Bm, Cm, Dm = map(circ, seqs)
R = np.eye(n)[::-1]
Z = lambda M: M
H = np.block([[Am, Bm@R, Cm@R, Dm@R],
              [-Bm@R, Am, Dm.T@R, -Cm.T@R],
              [-Cm@R, -Dm.T@R, Am, Bm.T@R],
              [-Dm@R, Cm.T@R, -Bm.T@R, Am]])
N = 4*n
assert H.shape == (N, N)
assert set(np.unique(H)) == {-1.0, 1.0}
G = H @ H.T
assert np.array_equal(G, N*np.eye(N)), "HH^T != nI"
print("H H^T == %d I exactly (float64 integers)" % N)
assert np.array_equal(H + H.T, 2*np.eye(N)), "not skew"
print("H + H^T == 2I exactly")
Hi = H.astype(np.int8)
buf = io.StringIO(); np.savetxt(buf, Hi, fmt="%d", delimiter=",")
sh = hashlib.sha256(buf.getvalue().encode()).hexdigest()
print("sha256 of canonical CSV", sh)
if csv_path:
    M = np.loadtxt(gzip.open(csv_path, 'rt'), delimiter=',', dtype=np.int64)
    print("stored matrix equals rebuild:", np.array_equal(M, Hi), M.shape)
    assert np.array_equal(M, Hi)
    assert np.array_equal(M @ M.T, N*np.eye(N, dtype=np.int64))
    print("stored matrix: M M^T = nI, M+M^T=2I:", np.array_equal(M+M.T, 2*np.eye(N, dtype=np.int64)))
