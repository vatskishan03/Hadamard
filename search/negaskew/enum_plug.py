"""Shapes of the quaternary Paley plug-in of qp.c for the Table 5 targets (entries v(m) with m >= 4 whose matrices of order
4v and 8v are not in skew/): K = Z_m cyclic, q prime = 3 (mod 4), gcd(m, q) = 1, H_K an odd-order subgroup of Z_m* generated by
1 or 2 elements.  Module: T5, targets(), subgroups_odd(m), orbits(m, H), weight_sets(...), repo_orders().
usage: python3 enum_plug.py       the shapes with NUMIN <= nu <= NUMAX K-orbits (NUMIN 5, NUMAX 9: environment variables) that pass the
                                  defect identity (a necessary condition: some allocation of the weights adds up to 4|K|);
                                  writes runs/plug_shapes.json (environment OUTF), prints one line per identity-feasible shape.
Which orders count as settled: the sweeps of NOTES.md section 89 ran before skew/2392 and skew/4712 (found by qp) were added, so the default
list is the one of that time: the contents of ../../skew without 2392 and 4712 (299 = 13 * 23 and 589 = 19 * 31 are targets).
PLUG_SETTLED=repo takes the repository as it is (a target v is dropped when 4v or 8v is in skew/)."""
import json, itertools, sys, os
from math import gcd
from sympy import isprime
HERE = os.path.dirname(os.path.abspath(__file__))
T5 = {int(k): v for k, v in json.load(open(os.path.join(HERE, 't5.json'))).items()}
QP_HITS = {2392, 4712}     # skew-Hadamard matrices found by qp.c (the plug-in sweeps ran before they were added to skew/)

def repo_orders():
    """orders of the matrices in skew/ at the time of the sweeps of NOTES.md section 89 (PLUG_SETTLED=repo: now)"""
    have = {int(d) for d in os.listdir(os.path.join(HERE, '..', '..', 'skew')) if d.isdigit()}
    return have if os.environ.get('PLUG_SETTLED') == 'repo' else have - QP_HITS

def targets(vmax=999):
    """Table 5 entries v(m) with m >= 4, v <= vmax, whose order 4v and 8v are not in skew/"""
    have = repo_orders()
    return sorted(v for v, m in T5.items() if m >= 4 and 4 * v not in have and 8 * v not in have and v <= vmax)

def census_values():
    """odd v < 2500 without a known skew matrix of order 4v (the census of search/data) that are not in skew/ either"""
    cen = [int(l.split()[0].lstrip('x')) for l in open(os.path.join(HERE, '..', 'data', 'skew_census_undecided.txt')) if l.strip() and not l.startswith('#')]
    have = repo_orders()
    return [v for v in cen if 4 * v not in have]

def subgroups_odd(m):
    U = [u for u in range(1, m) if gcd(u, m) == 1]
    def order(u):
        x, k = u, 1
        while x != 1: x = x * u % m; k += 1
        return k
    odd = [u for u in U if order(u) % 2 == 1 and u != 1]
    def closure(gens):
        H = {1}; fr = [1]
        while fr:
            x = fr.pop()
            for g in gens:
                y = x * g % m
                if y not in H: H.add(y); fr.append(y)
        return frozenset(H)
    subs = {frozenset([1]): [1]}
    for u in odd:
        H = closure([u]); subs.setdefault(H, [u])
    base = list(subs.items())
    for (H1, g1), (H2, g2) in itertools.combinations(base, 2):
        if H1 <= H2 or H2 <= H1: continue
        H = closure(g1 + g2)
        if len(H) % 2 == 0: continue
        subs.setdefault(H, g1 + g2)
    return subs

def orbits(m, H):
    seen = [False] * m; orbs = []
    for k in range(m):
        if not seen[k]:
            o = sorted({k * h % m for h in H}); 
            for x in o: seen[x] = True
            orbs.append(o)
    return orbs

def weight_sets(q, ells, negpairs):
    """reachable total defect weights of A (orbit 0 forced M, pairs doubled) and of a free block (B,C,D)"""
    cs = sorted({q + 1, q - 3, q - 1, (q + 1) // 2, (q - 3) // 2})
    cs = [c for c in cs]
    WA = set(); WB = set()
    # free: each orbit: 0 or ell*c
    reach = {0}
    for l in ells:
        reach = {r + x for r in reach for x in [0] + [l * c for c in cs if c > 0]}
    WB = reach
    # A: orbit 0 weight c in {(q+1)/2,(q-3)/2}; pairs 2*ell*c or 0
    reach = {w for w in [(q + 1) // 2, (q - 3) // 2]}
    for l in negpairs:
        reach = {r + x for r in reach for x in [0] + [2 * l * c for c in cs if c > 0]}
    WA = reach
    return WA, WB

if __name__ == '__main__':
    NUMIN = int(os.environ.get('NUMIN', '5')); NUMAX = int(os.environ.get('NUMAX', '9'))
    out = []
    for v in targets():
        for q in range(3, v):
            if v % q or not isprime(q) or q % 4 != 3: continue
            m = v // q
            if m % 2 == 0 or m == 1 or gcd(m, q) != 1: continue
            subs = subgroups_odd(m)
            for H, gens in subs.items():
                orbs = orbits(m, H); nu = len(orbs)
                if nu < NUMIN or nu > NUMAX: continue
                ells = [len(o) for o in orbs[1:]]  # orbit 0 is {0} (k=0 first)
                # orbit list: orbs[0] = {0}
                # negation pairs: each orbit o != 0 paired with -o
                idx = {}
                for i, o in enumerate(orbs):
                    for x in o: idx[x] = i
                pairs = []; seen = set()
                for i in range(1, nu):
                    if i in seen: continue
                    j = idx[(-orbs[i][0]) % m]; seen |= {i, j}; pairs.append(len(orbs[i]))
                WA, WB = weight_sets(q, [1] + ells, pairs)
                tot = 4 * m
                # B,C,D free blocks: orbit-0 weight included in WB (with ell=1)
                okid = False
                WBl = sorted(WB)
                pair2 = {a + b for a in WB for b in WB}
                for a in WA:
                    for s in pair2:
                        if tot - a - s in WB: okid = True; break
                    if okid: break
                out.append(dict(v=v, m5=T5[v], K=m, q=q, gens=gens, Hsize=len(H), nu=nu, ells=[len(o) for o in orbs], ident=okid))
    os.makedirs('runs', exist_ok=True)
    json.dump(out, open(os.environ.get('OUTF', 'runs/plug_shapes.json'), 'w'))
    feas = [s for s in out if s['ident']]
    print(len(out), 'shapes', len(feas), 'identity-feasible')
    from collections import Counter
    print(Counter(s['nu'] for s in feas))
    for s in sorted(feas, key=lambda s: (s['nu'], s['v'])):
        print(s['nu'], s['v'], 'm5', s['m5'], 'K', s['K'], 'q', s['q'], 'gens', s['gens'], '|H|', s['Hsize'], 'ells', s['ells'])
