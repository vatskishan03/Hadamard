r"""Spin structures (spin_skew.py) over a non-cyclic group G = Z_p^2 x Z_q, with automorphisms from GL(2, p) x Z_q^*.

A is skew and K-invariant (K = <H, mu>), B is H-invariant, C = B o mu, D = B o mu^2; the condition is
P_A(s) + P_B(s) + P_B(mu s) + P_B(mu^2 s) = 0 on the <K, -1>-classes, with row sums (1, b, b, b), 1 + 3b^2 = 4v.
The automorphisms act diagonally: (x, y) -> (M x, u y) with M in GL(2, p), u a unit mod q.

  python3 search/spin_group.py rank p q [--maxorbits N]      Gaussian estimate for every admissible (H, mu)
  python3 search/spin_group.py search p q "M1;u1|M2;u2" "Mmu;umu" [--restarts R] [--steps S] [--seed X]
  python3 search/spin_group.py check p q "M1;u1" "Mmu;umu"      exact fibre test on the subgroup classes
     (M as a,b,c,d: the matrix [[a, b], [c, d]] over GF(p); H generated by the listed elements)
"""
