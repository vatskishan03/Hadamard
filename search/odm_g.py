r"""Skew-type OD(4t; 1, m, 4t - m - 1) in Goethals-Seidel form over a finite abelian group G of order t (Seberry's
Theorem 7, search/NOTES.md §31), invariant under an automorphism group H of odd order: the generalisation of
search/odm_engine.py and search/odm_join2.py from Z_t to any G = Z_{n1}^{k1} x ... (search/gsgroup.py).

Blocks A_1 = a delta_0 + b u_1 + c w_1 (u_1, w_1 skew) and A_i = b u_i + c w_i (i = 2, 3, 4), with
    sum_i PAF(u_i) = m delta,  sum_i PAF(w_i) = 0 off the peak,  sum_i X_i(s) = 0 (X_i(s) = sum_g u_i(g) [w_i(g + s) + w_i(g - s)]).
1. b templates (join4x on the H-invariant ternary b parts, at most --bk), reduced modulo automorphisms generated by
   H and --norm, permutations of blocks 2-4, signs, and translations (by H-fixed elements) and negation of blocks 2-4.
2. Eades' row-sum screen: sum r_i rho_i = 0 and sum rho_i^2 = 4t - m - 1 (rho_1 = 0).
3. c lists (gdfs.c, cached) and join4x; each solution is checked as an OD in the Goethals-Seidel array.

Usage: python3 search/odm_g.py GROUP "HGENS" m [--norm GENS] [--bsub d] [--bk N] [--k K] [--first] [--dry]
"""
import argparse
import itertools
import os
import struct
import subprocess
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsgroup import Group, Orbits, read_list, group_matrix, reflection  # noqa: E402

WORK = os.path.join(os.environ.get('HADAMARD_WORK', '/tmp/hadamard-work'), 'tmp')


def gs_od(G, codes):
    """coefficient matrices (A, B, C) of a, b, c in the Goethals-Seidel array (codes 1 = a, +-2 = +-b, +-3 = +-c)"""
    R = reflection(G)
    out = []
    for var in (1, 2, 3):
        X = [group_matrix(G, np.where(np.abs(np.array(c)) == var, np.sign(np.array(c)), 0)) for c in codes]
        A1, A2, A3, A4 = X
        out.append(np.block([[A1, A2 @ R, A3 @ R, A4 @ R],
                             [-A2 @ R, A1, A4.T @ R, -A3.T @ R],
                             [-A3 @ R, -A4.T @ R, A1, A2.T @ R],
                             [-A4 @ R, A3.T @ R, -A2.T @ R, A1]]))
    return out


def check_od(G, codes, m):
    A, B, C = gs_od(G, codes)
    n = 4 * G.t
    c = n - m - 1
    I = np.eye(n, dtype=np.int64)
    return bool(np.array_equal(A, I) and np.array_equal(B, -B.T) and np.array_equal(C, -C.T)
                and np.all(np.abs(A) + np.abs(B) + np.abs(C) == 1) and np.array_equal(B @ B.T, m * I)
                and np.array_equal(C @ C.T, c * I) and not np.any(B @ C.T + C @ B.T))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('group')
    ap.add_argument('hgens')
    ap.add_argument('m', type=int)
    ap.add_argument('--norm', default='')
    ap.add_argument('--hb', default='', help='generators of a larger group H_b >= H for the x/b part')
    ap.add_argument('--bsub', type=int, default=0, help='b part on the elements killed by this integer')
    ap.add_argument('--bk', type=int, default=200000)
    ap.add_argument('--b4w', type=int, default=-1, help='weight bound for the b part of one of blocks 2-4')
    ap.add_argument('--b3w', type=int, default=-1, help='weight bound for the b part of a second one of blocks 2-4')
    ap.add_argument('--k', type=int, default=2)
    ap.add_argument('--first', action='store_true')
    ap.add_argument('--dry', action='store_true')
    ap.add_argument('--maxtpl', type=int, default=10 ** 7)
    ap.add_argument('--gdfs', default='/tmp/hadamard-work/bin/gdfs')
    ap.add_argument('--anneal', default='', help='R,STEPS,T0,T1: anneal the c parts with osa.c instead of lists')
    ap.add_argument('--osa', default='/tmp/hadamard-work/bin/osa')
    ap.add_argument('--join4x', default='/tmp/hadamard-work/bin/join4x')
    a = ap.parse_args()
    os.makedirs(WORK, exist_ok=True)
    G = Group(a.group)
    t, m = G.t, a.m
    ident = '/'.join(('1' if k == 1 else ';'.join(','.join('1' if i == j else '0' for j in range(k)) for i in range(k)))
                     for n, k in G.comps)
    hg = [x for x in a.hgens.split('|') if x and x != '1'] or [ident]
    H = G.closure([G.aut_perm(x) for x in hg])
    O = Orbits(G, H)
    if a.hb:
        Hb = G.closure([G.aut_perm(x) for x in hg] + [G.aut_perm(x) for x in a.hb.split('|') if x])
        Ob = Orbits(G, Hb)
        print(f'|H_b|={len(Hb)} H_b-orbits {Ob.no} reps {Ob.npr}', file=sys.stderr)
    else:
        Ob = O
    N = G.closure([G.aut_perm(x) for x in hg] + [G.aut_perm(x) for x in a.norm.split('|') if x])
    print(f'G={a.group} t={t} |H|={len(H)} H-orbits {O.no} reps {O.npr} |N|={len(N)} m={m}', file=sys.stderr)
    nperms, seenp = [], set()
    for p in N:
        for o in O.obs:
            if len({int(O.orb[p[x]]) for x in o}) != 1:
                sys.exit('--norm does not normalise H')
        k = tuple(int(O.orb[p[o[0]]]) for o in O.obs)
        if k not in seenp:
            seenp.add(k)
            nperms.append(np.array(k))
    fixed = [c for c in range(t) if all(int(h[c]) == c for h in H)]
    tr_perms = []
    for c in fixed:
        for sgn in (1, -1):
            tr_perms.append(np.array([int(O.orb[G.add[o[0] if sgn == 1 else G.neg[o[0]], c]]) for o in O.obs]))
    within = None
    if a.bsub:
        kill = np.all((a.bsub * G.elts) % G.mods_a == 0, axis=1)
        within = [bool(all(kill[x] for x in o)) for o in Ob.obs]
    tag = f'odmg_{a.group.replace("^", "p")}_{m}_{os.getpid()}'

    cands = []
    for blk, btype, wb in (('1', 'skew', m), ('k', 'plain', m), ('4', 'plain', a.b4w if a.b4w >= 0 else m),
                           ('3', 'plain', a.b3w if a.b3w >= 0 else m)):
        var = Ob.variables(btype, None, within)
        tp, lp = os.path.join(WORK, f'{tag}_{blk}.tab'), os.path.join(WORK, f'{tag}_{blk}.lst')
        Ob.write_tables(tp, var, 1, wb, 1)
        r = subprocess.run([a.gdfs, tp, lp], capture_output=True, text=True)
        if r.returncode:
            sys.exit(r.stderr)
        n, D, vec, masks = read_list(lp)
        os.remove(tp); os.remove(lp)
        cands.append((var, vec, masks.reshape(n, 2)))
        print(f'b candidates block {blk}: {len(var)} variables, {n}', file=sys.stderr)
    D = Ob.npr + 1
    fb = os.path.join(WORK, f'{tag}_tpl.bin')
    with open(fb, 'wb') as f:
        # list order (block 1, block 3, block 2, block 4): join4x pairs (1, 3) against (2, 4), so the bounded lists
        # of blocks 3 and 4 each pair with one of the large ones
        f.write(struct.pack('5i', len(cands[0][1]), len(cands[3][1]), len(cands[1][1]), len(cands[2][1]), D))
        f.write(np.array([0] * Ob.npr + [m], dtype=np.int16).tobytes())
        for c in (cands[0], cands[3], cands[1], cands[2]):
            f.write(np.ascontiguousarray(c[1]).tobytes())
    j = subprocess.run([a.join4x, fb, str(a.bk), '8000000', '1'], capture_output=True, text=True)
    os.remove(fb)
    sols = np.array([list(map(int, ln.split()[1:5])) for ln in j.stdout.splitlines() if ln.startswith('SOL')],
                    dtype=np.int64).reshape(-1, 4)
    tot = [ln for ln in j.stdout.splitlines() if ln.startswith('TOTAL')]
    print(f'b quadruples from join4x: {len(sols)} ({tot[0] if tot else "?"})', file=sys.stderr)

    def to_orbits(c, idx):
        var, _, masks = c
        V = np.zeros((len(idx), O.no), dtype=np.int64)
        pl, mi = masks[idx, 0], masks[idx, 1]
        for jv, v in enumerate(var):
            bp = ((pl >> np.uint64(jv)) & np.uint64(1)).astype(np.int64)
            bm = ((mi >> np.uint64(jv)) & np.uint64(1)).astype(np.int64)
            for o, cf in v:
                for x in Ob.obs[o]:
                    V[:, O.orb[x]] = cf * (bp - bm)
        return V

    def lexless(X, Y):
        """row-wise X < Y lexicographically"""
        d = X != Y
        idx = np.argmax(d, axis=1)
        r = np.arange(len(X))
        return d.any(axis=1) & (X[r, idx] < Y[r, idx])

    def lexmin(X, Y):
        m = lexless(Y, X)
        Z = X.copy()
        Z[m] = Y[m]
        return Z

    def canon_plain(V):
        best = None
        for pm in tr_perms:
            W = np.zeros_like(V)
            W[:, pm] = V
            for sg in (1, -1):
                best = sg * W if best is None else lexmin(best, sg * W)
        return best

    def sort_blocks(Ws):
        """sort blocks 2-4 lexicographically per row (a permutation of blocks is an equivalence)"""
        Ws = [w.copy() for w in Ws]
        for i in range(3):
            for j in range(2 - i):
                m = lexless(Ws[j + 1], Ws[j])
                tmp = Ws[j][m].copy()
                Ws[j][m] = Ws[j + 1][m]
                Ws[j + 1][m] = tmp
        return Ws

    X4 = [to_orbits(cands[0], sols[:, 0]), to_orbits(cands[1], sols[:, 2]), to_orbits(cands[3], sols[:, 1]),
          to_orbits(cands[2], sols[:, 3])]
    keys = None
    for pm in nperms:
        img = []
        for i, V in enumerate(X4):
            W = np.zeros_like(V)
            W[:, pm] = V
            img.append(lexmin(W, -W) if i == 0 else canon_plain(W))
        K = np.concatenate([img[0]] + sort_blocks(img[1:]), axis=1)
        keys = K if keys is None else lexmin(keys, K)
    uniq = np.unique(keys, axis=0) if keys is not None and len(keys) else np.zeros((0, 4 * O.no), dtype=np.int64)

    def decode_vec(v):
        s = np.zeros(t, dtype=np.int64)
        for i, x in enumerate(v):
            if x:
                s[O.obs[i]] = x
        return s

    templates = [[decode_vec(row[b * O.no:(b + 1) * O.no]) for b in range(4)] for row in uniq]
    print(f'{len(templates)} b templates up to equivalence', file=sys.stderr)

    def free_sizes(U, btype):
        return [int(sum(O.size[o] for o, c in v)) for v in O.variables(btype, U)]

    def signed_sums(sizes):
        s = {0}
        for z in sizes:
            s = {x + z for x in s} | {x - z for x in s}
        return s

    cw = 4 * t - m - 1
    work = []
    for tpl in templates:
        if tpl[0][0]:
            continue
        r = [int(x.sum()) for x in tpl]
        att = [signed_sums(free_sizes(tpl[i], 'plain')) for i in (1, 2, 3)]
        lim = int(cw ** 0.5) + 1
        feas = []
        for r2 in range(-lim, lim + 1):
            if r2 not in att[0]:
                continue
            for r3 in range(-lim, lim + 1):
                if r3 not in att[1]:
                    continue
                rem = cw - r2 * r2 - r3 * r3
                if rem < 0:
                    continue
                r4 = int(round(rem ** 0.5))
                for r4s in {r4, -r4}:
                    if r4s * r4s == rem and r4s in att[2] and r[1] * r2 + r[2] * r3 + r[3] * r4s == 0:
                        feas.append((r2, r3, r4s))
        # negating all c parts is an equivalence
        feas = sorted(set(min(f, tuple(-x for x in f)) for f in feas))
        if feas:
            work.append((tpl, feas))
    print(f'{len(work)} templates pass the row-sum screen', file=sys.stderr)
    if a.dry:
        for tpl, feas in work[:20]:
            print('TPL', [[(int(g), int(v)) for g, v in enumerate(s) if v] for s in tpl], feas[:4], len(feas))
        return

    cache = {}

    def get_list(U, btype, rs):
        key = (btype, U.tobytes(), rs)
        if key in cache:
            return cache[key]
        var = O.variables(btype, U)
        tp, lp = os.path.join(WORK, f'{tag}_y.tab'), os.path.join(WORK, f'{tag}_y.lst')
        O.write_tables(tp, var, 0, rs, 1, U)
        r = subprocess.run([a.gdfs, tp, lp], capture_output=True, text=True)
        if r.returncode:
            sys.exit(r.stderr)
        n, D, vec, masks = read_list(lp)
        os.remove(tp); os.remove(lp)
        cache[key] = (n, D, vec, masks, var)
        return cache[key]

    total = 0
    if a.anneal:
        R, STEPS, T0, T1 = a.anneal.split(',')
        seed = 1
        for ti, (tpl, feas) in enumerate(work[:a.maxtpl]):
            for rows in feas:
                blocks = [(1, O.variables('skew', tpl[0]), 0, tpl[0])] + \
                         [(1, O.variables('plain', tpl[i]), rows[i - 1], tpl[i]) for i in (1, 2, 3)]
                pf, of = os.path.join(WORK, f'{tag}_osa.bin'), os.path.join(WORK, f'{tag}_osa.out')
                O.write_osa(pf, blocks)
                seed += 1
                r = subprocess.run([a.osa, pf, str(seed), R, STEPS, T0, T1, of], capture_output=True, text=True)
                best = [ln for ln in r.stdout.splitlines()]
                print(f'template {ti} rows {rows}: {best[-1] if best else r.stderr[-200:]}', file=sys.stderr)
                if r.stdout.startswith('SOL'):
                    lines = open(of).read().split('\n')[1:5]
                    codes = []
                    for i, (bt, ln) in enumerate(zip(blocks, lines)):
                        vals = [int(x) for x in ln.split()]
                        w = O.seq_from(bt[1], vals)
                        U = tpl[i]
                        codes.append([1 if (i == 0 and g == 0) else 2 * int(U[g]) if U[g] else 3 * int(w[g])
                                      for g in range(t)])
                    ok = check_od(G, codes, m)
                    print(f'SOL G={a.group} m={m} template {ti} rows {rows} checked={ok} (anneal)')
                    for c in codes:
                        print(' '.join(map(str, c)))
                    sys.stdout.flush()
                    total += 1
                    if a.first:
                        print(f'total solutions {total}', file=sys.stderr)
                        return
        print(f'total solutions {total}', file=sys.stderr)
        return
    for ti, (tpl, feas) in enumerate(work[:a.maxtpl]):
        nsol = 0
        for rows in feas:
            L = [get_list(tpl[0], 'skew', 0)] + [get_list(tpl[i], 'plain', rows[i - 1]) for i in (1, 2, 3)]
            if any(x[0] == 0 for x in L):
                continue
            D = L[0][1]
            fn = os.path.join(WORK, f'{tag}_join.bin')
            with open(fn, 'wb') as f:
                f.write(struct.pack('5i', L[0][0], L[1][0], L[2][0], L[3][0], D))
                f.write(b'\0' * (2 * D))
                for x in L:
                    f.write(np.ascontiguousarray(x[2]).tobytes())
            jj = subprocess.run([a.join4x, fn, str(a.k)], capture_output=True, text=True)
            os.remove(fn)
            ss = [list(map(int, ln.split()[1:5])) for ln in jj.stdout.splitlines() if ln.startswith('SOL')]
            tt = [ln for ln in jj.stdout.splitlines() if ln.startswith('TOTAL')]
            print(f'template {ti} rows {rows}: lists {[x[0] for x in L]} {tt[0] if tt else "?"}', file=sys.stderr)
            for s in ss:
                codes = []
                for i, (U, lst, idx) in enumerate(zip(tpl, L, s)):
                    mm = int(lst[3][idx])
                    vals = [-1 if mm >> jv & 1 else 1 for jv in range(len(lst[4]))]
                    w = O.seq_from(lst[4], vals)
                    codes.append([1 if (i == 0 and g == 0) else 2 * int(U[g]) if U[g] else 3 * int(w[g])
                                  for g in range(t)])
                ok = check_od(G, codes, m)
                print(f'SOL G={a.group} m={m} template {ti} rows {rows} checked={ok}')
                for c in codes:
                    print(' '.join(map(str, c)))
                sys.stdout.flush()
                nsol += 1
        total += nsol
        if nsol and a.first:
            break
    print(f'total solutions {total}; {len(cache)} distinct c lists', file=sys.stderr)


if __name__ == '__main__':
    main()
