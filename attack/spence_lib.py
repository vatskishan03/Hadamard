"""Spence-type structures with symmetry from arbitrary automorphism groups.

Spence's bordered construction: four +-1 sequences x_1..x_4 on an abelian group G of
order v = n - 1 with row sums (2, 0, 0, 0) and

    sum_i P_i(g) = -4   for every g != 0,      P_i(g) = sum_t x_i(t) x_i(t + g),

give a Hadamard matrix of order 4n (verify/verify.py, build_spence).

Symmetry: H <= Aut(G). A sequence constant on H-orbits has P(sigma g) = P(g) for
sigma in H, and P(-g) = P(g), so the condition only has to hold on the orbits of
<H, -1> on G \\ {0} ("classes"). The repository's triage used scalar multipliers only,
which act trivially on elementary-abelian 2-parts; here H may contain any
automorphisms, e.g. Singer cycles and Frobenius maps of GF(p^b) acting on Z_p^b.
"""
import math
from math import gcd, log10, pi

import numpy as np


class AbGroup:
    """G = Z_{m_1} x ... x Z_{m_r}, elements indexed in mixed radix."""

    def __init__(self, mods):
        self.mods = np.array(mods, dtype=np.int64)
        self.v = int(np.prod(self.mods))
        self.coords = np.array(np.unravel_index(np.arange(self.v), tuple(int(m) for m in mods))).T.astype(np.int64)

    def index(self, C):
        C = np.asarray(C, dtype=np.int64) % self.mods
        return np.ravel_multi_index(tuple(C.T), tuple(int(m) for m in self.mods))

    def perm_from_matrix(self, A):
        """x -> A x (mod mods). Caller supplies an automorphism (checked: bijective, additive)."""
        p = self.index(self.coords @ np.asarray(A, dtype=np.int64).T)
        if len(np.unique(p)) != self.v:
            raise ValueError("matrix is not a bijection of G")
        rng = np.random.default_rng(0)
        a, b = rng.integers(0, self.v, 64), rng.integers(0, self.v, 64)
        if not np.array_equal(p[self.index(self.coords[a] + self.coords[b])],
                              self.index(self.coords[p[a]] + self.coords[p[b]])):
            raise ValueError("matrix is not additive on G")
        return p

    def neg(self):
        return self.index(-self.coords)

    def translate(self, g):
        return self.index(self.coords + self.coords[g])


def closure_partition(v, perms):
    """Orbits of the group generated by the permutations (labels 0..k-1, orbit of 0 first)."""
    lab = -np.ones(v, dtype=np.int64)
    k = 0
    for s in range(v):
        if lab[s] >= 0:
            continue
        lab[s] = k
        stack = [s]
        while stack:
            x = stack.pop()
            for p in perms:
                y = int(p[x])
                if lab[y] < 0:
                    lab[y] = k
                    stack.append(y)
        k += 1
    return lab, k


class Structure:
    def __init__(self, G, gens, name=""):
        self.G, self.name = G, name
        self.orb, self.O = closure_partition(G.v, gens)
        assert (self.orb == 0).sum() == 1 and self.orb[0] == 0, "orbit 0 must be {0}"
        self.sizes = np.bincount(self.orb, minlength=self.O)
        cl, _ = closure_partition(G.v, list(gens) + [G.neg()])
        zero = cl[0]
        labels = sorted(set(cl.tolist()) - {zero})
        remap = {l: i for i, l in enumerate(labels)}
        self.cls = np.array([remap.get(int(c), -1) for c in cl])
        self.C = len(labels)
        self.reps = [int(np.flatnonzero(self.cls == c)[0]) for c in range(self.C)]
        self.csize = np.bincount(self.cls[self.cls >= 0], minlength=self.C)
        self._S = None

    @property
    def S(self):
        if self._S is None:
            S = np.zeros((self.C, self.O, self.O))
            for c, g in enumerate(self.reps):
                np.add.at(S[c], (self.orb, self.orb[self.G.translate(g)]), 1)
            self._S = S
        return self._S

    # ---- row sums -------------------------------------------------------------
    def _dp(self):
        """W[j][s + v] = number of sign choices for orbits j..O-1 with sum s (float)."""
        v, O = self.G.v, self.O
        W = np.zeros((O + 1, 2 * v + 1))
        W[O, v] = 1.0
        for j in range(O - 1, -1, -1):
            s = int(self.sizes[j])
            W[j, :] = 0
            W[j, s:] += W[j + 1, :2 * v + 1 - s]
            W[j, :2 * v + 1 - s] += W[j + 1, s:]
        return W

    def pool(self, r):
        if not hasattr(self, "_W"):
            self._W = self._dp()
        return self._W[0, r + self.G.v]

    def sample(self, r, count, rng):
        """Exactly uniform sign vectors (count x O) with row sum r."""
        if not hasattr(self, "_W"):
            self._W = self._dp()
        W, v = self._W, self.G.v
        if W[0, r + v] == 0:
            return np.zeros((0, self.O))
        Y = np.empty((count, self.O))
        rem = np.full(count, r)
        for j in range(self.O):
            s = int(self.sizes[j])
            tot = W[j, rem + v]
            plus = np.where(rem - s >= -v, W[j + 1, np.clip(rem - s + v, 0, 2 * v)], 0.0)
            take = rng.random(count) < plus / tot
            Y[:, j] = np.where(take, 1.0, -1.0)
            rem = rem - Y[:, j].astype(np.int64) * s
        assert np.all(rem == 0)
        return Y

    def class_values(self, Y):
        """Periodic autocorrelation on each class rep, for each sign vector."""
        return np.einsum("bo,cop,bp->bc", Y, self.S, Y, optimize=True)

    # ---- Gaussian estimate -------------------------------------------------------
    def estimate(self, samples=3000, log_list=8.0, seed=1):
        v = self.G.v
        pm = v % 4
        target = (-4 - 4 * pm) // 4                       # sum of v_c = (P - pm)/4
        N2, N0 = self.pool(2), self.pool(0)
        if N2 == 0 or N0 == 0:
            return None
        rng = np.random.default_rng(seed)
        stats = {}
        for r in (2, 0):
            V = (self.class_values(self.sample(r, samples, rng)) - pm) / 4.0
            Vi = np.rint(V).astype(np.int64)
            assert np.allclose(V, Vi)
            lat = []
            for c in range(self.C):
                u = np.unique(Vi[:, c])
                g = int(np.gcd.reduce(np.diff(u))) if len(u) > 1 else 0
                lat.append((g, int(u[0] % g) if g else int(u[0])))
            stats[r] = (V.mean(0), V.var(0), lat)
        roles = (2, 0, 0, 0)
        mu = sum(stats[r][0] for r in roles)
        var = sum(stats[r][1] for r in roles)
        lp, terms = 0.0, []
        for c in range(self.C):
            g, res = 0, 0
            for r in roles:
                gg, aa = stats[r][2][c]
                g, res = gcd(g, gg), res + aa
            if var[c] < 1e-9:
                if abs(target - mu[c]) > 1e-6:
                    return dict(lE=-math.inf)
                continue
            if g and (target - res) % g:
                return dict(lE=-math.inf)
            t = -0.5 * log10(2 * pi * var[c]) - (target - mu[c]) ** 2 / (2 * var[c]) / math.log(10) + log10(max(g, 1))
            terms.append((self.csize[c] * math.sqrt(var[c]), t))
        terms.sort()                                      # drop the class the row sums determine:
        lp = sum(t for _, t in terms[:-1])                # the one with the largest weighted spread
        lE = log10(N2) + 3 * log10(N0) + lp
        lN = log10(min(N2, N0))
        C = self.C
        if lN <= log_list:
            lW = 2 * lN - lE
        else:
            lW = 3 * lN - lE - log_list - 0.5 * log10(6 / pi) * (C - 1)
        return dict(lE=lE, lN=lN, lW=lW, sd=np.sqrt(var / 4).mean())


# ---- automorphisms of elementary-abelian parts via finite fields --------------------
PRIMITIVE = {  # primitive polynomials over GF(p), low degree first: x^b = -(c_0 + ... )
    (2, 2): [1, 1], (2, 3): [1, 1, 0], (2, 4): [1, 1, 0, 0], (2, 5): [1, 0, 1, 0, 0],
    (2, 6): [1, 1, 0, 0, 0, 0], (3, 2): [2, 2], (3, 3): [1, 2, 0], (3, 4): [2, 0, 0, 1],
    (5, 2): [2, 1], (5, 3): [2, 3, 0], (7, 2): [3, 1],
}


def field_mult_matrix(p, b):
    """Companion matrix of x^b - (-(c_0) - c_1 x ...): multiplication by a primitive element."""
    c = PRIMITIVE[(p, b)]
    M = np.zeros((b, b), dtype=np.int64)
    for i in range(1, b):
        M[i, i - 1] = 1
    for i in range(b):
        M[i, b - 1] = (-c[i]) % p
    return M


def mat_pow_mod(M, e, p):
    R = np.eye(M.shape[0], dtype=np.int64)
    B = M.copy()
    while e:
        if e & 1:
            R = R @ B % p
        B = B @ B % p
        e >>= 1
    return R


def mat_order(M, p, limit=10**6):
    I = np.eye(M.shape[0], dtype=np.int64)
    X = M % p
    for k in range(1, limit):
        if np.array_equal(X, I):
            return k
        X = X @ M % p
    raise ValueError("order too large")


def frobenius_matrix(p, b):
    """x -> x^p on GF(p^b) in the power basis 1, a, ..., a^(b-1)."""
    A = field_mult_matrix(p, b)
    cols = []
    for i in range(b):
        e = np.zeros(b, dtype=np.int64)
        e[i] = 1                                          # basis element a^i
        # a^i as a matrix is A^i; its p-th power is A^(i p); apply to vector 1 = e_0
        cols.append(mat_pow_mod(A, i * p, p)[:, 0])
    return np.array(cols).T % p


def check_field_tables():
    for (p, b) in PRIMITIVE:
        M = field_mult_matrix(p, b)
        assert mat_order(M, p) == p ** b - 1, (p, b, mat_order(M, p))
    return True
