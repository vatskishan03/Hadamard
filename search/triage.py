#!/usr/bin/env python3
"""Rank multiplier structures for Goethals-Seidel searches over Z_n.

For every subgroup H of Z_n^* generated by at most two elements whose number of
orbits on Z_n lies in the given range, and for every admissible row-sum pattern
(four odd squares summing to 4n, each attainable by sequences constant on the
orbits of H), the script estimates

  log10 E    expected number of solutions in the structure,
  log10 N    size of the smallest pool (sequences with one of the row sums),
  log10 W    matching work per solution with lists of size L.

E comes from a Gaussian model of the class values, fitted to random sequences;
it accounts for the lattice of attainable values and for the one class that is
determined by the others. W uses the selection bound for descent-selected lists,

  E_found ~ E (L/N)^3 (6/pi)^((C-1)/2),

or N^2/E when the pools are small enough to keep entirely (N <= L). W is
conservative: processing the most probable partial sums first, the runs in this
repository needed about a tenth of it.

    python3 search/triage.py 919 1103 1123
"""
import argparse
import math
from math import gcd, log10, pi

import numpy as np


def subgroups(n):
    """Subgroups of Z_n^* generated by one or two elements, keyed by their elements."""
    units = [u for u in range(1, n) if gcd(u, n) == 1]

    def closure(gens):
        S, todo = {1}, [1]
        while todo:
            x = todo.pop()
            for g in gens:
                y = x * g % n
                if y not in S:
                    S.add(y)
                    todo.append(y)
        return frozenset(S)

    cyclic = {}
    for u in units:
        cyclic.setdefault(closure([u]), u)
    subs = {H: (g,) for H, g in cyclic.items()}
    items = list(cyclic.items())
    for i in range(len(items)):
        for j in range(i + 1, len(items)):
            H = closure([items[i][1], items[j][1]])
            subs.setdefault(H, (items[i][1], items[j][1]))
    return subs, closure


def orbits(n, H):
    orb = -np.ones(n, dtype=np.int64)
    sizes = []
    for j in range(n):
        if orb[j] < 0:
            O = {j * h % n for h in H}
            orb[list(O)] = len(sizes)
            sizes.append(len(O))
    return orb, np.array(sizes)


def rowsum_patterns(n):
    out, odd = [], range(1, int((4 * n) ** 0.5) + 1, 2)
    for a in odd:
        for b in odd:
            for c in odd:
                if not a <= b <= c:
                    continue
                d2 = 4 * n - a * a - b * b - c * c
                d = math.isqrt(d2) if d2 >= c * c else 0
                if d and d * d == d2:
                    out.append((a, b, c, d))
    return out


def class_stats(Y, S, pm):
    """Means, variances and value lattices (spacing, residue) of v_c over samples Y."""
    V = (np.einsum("bo,cop,bp->bc", Y, S, Y) - pm) / 4.0
    Vi = np.rint(V).astype(np.int64)
    lat = []
    for c in range(Vi.shape[1]):
        u = np.unique(Vi[:, c])
        g = int(np.gcd.reduce(np.diff(u))) if len(u) > 1 else 0
        lat.append((g, int(u[0] % g) if g else int(u[0])))
    return V.mean(0), V.var(0), lat


def log10_match_probability(pattern, stats, target):
    """log10 P(v_A + v_B + v_C + v_D = target on every class); -inf if impossible."""
    C = len(stats[abs(pattern[0])][0])
    lp, dropped = 0.0, False
    for c in range(C):
        mu = sum(stats[abs(r)][0][c] for r in pattern)
        var = sum(stats[abs(r)][1][c] for r in pattern)
        g, res = 0, 0
        for r in pattern:
            gg, aa = stats[abs(r)][2][c]
            g, res = gcd(g, gg), res + aa
        if var < 1e-9:
            if abs(target - mu) > 1e-6:
                return -math.inf
            continue
        if g and (target - res) % g:
            return -math.inf
        if not dropped:          # the class determined by the row-sum identity
            dropped = True
            continue
        lp += -0.5 * log10(2 * pi * var) - (target - mu) ** 2 / (2 * var) / math.log(10) + log10(max(g, 1))
    return lp


def triage(n, lo, hi, log_list, samples, rng):
    subs, closure = subgroups(n)
    patterns = rowsum_patterns(n)
    pm = n % 4
    rows = []
    for H, gens in sorted(subs.items(), key=lambda kv: -len(kv[0])):
        orb, sizes = orbits(n, H)
        if not lo <= len(sizes) <= hi:
            continue
        counts = {0: 1.0}
        for s in sizes:
            nxt = dict(counts)
            for t, c in counts.items():
                nxt[t + s] = nxt.get(t + s, 0.0) + c
            counts = nxt
        pool = lambda r: counts.get((n - r) // 2, 0.0) if (n - r) % 2 == 0 else 0.0
        admissible = [q for q in patterns if all(pool(r) > 0 for r in q)]
        if not admissible:
            continue
        Hm = closure(list(H) + [n - 1])
        corb, _ = orbits(n, Hm)
        reps = [int(np.flatnonzero(corb == k)[0]) for k in range(1, corb.max() + 1)]
        S = np.zeros((len(reps), len(sizes), len(sizes)))
        for c, s in enumerate(reps):
            np.add.at(S[c], (orb, orb[(np.arange(n) + s) % n]), 1)
        stats = {}
        for r in sorted({abs(x) for q in admissible for x in q}):
            Y = []
            for _ in range(400):
                Z = np.where(rng.random((20000, len(sizes))) < 0.5, 1.0, -1.0)
                Y.append(Z[np.abs(Z @ sizes) == r])
                if sum(len(z) for z in Y) >= samples:
                    break
            Y = np.concatenate(Y)[:samples]
            if len(Y):
                stats[r] = class_stats(Y, S, pm) + (pool(r),)
        best = None
        for q in admissible:
            if any(abs(r) not in stats for r in q):
                continue
            lE = sum(log10(stats[abs(r)][3]) for r in q) + log10_match_probability(q, stats, -pm)
            lN = min(log10(stats[abs(r)][3]) for r in q)
            if lN <= log_list:
                lW = 2 * lN - lE
            else:
                lW = 3 * lN - lE - log_list - 0.5 * log10(6 / pi) * (len(reps) - 1)
            if best is None or lW < best[0]:
                best = (lW, q, lE, lN)
        if best and math.isfinite(best[2]):
            rows.append((best[0], n, len(H), gens, len(sizes), len(reps), best[1], best[2], best[3]))
    return rows


def main():
    ap = argparse.ArgumentParser(description="Rank multiplier structures for Goethals-Seidel searches.")
    ap.add_argument("n", type=int, nargs="+", help="odd n (target order 4n)")
    ap.add_argument("--min-orbits", type=int, default=12)
    ap.add_argument("--max-orbits", type=int, default=110)
    ap.add_argument("--list-size", type=float, default=1e9, help="list size L assumed for the matcher")
    ap.add_argument("--samples", type=int, default=3000, help="random sequences per row sum")
    a = ap.parse_args()
    rng = np.random.default_rng(1)
    print(f"{'log10 W':>8} {'n':>6} {'|H|':>5} {'gens':>10} {'orbits':>6} {'classes':>7}  "
          f"{'row sums':<22} {'log10 E':>8} {'log10 N':>8}")
    rows = [r for n in a.n for r in triage(n, a.min_orbits, a.max_orbits, log10(a.list_size), a.samples, rng)]
    for lW, n, h, gens, no, nc, q, lE, lN in sorted(rows):
        print(f"{lW:8.1f} {n:6d} {h:5d} {str(gens):>10} {no:6d} {nc:7d}  {str(q):<22} {lE:8.1f} {lN:8.1f}")


if __name__ == "__main__":
    main()
