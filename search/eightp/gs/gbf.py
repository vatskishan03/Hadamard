"""INDEPENDENT G-level brute force for the REAL GS-type plug-ins (four free blocks) over G = K x F_r (K abelian, F_r = GF(r), additive group Z_p^e).
No Paley / s,t,e algebra: a block is a +-1 function on G invariant under the multiplier group generated by {1} x S (S = squares of F_r*) and, for every generator
(units u, phi), the map (k, a) -> (u k, c a) with c a square (phi = +1) or non-square (phi = -1).  The orbits of this permutation group are computed numerically.
PAF over G by integer arithmetic.  The target is F(0) = 4|G|, F(g) = -Gamma(g) for g != 0 with Gamma(g) = 4 sum_{chi in T} Re chi(k(g))  (mode 'gs': 0, 'spence': T = {1}).
count_G returns the exact number of ORDERED quadruples (A, B, C, D) of invariant +-1 functions with sum PAF = F."""
import numpy as np, itertools, math, sys, time
from idx import GF, Abel, factor_prime_power
from gbrute import build, orbits


def target_G(Kmods, r, mode, T):
    n = int(np.prod(Kmods)) * r
    Kg = Abel(list(Kmods))
    if mode == 'gs': Gam = np.zeros(Kg.n)
    else:
        if mode == 'spence': T = [tuple([0] * len(Kmods))]
        Gam = np.zeros(Kg.n)
        for c in T:
            Gam += 4 * np.cos(2 * np.pi * (Kg.el * np.array(c)[None, :] / np.array(Kmods)[None, :]).sum(1))
    Gam = np.rint(Gam).astype(np.int64)
    F = np.repeat(-Gam, r).astype(np.int64); F[0] = 4 * n
    return F


def paf_int(G, X, reps):
    """exact integer PAF(g) = sum_h x(h) x(h+g) for rows of X (M, |G|), g in reps"""
    X = X.astype(np.int32); out = np.zeros((X.shape[0], len(reps)), dtype=np.int32)
    for j, g in enumerate(reps):
        sh = G.add[np.arange(G.n), g]                       # h + g
        out[:, j] = (X * X[:, sh]).sum(1)
    return out


def count_G(Kmods, r, hgens, mode='gs', T=None, maxu=6000, verbose=False):
    F, G, maps, neg = build(Kmods, r, hgens)
    n = G.n
    lab, nor = orbits(n, maps)
    if nor > 20: raise RuntimeError(f'too many orbits {nor}')
    M = 1 << nor
    ids = np.arange(M, dtype=np.int64)
    vals = np.zeros((M, nor), dtype=np.int8)
    for j in range(nor): vals[:, j] = 1 - 2 * ((ids >> j) & 1)
    X = vals[:, lab]
    reps = [g for g in range(n) if g <= int(neg[g])]
    P = paf_int(G, X, reps)
    tgt = target_G(Kmods, r, mode, T)[reps].astype(np.int64)
    # sanity: the target is symmetric under g -> -g
    Tfull = target_G(Kmods, r, mode, T); assert (Tfull[neg] == Tfull).all()
    u, cnt = np.unique(P, axis=0, return_counts=True)
    if verbose: print(f'  G-level: |G|={n}, orbits {nor}, configs {M}, distinct PAF vectors {len(u)}', flush=True)
    if len(u) > maxu: raise RuntimeError(f'too many distinct PAF vectors {len(u)}')
    rng = np.random.default_rng(12345)
    c1 = rng.integers(1, 2 ** 61, len(reps), dtype=np.int64) | 1; c2 = rng.integers(1, 2 ** 61, len(reps), dtype=np.int64) | 1
    h1 = (u.astype(np.int64) * c1).sum(1); h2 = (u.astype(np.int64) * c2).sum(1)
    t1 = int((tgt * c1).sum()); t2 = int((tgt * c2).sum())
    # pair sums of the list with itself (ordered pairs)
    k1 = (h1[:, None] + h1[None, :]).ravel(); k2 = (h2[:, None] + h2[None, :]).ravel()
    mult = (cnt[:, None].astype(np.float64) * cnt[None, :]).ravel()
    order = np.lexsort((k2, k1)); k1 = k1[order]; k2 = k2[order]; mult = mult[order]
    brk = np.concatenate([[True], (k1[1:] != k1[:-1]) | (k2[1:] != k2[:-1])])
    gid = np.cumsum(brk) - 1
    U1 = k1[brk]; U2 = k2[brk]; C = np.bincount(gid, weights=mult)
    # count = sum over distinct pair-sums v of C(v) * C(target - v)
    n1 = np.int64(t1) - U1; n2 = np.int64(t2) - U2
    lo = np.searchsorted(U1, n1, 'left'); hi = np.searchsorted(U1, n1, 'right')
    total = 0.0
    for i in np.flatnonzero(hi > lo):
        for j in range(lo[i], hi[i]):
            if U2[j] == n2[i]: total += C[i] * C[j]
    return int(round(total)), dict(orbits=nor, configs=M, distinct=len(u))

if __name__ == '__main__':
    import json
    Kmods = json.loads(sys.argv[1]); r = int(sys.argv[2]); mode = sys.argv[3]
    hg = json.loads(sys.argv[4]) if len(sys.argv) > 4 else []
    T = json.loads(sys.argv[5]) if len(sys.argv) > 5 else None
    t0 = time.time()
    tot, info = count_G(Kmods, r, [(u, ph) for u, ph in hg], mode, T, verbose=True)
    print('G-level exact ordered count', tot, info, f'[{time.time()-t0:.1f}s]')
