"""Gaussian/lattice estimator for the octic orbit-level problem (HEURISTIC).  usage: python3 oest.py v "[gens]"   prints log2 E[#normalised solutions].
Calibration against the exhaustive counts of oskew (log2 of the estimate / log2 of the exact count): 21.95 / 21.94 (v = 3), 14.34 / 14.69 (v = 7 <2>),
25.6 / 27.8 (v = 13 <3>), 3.95 / 13.91 (v = 61 <12>): accurate for h = 1 and 3, increasingly conservative with h (by 2 to 10 bits for h = 3 .. 15).
log2 E[#solutions] = log2(#tuples) + log2 P(sum of 4 PAF vectors = 0) + log2 P(DC)  [DC left out: the DC sum is implied by the PAF equations at the trivial character? no: DC is an extra equation; handled by 'dc' flag]
P(sum PAF = 0): Gaussian density at 0 of the empirical covariance (blockwise per lag-class pair) times the covolume of the lattice generated by the sampled sums."""
import numpy as np, math, sys, json, os
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from octic import *
from dcfeas import orbit_data
from sympy import Matrix
rng=np.random.default_rng(5)
A16=np.array(alphabet())
def negcode_vec(c): return np.array([-c[0],c[3],c[2],c[1]])
def sample_block(sz,neg,skew,n):
    U=np.zeros((n,4),dtype=np.int64)
    if skew:
        c=rng.choice([-1,1]); d=rng.choice([-1,1]); U[0]=[1,c,d,c]
        for a in range(1,n):
            if a<neg[a]:
                u=A16[rng.integers(16)]; U[a]=u; U[neg[a]]=negcode_vec(u)
    else:
        for a in range(n): U[a]=A16[rng.integers(16)]
    return U
TP=np.zeros((16,16,4),dtype=np.int64)
for p in range(16):
    for q in range(16): TP[p,q]=zmul(A16[p],zconj(A16[q]))
CODE={tuple(c):i for i,c in enumerate(A16.tolist())}
def paf_classes(U,Nt,cls,n,sz=None):
    e=np.array([CODE[tuple(u)] for u in U.tolist()])
    G=TP[e[None,:],e[:,None]]        # G[a,b]=U_b conj U_a  -> (n,n,4)
    out=[np.tensordot(Nt[c],G,axes=([0,1],[0,1])) for c in cls]
    q=sum(sz[a]*G[a,a,1] for a in range(n))
    out.append(np.array([q,0,0,0],dtype=np.int64))
    return np.array(out)
def lattice_covol(vecs):
    """covolume of the lattice generated by the integer row vectors (any dimension): via HNF using sympy on a reduced set"""
    M=Matrix(vecs.tolist())
    from sympy.matrices.normalforms import smith_normal_form
    from sympy import ZZ
    S=smith_normal_form(M,domain=ZZ)
    d=1
    for i in range(min(S.shape)):
        if S[i,i]!=0: d*=abs(int(S[i,i]))
    return d
def estimate(v,gens,nsamp=3000,dc_bits=None):
    H,orb,reps,sz,neg=orbit_data(v,gens); n=len(reps)
    Nt={}
    for c in range(1,n):
        M=np.zeros((n,n),dtype=np.int64); s=reps[c]
        for g in range(v): M[orb[g],orb[(g+s)%v]]+=1
        Nt[c]=M
    cls=[c for c in range(1,n) if c<neg[c]]
    # sample sum of four blocks (A skew + 3 free)
    S=[]
    for t in range(nsamp):
        tot=0
        for X in range(4):
            U=sample_block(sz,neg,X==0,n); tot=tot+paf_classes(U,Nt,cls,n,sz)
        S.append(tot.reshape(-1))
    S=np.array(S,dtype=np.int64)
    mu=S.mean(0); cov=np.cov(S.T)
    # per-class 4x4 blocks
    lg=0.0; k=4
    for i,c in enumerate(cls+[0]):
        if c==0:
            var=cov[4*i,4*i]; d0=mu[4*i]; lg+=math.log2(math.exp(-0.5*d0*d0/var)/math.sqrt(2*math.pi*var)); continue
        sub=cov[4*i:4*i+4,4*i:4*i+4]
        sub=sub+1e-9*np.eye(4)
        # lattice for this class: from samples
        cv=lattice_covol(S[:400,4*i:4*i+4]-S[:400,4*i:4*i+4][0:1]) if False else None
        det=np.linalg.det(sub)
        # Gaussian density at 0 with mean mu_i
        d=mu[4*i:4*i+4]
        dens=math.exp(-0.5*d@np.linalg.solve(sub,d))/math.sqrt((2*math.pi)**4*det)
        lg+=math.log2(max(dens,1e-300))
    # lattice covolume of all sums (joint): use differences of samples (generates the translate-lattice)
    D=S[1:400]-S[0:1]
    D=D[:,[j for j in range(D.shape[1]) if not (j>=4*len(cls) and j%4!=0)]]
    cov_lat=2**(8*len(cls)+2)   # verified = joint Smith form index for n = 3, 5, 7 (v = 7..61)
    lg+=math.log2(cov_lat)
    tuples_bits=2*n+3*(4*n-3)   # A: 2n (4*16^((n-1)/2)), B,C,D: 2*16^(n-1)
    return dict(v=v,n=n,tuples_bits=tuples_bits,eq_bits=-lg,lat_index=cov_lat,logN=tuples_bits+lg,mean_nonzero=float(np.abs(mu).max()))
