"""INDEPENDENT G-level brute force for the plug-in Szollosi arrays over G = K x F_q (K abelian, F_q = GF(q) additive group Z_p^e).
No Paley / s,t,e algebra is used: blocks are +-1 functions on G invariant under the multiplier group H_G generated by
   {1} x S (S = squares of F_q*)  and, for each generator (units u, phi): (k, a) -> (u k, c a) with c a square (phi = +1) or non-square (phi = -1);
A, B are in addition symmetric (f(-g) = f(g)); the orbits of H_G (and -1 for A, B) are computed numerically.  A, B, C, D in {+-1}^G (plain)
or A, B in {0,+-1} with zero at the identity ('zd', C, D in +-1).  The condition is  sum PAF = target * delta_G  with target = 4|G| (plain) or 4|G| - 2 (zd).
count_G(...) returns the exact number of ordered quadruples (A, B, C, D) (A, B from the AB list, C, D from the CD list)."""
import numpy as np, itertools, math, sys, time
from idx import GF, Abel, factor_prime_power
from math import gcd


def build(Kmods, q, hgens):
    p, e = factor_prime_power(q)
    F = GF(p, e)
    mods = list(Kmods) + [p] * e
    G = Abel(mods)
    nK = int(np.prod(Kmods)) if len(Kmods) else 1
    Kg = Abel(list(Kmods))
    # squares / nonsquares of F_q*
    sq = sorted({int(F.mul[x, x]) for x in range(1, q)})
    nonsq = [x for x in range(1, q) if x not in set(sq)]
    gen_maps = []                                  # permutations of G
    def perm_from(kperm, c):
        pm = np.zeros(G.n, dtype=np.int64)
        for k in range(nK):
            for a in range(q):
                pm[k * q + a] = int(kperm[k]) * q + int(F.mul[c, a]) if c is not None else int(kperm[k]) * q + a
        return pm
    ident = np.arange(nK)
    for s in sq:
        gen_maps.append(perm_from(ident, s))
    for (units, phi) in hgens:
        r = len(Kmods)
        kperm = np.zeros(nK, dtype=np.int64)
        isM = (not np.isscalar(units)) and len(units) and not np.isscalar(units[0])
        if isM: Mx = np.array(units, dtype=np.int64)
        else: u = np.array([int(units)] * r if np.isscalar(units) else [int(x) for x in units])
        for k in range(nK):
            el = Kg.el[k]
            img = ((Mx @ el) % np.array(Kmods)) if isM else ((el * u) % np.array(Kmods))
            kperm[k] = int((img * Kg.w).sum())
        c = sq[0] if phi == 1 else nonsq[0]
        gen_maps.append(perm_from(kperm, c))
    # -1 map
    neg = np.zeros(G.n, dtype=np.int64)
    for k in range(nK):
        for a in range(q):
            neg[k * q + a] = int(Kg.neg[k]) * q + F.neg(a)
    return F, G, gen_maps, neg


def orbits(n, maps):
    parent = list(range(n))
    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]; x = parent[x]
        return x
    for pm in maps:
        for x in range(n):
            a, b = find(x), find(int(pm[x]))
            if a != b: parent[a] = b
    roots = {}
    lab = np.zeros(n, dtype=np.int64)
    for x in range(n):
        r = find(x)
        if r not in roots: roots[r] = len(roots)
        lab[x] = roots[r]
    return lab, len(roots)


def block_list(G, lab, nor, zero_orbit=None):
    """all +-1 assignments to the orbits (zero_orbit forced to 0) as an (M, |G|) int8 array"""
    free = [o for o in range(nor) if o != zero_orbit]
    M = 1 << len(free)
    ids = np.arange(M, dtype=np.int64)
    vals = np.zeros((M, nor), dtype=np.int8)
    for j, o in enumerate(free):
        vals[:, o] = 1 - 2 * ((ids >> j) & 1)
    return vals[:, lab]


def paf_batch(G, X):
    """periodic autocorrelations PAF(g) = sum_h x(h) x(h+g) for a batch (M, |G|) -> (M, |G|) int64"""
    M = X.shape[0]
    out = np.zeros((M, G.n), dtype=np.int64)
    for i in range(0, M, 4096):
        a = X[i:i + 4096].astype(float).reshape((-1,) + tuple(G.mods))
        axes = tuple(range(1, a.ndim))
        f = np.fft.fftn(a, axes=axes)
        r = np.fft.ifftn(f * np.conj(f), axes=axes).real
        out[i:i + 4096] = np.rint(r).astype(np.int64).reshape(len(a), -1)
    return out


def count_G(Kmods, q, hgens, mode="plain", want=0, verbose=False, maxpairs=3e7):
    F, G, maps, neg = build(Kmods, q, hgens)
    n = G.n
    labC, nC = orbits(n, maps)
    labA, nA = orbits(n, maps + [neg])
    zeroA = int(labA[0]) if mode == 'zd' else None
    if nC > 18 or nA > 20: raise RuntimeError(f'G-level lists too large: orbits AB {nA} CD {nC}')
    XA = block_list(G, labA, nA, zeroA); XC = block_list(G, labC, nC, None)
    if verbose: print(f'  G-level: |G|={n}, orbits AB {nA} CD {nC}; lists {len(XA)} {len(XC)}', flush=True)
    # AB must be symmetric: guaranteed by orbits; verify
    assert (XA[:, neg] == XA).all()
    PA = paf_batch(G, XA); PC = paf_batch(G, XC)
    # reduce to representatives g <= -g (PAF(-g) = PAF(g) always)
    reps = [g for g in range(n) if g <= int(neg[g])]
    PA = PA[:, reps]; PC = PC[:, reps]
    target = np.zeros(len(reps), dtype=np.int64)
    target[reps.index(0)] = 4 * n if mode == 'plain' else 4 * n - 2
    # dedupe by PAF vector with multiplicity
    def dd(P):
        u, inv, cnt = np.unique(P, axis=0, return_inverse=True, return_counts=True)
        return u, cnt
    uA, cA = dd(PA); uC, cC = dd(PC)
    if verbose: print(f'  distinct PAF vectors: AB {len(uA)} CD {len(uC)}', flush=True)
    if len(uA) * len(uC) > maxpairs: raise RuntimeError(f'too many pairs {len(uA)*len(uC)}')
    rng = np.random.default_rng(99)
    coef = rng.integers(1, 2 ** 61, len(reps), dtype=np.int64) | 1
    hA = (uA * coef).sum(1); hC = (uC * coef).sum(1); hT = int((target * coef).sum())
    left = (hA[:, None] + hC[None, :]).ravel()
    mult = (cA[:, None].astype(np.float64) * cC[None, :]).ravel()
    order = np.argsort(left, kind='stable'); ls = left[order]; ms = mult[order]
    cm = np.concatenate([[0], np.cumsum(ms)])
    total = 0.0
    for b in range(len(uA)):
        need = np.int64(hT) - hA[b] - hC
        lo = np.searchsorted(ls, need, 'left'); hi = np.searchsorted(ls, need, 'right')
        total += float(((cm[hi] - cm[lo]) * cA[b] * cC).sum())
    return total, (nA, nC, len(XA), len(XC))


if __name__ == '__main__':
    import json
    Kmods = json.loads(sys.argv[1]); q = int(sys.argv[2]); mode = sys.argv[3]
    hg = json.loads(sys.argv[4]) if len(sys.argv) > 4 else []
    t0 = time.time()
    tot, info = count_G(Kmods, q, [(u, ph) for u, ph in hg], mode, verbose=True)
    print('G-level exact ordered count', tot, info, f'[{time.time()-t0:.1f}s]')
