"""hlib.py -- generic model + kernels for the exact compression-chain engine (driver: hchain.py).

Problem.  G = Z_{m_1} x ... x Z_{m_r} (mixed radix, first coordinate slowest, as verify/verify.py; the moduli need not be coprime or
prime powers: Z4^3 x Z13 is fine).  S <= G is given by generators (`S_gens`; legacy: `nq` = the first nq coordinates form Q = G/S with
S = 0 x rest); Q = G/S, k = |Q|; the cosets of S are numbered in order of their smallest element (mixed-radix order, as the repository's
build_bordered_gs does).
Four +-1 sequences x_0..x_3 on G, each constant on the orbits of H = <gens> (matrices acting on coordinate column
vectors, row i reduced mod m_i), with prescribed coset sums y_i (one number per coset) and

        sum_i PAF_{x_i}(d) = tgt(d)   for all d != 0,        PAF_x(d) = sum_t x(t) x(t + d),

tgt = t_in on S \\ {0}, t_out off S (for the Theorem-7 family with k = |Q| = 4: -12 and +4); tgt(0) = 4 v.

Levels.  A level is a quotient pi: G -> G_l = G/N given by an H-invariant subgroup N (generators, `{"ker": [...]}`; legacy: the kept
coordinates `[j, ...]`, N = the dropped coordinates).  N need not be a coordinate subgroup (split or non-split G); the cosets of N are
numbered in order of their smallest element.  The
compression Y(a) = sum_{pi(g) = a} x(g) of an H-invariant sequence is constant on the H-orbits of G_l, and
sum_i PAF_{Y_i}(t) = sum_{s in pi^-1(t)} tgt(s) on G_l.  Coordinates of a level = its quotient orbits.
"""
