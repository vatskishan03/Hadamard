"""nm_cmp.py -- observed / predicted near-miss counts of nm_5912.py (HEURISTIC calibration of the Gaussian-lattice estimate at the first level-2 step; README, "Order 5912").
Prediction for one level-1 instance: the t-sign vectors of each block that pass the exact row-sum filter form a fibre of key vectors in Z^14 (7 I-lags, 7 Q-lags: the keys of gl2.c).  The number of
quadruples with sum 0 on a coordinate set C is predicted as  n1 n2 n3 n4 det(L_C) N(0; mu_C, Sigma_C),  mu and Sigma the exact mean and covariance of the sum of four independent uniform draws from
the fibres, L_C the lattice generated by (sampled) differences inside the fibres, projected to C.  For every chunk of nm_5912.py (dropped set OM) and every subset Z of OM, the events with residual 0 on Z
are counted and compared with the prediction for C = (not OM) + Z, summed over the instances of the chunk (NSAMP instances per chunk are predicted and scaled).
usage: nm_cmp.py OUTPREFIX NSAMP [MAXCHUNKS]     (one OUTPREFIX must hold runs of a single number of dropped constraints)     prints and writes OUTPREFIX.cmp.json: {obs, prd} indexed by |Z|, i.e. by the number of constraints that are satisfied, 14 - |OM| + |Z|"""
import sys, os, json, math, time, itertools, collections
import numpy as np
