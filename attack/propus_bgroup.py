"""Bordered propus over non-cyclic abelian groups: symmetric Hadamard matrices of order 4(m + 1).

For an abelian group G of order m and +-1 functions A (symmetric, A(-g) = A(g)), B, D on G with
    PAF_A + 2 PAF_B + PAF_D = -4 off 0   and row sums (a, b, d) = (+-2, 0, 0) or (0, 0, +-2),
the propus array P of group-developed blocks (propus_group.propus_matrix) bordered as
    H = [[L, K (x) e^T], [K^T (x) e, P]],   L = -K S K^T / 4   (S the propus array of the row sums, K a Hadamard
matrix of order 4 that makes L a +-1 matrix)
is a symmetric Hadamard matrix of order 4(m + 1) (propus.bordered_matrix for Z_m; the algebra is the same over any
abelian group). This is how the census value v = m + 1 can be reached through groups of order v - 1 instead of v.

Automorphisms of G = Z_{n_1} x ... x Z_{n_k} are enumerated as matrices M with M_ij a multiple of n_i / gcd(n_i, n_j)
(images of the generators), kept when bijective. For every cyclic subgroup <phi> (up to an invariant of its action),
B and D live on the orbits of <phi>, A on the orbits of <phi, -1>; every structure whose pools fit in MAXPOOL is
joined exactly (join4x) for both row patterns, and every hit is rebuilt as a matrix and checked.

  python3 attack/propus_bgroup.py 8,8 [--maxo 30] [--mino 1] [--maxpool 3e7] [--maxwork 1e10] [--maxend 3e5]
Hits go to $HADAMARD_WORK/sym_hits.jsonl (border: true, order, group, automorphism matrix, K).
"""
import argparse, itertools, json, math, os, struct, subprocess, sys, tempfile, time
import numpy as np
from pathlib import Path as _P
sys.path[:0] = [str(_P(__file__).resolve().parent), str(_P(__file__).resolve().parent.parent / 'verify')]
import workdir as W
import spence_lib as L
import propus as PR
import propus_group as PG


def automorphisms(G, maxend):
    """(matrix, permutation) for every automorphism of G (None if the endomorphisms exceed maxend)."""
    n = [int(x) for x in G.mods]; k = len(n)
    choices = []
    for i in range(k):
        for j in range(k):
            step = n[i] // math.gcd(n[i], n[j])
            choices.append(list(range(0, n[i], step)))
    total = math.prod(len(c) for c in choices)
    if total > maxend: return None
    out = []
    C = G.coords
    for entries in itertools.product(*choices):
        M = np.array(entries, dtype=np.int64).reshape(k, k)
        p = G.index(C @ M.T)
        if len(np.unique(p)) == G.v: out.append((M, p))
    return out


def subgroup_perms(p, v):
    """The cyclic group generated by the permutation p, as a list of permutations."""
    ident = np.arange(v)
    out = [ident]; q = p.copy()
    while not np.array_equal(q, ident):
        out.append(q); q = p[q]
    return out


def invariant(G, perms):
    """Isomorphism-type invariant of the action of a cyclic group of automorphisms (orbit sizes on G with element
    orders, for the group and for <group, -1>)."""
    v = G.v
    order = np.array([math.lcm(*[int(m // math.gcd(int(c), int(m))) for c, m in zip(G.coords[g], G.mods)]) if g else 1
                      for g in range(v)])
    lab, k = L.closure_partition(v, perms)
    sig = sorted((int(np.sum(lab == o)), int(order[np.argmax(lab == o)])) for o in range(k))
    lab2, k2 = L.closure_partition(v, list(perms) + [G.neg()])
    sig2 = sorted((int(np.sum(lab2 == o)), int(order[np.argmax(lab2 == o)])) for o in range(k2))
    return (len(perms), tuple(sig), tuple(sig2))


def bordered_group_matrix(G, A, B, D):
    m = G.v; a, b, d = int(A.sum()), int(B.sum()), int(D.sum())
    S = np.array([[a, b, b, d], [b, d, -a, -b], [b, -a, -d, b], [d, -b, b, -a]])
    for K in PR.hadamard4():
        L4 = -(K @ S @ K.T)
        if np.all(np.abs(L4) == 4):
            P = PG.propus_matrix(G, A, B, D)
            M = np.kron(K, np.ones((1, m), dtype=P.dtype))
            return np.block([[L4 // 4, M], [M.T, P]]), K
    return None, None


UNBORDERED = False       # --unbordered: plain propus on G itself (PAF sum 0, order 4|G|, any row-sum pattern)


def mode(G):
    """(T, row patterns, matrix builder returning (H, K), order) for the bordered or the plain propus problem on G."""
    m = G.v
    if UNBORDERED:
        return 0, [p for p in PR.patterns(m)], (lambda A, B, D: (PG.propus_matrix(G, A, B, D), None)), 4 * m
    return -4, [(2, 0, 0), (0, 0, 2)], (lambda A, B, D: bordered_group_matrix(G, A, B, D)), 4 * (m + 1)


def search(G, name, mat, st_ad, st_b, maxpool, maxwork, log):
    m = G.v; pm = m % 4
    T, pats, build, n4 = mode(G)
    found = []
    log(f"m={m} G={list(map(int, G.mods))} {name}: orbits A {st_ad.O}, B/D {st_b.O}, classes {st_ad.C}")
    for ra, rb, rd in pats:
        sizes = [st_ad.pool(ra), st_b.pool(rb), st_b.pool(rd)]
        if min(sizes) == 0 or max(sizes) > maxpool:
            log(f"  rows ({ra}, {rb}, {rd}): pools {[int(s) for s in sizes]} skipped"); continue
        work = float(np.prod(sorted(sizes)[:2]))
        if work > maxwork:
            log(f"  rows ({ra}, {rb}, {rd}): pools {[int(s) for s in sizes]} work {work:.1e} skipped"); continue
        t = time.time()
        def vals(st, Y, scale, chunk=1 << 18):
            out = np.empty((len(Y), st.C), dtype=np.int16)
            for c0 in range(0, len(Y), chunk):
                out[c0:c0 + chunk] = scale * np.rint((st.class_values(Y[c0:c0 + chunk].astype(np.float64)) - pm) / 4)
            return out
        Ya = PR.pool_vectors(st_ad, ra); Yb = PR.pool_vectors(st_b, rb); Yd = PR.pool_vectors(st_b, rd)
        Va = vals(st_ad, Ya, 1); Vb = vals(st_b, Yb, 2); Vd = vals(st_b, Yd, 1)
        Z = np.zeros((1, st_ad.C), dtype=np.int16)
        roles = sorted([(len(Va), 0), (len(Vd), 1), (len(Vb), 2)])
        byrole = {0: Va, 1: Vd, 2: Vb}
        lists = [byrole[roles[0][1]], byrole[roles[1][1]], byrole[roles[2][1]], Z]
        slot = {r: i for i, (_, r) in enumerate(roles)}
        fd, path = tempfile.mkstemp(suffix='.bin', dir=W.tmpdir()); os.close(fd)
        try:
            with open(path, 'wb') as f:
                f.write(struct.pack('iiiii', *[len(x) for x in lists], st_ad.C))
                f.write(np.full(st_ad.C, (T - 4 * pm) // 4, dtype=np.int16).tobytes())
                for x in lists: f.write(np.ascontiguousarray(x).tobytes())
            out = subprocess.run([W.bin('join4x'), path, '1'], capture_output=True, text=True, check=True).stdout
        finally:
            os.remove(path)
        total = int(out.strip().split('TOTAL')[-1])
        log(f"  rows ({ra}, {rb}, {rd}): pools {[int(s) for s in sizes]}: {total} solutions [{time.time() - t:.1f}s]")
        for line in out.splitlines():
            if not line.startswith('SOL'): continue
            ids = list(map(int, line.split()[1:]))
            A = Ya[ids[slot[0]]].astype(np.int64)[st_ad.orb]; D = Yd[ids[slot[1]]].astype(np.int64)[st_b.orb]
            B = Yb[ids[slot[2]]].astype(np.int64)[st_b.orb]
            tot = PG.group_paf(G, A) + 2 * PG.group_paf(G, B) + PG.group_paf(G, D)
            if not (tot[0] == 4 * m and np.all(tot[1:] == T)): log('  WRONG autocorrelations'); continue
            if not np.array_equal(A, A[G.neg()]): log('  A not symmetric'); continue
            Hm, Kb = build(A, B, D)
            ok = Hm is not None and np.array_equal(Hm, Hm.T) and np.array_equal(Hm @ Hm.T, n4 * np.eye(n4, dtype=Hm.dtype))
            log(f"  hit: {'' if UNBORDERED else 'bordered '}symmetric Hadamard of order {n4} {ok}")
            if ok:
                mats = [mat] if mat.ndim == 2 else list(mat)
                rec = dict(n=m, order=n4, border=not UNBORDERED, group=[int(x) for x in G.mods], structure=name,
                           automorphisms=[x.tolist() for x in mats], freeD=True, rows=[int(A.sum()), int(B.sum()), int(D.sum())],
                           K=None if Kb is None else Kb.tolist(), seqs=[''.join('+' if x > 0 else '-' for x in s) for s in (A, B, D)])
                with open(W.hits('sym_hits.jsonl'), 'a') as fh: fh.write(json.dumps(rec) + '\n')
                found.append(rec)
        if found: break
    return found


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('mods'); ap.add_argument('--maxo', type=int, default=30); ap.add_argument('--mino', type=int, default=1)
    ap.add_argument('--maxpool', type=float, default=3e7); ap.add_argument('--maxwork', type=float, default=1e10)
    ap.add_argument('--maxend', type=float, default=3e5)
    ap.add_argument('--pairs', action='store_true', help='also subgroups generated by two automorphisms (one per invariant '
                    'class of the first, any second); only the structures not already seen are searched')
    ap.add_argument('--unbordered', action='store_true', help='plain propus on G (order 4|G|, |G| odd)')
    a = ap.parse_args()
    global UNBORDERED
    UNBORDERED = a.unbordered
    log = lambda s: print(s, flush=True)
    G = L.AbGroup([int(x) for x in a.mods.split(',')])
    t0 = time.time()
    auts = automorphisms(G, a.maxend)
    if auts is None: log(f"G={a.mods}: too many endomorphisms"); return
    log(f"G={a.mods} (order {G.v}): {len(auts)} automorphisms [{time.time() - t0:.1f}s]")
    seen = {}; jobs = []
    for M, p in auts:
        perms = subgroup_perms(p, G.v)
        key = frozenset(tuple(q.tolist()) for q in perms)
        if key in seen: continue
        seen[key] = True
        neg = G.neg()
        if any(np.array_equal(q, neg) for q in perms): continue          # -1 in H: B and D symmetric too (skip)
        inv = invariant(G, perms)
        jobs.append((inv, M, p))
    uniq = {}
    for inv, M, p in jobs:
        uniq.setdefault(inv, (M, p))
    log(f"{len(seen)} cyclic subgroups, {len(jobs)} without -1, {len(uniq)} invariant classes")
    if a.pairs:
        cyc = [(M, p) for _, M, p in jobs]
        firsts = list(uniq.values())
        pairs = {}
        neg = G.neg()
        for M1, p1 in firsts:
            for M2, p2 in cyc:
                lab, k = L.closure_partition(G.v, [p1, p2])
                if k < a.mino or k > a.maxo: continue
                # -1 must stay outside H: test by closing the group (small) and looking for neg
                grp = {tuple(range(G.v))}; frontier = [np.arange(G.v)]
                ok = True
                while frontier and ok:
                    q = frontier.pop()
                    for g in (p1, p2):
                        r = g[q]; t = tuple(r.tolist())
                        if t not in grp:
                            if np.array_equal(r, neg): ok = False; break
                            grp.add(t); frontier.append(r)
                    if len(grp) > 4096: ok = False
                if not ok or len(grp) <= 1: continue
                perms = [np.array(t) for t in grp]
                inv = invariant(G, perms)
                if inv in uniq or inv in pairs: continue
                pairs[inv] = (np.stack([M1, M2]), p1, p2)
        log(f"{len(pairs)} new invariant classes from pairs")
        for inv, (Ms, p1, p2) in pairs.items():
            uniq[inv] = (Ms, (p1, p2))
    todo = []
    for inv, (M, p) in uniq.items():
        gens = list(p) if isinstance(p, tuple) else [p]
        st_b = L.Structure(G, gens); st_ad = L.Structure(G, gens + [G.neg()])
        if a.mino <= st_b.O <= a.maxo: todo.append((st_b.O + st_ad.O, M, st_ad, st_b))
    todo.sort(key=lambda x: x[0])
    log(f"{len(todo)} structures with {a.mino}..{a.maxo} orbits")
    for _, M, st_ad, st_b in todo:
        name = 'aut' + ''.join(str(x) for x in M.flatten())
        if search(G, name, M, st_ad, st_b, a.maxpool, a.maxwork, log):
            log(f"HIT m={G.v} G={a.mods} {name}"); return
    log(f"=== G={a.mods}: none")


if __name__ == '__main__':
    main()
