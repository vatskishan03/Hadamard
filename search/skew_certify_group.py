"""Write a repository certificate for a skew Goethals-Seidel hit over a non-cyclic group Z_m x Z_p^k (a hit of
cp_lowe.py --field, recorded in $HADAMARD_WORK/skew_hits.jsonl with its group and automorphism matrices).

    python3 search/skew_certify_group.py n [index]      # index-th verified group hit for n (default 0)

Writes skew/<4n>/certificate.json (construction "goethals-seidel-group", as verify.build_goethals_seidel_group
reads it), sequences.txt and H<4n>.csv.gz, and checks them with verify/verify.py."""
import gzip, hashlib, json, sys
from pathlib import Path
import numpy as np
ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "verify"), str(ROOT / "search")]
import verify
import workdir as W
from certify import write_certificate


def subgroup_order(mats, mods):
    """Order of the group generated by the automorphism matrices (as permutations of G)."""
    mods = np.array(mods, dtype=np.int64); v = int(np.prod(mods))
    coords = np.array(np.unravel_index(np.arange(v), tuple(int(x) for x in mods))).T.astype(np.int64)
    perms = [np.ravel_multi_index(tuple(((coords @ np.array(M, dtype=np.int64).T) % mods).T), tuple(int(x) for x in mods))
             for M in mats]
    seen = {tuple(range(v))}; frontier = [np.arange(v)]
    while frontier:
        new = []
        for P in frontier:
            for Q in perms:
                R = Q[P]; key = tuple(R.tolist())
                if key not in seen: seen.add(key); new.append(R)
        frontier = new
    return len(seen)


def main():
    n = int(sys.argv[1]); k = int(sys.argv[2]) if len(sys.argv) > 2 else 0
    hits = [json.loads(l) for l in open(W.hits())]
    hits = [h for h in hits if h["n"] == n and h["hadamard"] and h["skew"] and "group" in h]
    h = hits[k]
    order = 4 * n
    cert = {"order": order, "construction": "goethals-seidel-group", "skew": True, "group": h["group"],
            "structure": h.get("structure", h.get("method", "")),
            "automorphisms": h["automorphisms"], "subgroup_order": subgroup_order(h["automorphisms"], h["group"]),
            "rowsums": h["pattern"], "sequences": h["seqs"]}
    H, _ = verify.build_goethals_seidel_group(cert)
    data = verify.canonical_csv(H)
    cert["sha256"] = hashlib.sha256(data).hexdigest()
    out = ROOT / "skew" / str(order); out.mkdir(parents=True, exist_ok=True)
    write_certificate(cert, out / "certificate.json")
    (out / "sequences.txt").write_text("".join(s + "\n" for s in h["seqs"]))
    with gzip.open(out / f"H{order}.csv.gz", "wb", compresslevel=9) as f: f.write(data)
    m, digest = verify.check(out)
    print(f"skew order {m}: group {h['group']}, |H| = {cert['subgroup_order']}, rows {cert['rowsums']}, sha256 {digest}")


if __name__ == "__main__":
    main()
