# --------------------------------------------------------------------------------------------- group helpers
class Group:
    def __init__(self, mods):
        self.mods = np.array(mods, dtype=np.int64); self.r = len(mods)
        self.v = int(np.prod(self.mods))
        self.coords = np.array(np.unravel_index(np.arange(self.v), tuple(int(m) for m in mods))).T.astype(np.int64)

    def index(self, C):
        C = np.asarray(C, dtype=np.int64) % self.mods
        return np.ravel_multi_index(tuple(C.T), tuple(int(m) for m in self.mods))

    def perm_from_matrix(self, A):
        A = np.asarray(A, dtype=np.int64)
        p = self.index(self.coords @ A.T)
        if len(np.unique(p)) != self.v:
            raise ValueError("matrix is not a bijection of G")
        rng = np.random.default_rng(0)
        a, b = rng.integers(0, self.v, 64), rng.integers(0, self.v, 64)
        if not np.array_equal(p[self.index(self.coords[a] + self.coords[b])], self.index(self.coords[p[a]] + self.coords[p[b]])):
            raise ValueError("matrix is not additive on G")
        return p

    def neg(self):
        return self.index(-self.coords)

    def translate(self, g):
        return self.index(self.coords + self.coords[g])


def subgroup_elements(G, gens):
    """sorted element indices of the subgroup of G generated by the coordinate vectors `gens`"""
    gi = [int(G.index(np.array(g, dtype=np.int64))) for g in gens]
    K = {0}; frontier = [0]
    while frontier:
        x = frontier.pop()
        for g in gi:
            y = int(G.index(G.coords[x] + G.coords[g]))
            if y not in K: K.add(y); frontier.append(y)
    return np.array(sorted(K), dtype=np.int64)


def coset_structure(G, gens):
    """cosets of the subgroup generated by gens, numbered in order of their smallest element:
    returns (lab [v], kernel mask [v], rep [#cosets] = smallest element of each coset)"""
    Kel = subgroup_elements(G, gens)
    lab = -np.ones(G.v, dtype=np.int64); q = 0; rep = []
    for g in range(G.v):
        if lab[g] < 0:
            lab[G.index(G.coords[g][None, :] + G.coords[Kel])] = q; rep.append(g); q += 1
    ker = np.zeros(G.v, dtype=bool); ker[Kel] = True
    return lab, ker, np.array(rep, dtype=np.int64)


class QGroup:
    """the quotient group G/N (cosets labelled by `lab`), with the Group interface used by the engine (v, translate, neg)"""

    def __init__(self, G, lab, rep):
        self.G = G; self.lab = lab; self.rep = rep; self.v = len(rep)

    def translate(self, d):
        return self.lab[self.G.index(self.G.coords[self.rep] + self.G.coords[self.rep[d]][None, :])]

    def neg(self):
        return self.lab[self.G.index(-self.G.coords[self.rep])]


def closure_partition(v, perms):
    """Orbits of the group generated by perms; labels in order of the smallest element."""
    lab = -np.ones(v, dtype=np.int64); k = 0
    for s in range(v):
        if lab[s] >= 0: continue
        lab[s] = k; stack = [s]
        while stack:
            x = stack.pop()
            for p in perms:
                y = int(p[x])
                if lab[y] < 0:
                    lab[y] = k; stack.append(y)
        k += 1
    return lab, k


def _tensors(G, orb, O, cls, C, reps):
    S = np.zeros((C, O, O), dtype=np.int64)
    for c, d in enumerate(reps):
        t = G.translate(d)
        S[c] = np.bincount(orb * O + orb[t], minlength=O * O).reshape(O, O)
    return S


class Level:
    """Quotient G/N of G by an H-invariant subgroup N, with the H action, orbit weights, classes and targets.
    spec: a list of KEPT coordinates (legacy: N = the dropped coordinates), or {"ker": [generators of N]} (or {"keep": [...]})."""

    def __init__(self, P, spec, name=None):
        if isinstance(spec, dict) and 'ker' in spec:
            gens = [list(g) for g in spec['ker']]; self.name = name or spec.get('name') or 'ker' + str(len(gens))
            keep = None
        else:
            keep = list(spec['keep'] if isinstance(spec, dict) else spec)
            gens = []
            for j in range(P.G.r):
                if j not in keep:
                    e = [0] * P.G.r; e[j] = 1; gens.append(e)
            self.name = name or 'keep' + ''.join(map(str, keep))
        self.keep = keep; self.kergens = gens
        lab, ker, rep = coset_structure(P.G, gens)
        self.ker = ker; self.lab = lab; self.rep = rep
        self.GK = QGroup(P.G, lab, rep)
        qperms = []
        for p in P.perms:
            q = -np.ones(self.GK.v, dtype=np.int64); q[lab] = lab[p]
            if not np.array_equal(q[lab], lab[p]):
                raise ValueError("level %s: kernel is not H-invariant" % self.name)
            qperms.append(q)
        self.orb, self.O = closure_partition(self.GK.v, qperms)
        self.sizes = np.bincount(self.orb, minlength=self.O)
        cl, _ = closure_partition(self.GK.v, qperms + [self.GK.neg()])
        zero = cl[0]; labels = sorted(set(cl.tolist()) - {zero})
        remap = {l: i for i, l in enumerate(labels)}
        self.cls = np.array([remap.get(int(c), -1) for c in cl]); self.C = len(labels)
        self.reps = [int(np.flatnonzero(self.cls == c)[0]) for c in range(self.C)]
        self.S = _tensors(self.GK, self.orb, self.O, self.cls, self.C, self.reps)
        # orbit maps and weights
        self.uof = np.zeros(P.O, dtype=np.int64); self.w = np.zeros(P.O, dtype=np.int64)
        for o in range(P.O):
            mem = np.flatnonzero(P.orb == o)
            u = int(self.orb[lab[mem[0]]]); self.uof[o] = u
            cnt = np.bincount(lab[mem], minlength=self.GK.v)
            nz = cnt[self.orb == u]
            if not (nz.min() == nz.max() and len(mem) == nz.sum()):
                raise ValueError("level %s: non-uniform fibres" % self.name)
            self.w[o] = int(nz[0])
        # targets: T[0] = sum over the kernel, T[1 + c] = sum over the fibre of the class representative
        byl = np.bincount(lab, weights=P.tgt.astype(np.float64), minlength=self.GK.v)
        self.T = np.array([byl[0]] + [byl[r] for r in self.reps]).round().astype(np.int64)
        # matrix form for batch PAF
        self._M = np.ascontiguousarray(self.S.transpose(1, 0, 2).reshape(self.O, self.C * self.O)).astype(np.float64)
        # bit-matrix: coordinate vector of an orbit-sign mask:  c = 2 (b @ Wm) - Wm.sum(0)
        self.Wm = np.zeros((P.O, self.O), dtype=np.int64)
        for o in range(P.O): self.Wm[o, self.uof[o]] = self.w[o]

    def paf(self, Cm):
        """(n x (1 + C)) integer vector: sum_u |u| c_u^2 and c S_c c for each class, for compressed vectors Cm (n x O)."""
        Cm = np.asarray(Cm, dtype=np.float64)
        n = len(Cm); out = np.empty((n, 1 + self.C), dtype=np.int32)
        out[:, 0] = np.rint((Cm ** 2) @ self.sizes)
        B = 1 << 16
        for i in range(0, n, B):
            X = Cm[i:i + B]
            Z = (X @ self._M).reshape(len(X), self.C, self.O)
            out[i:i + B, 1:] = np.rint(np.einsum('ncp,np->nc', Z, X))
        return out

    def implied_by(self, other):
        """True when this level is a quotient of `other` (ker(other) <= ker(self)): its compression is determined by other's"""
        return bool(np.all(self.ker[other.ker]))

    def of_masks(self, masks, nbits, B=65536):
        """compressed vectors of orbit-sign masks (bit 1 = +1): c = 2 (b @ Wm) - Wm.sum(0), in float32 (exact, values < 2^24)"""
        out = np.empty((len(masks), self.O), dtype=np.int32)
        Wf = self.Wm.astype(np.float32); ws = self.Wm.sum(0).astype(np.float32)
        sh = np.arange(nbits, dtype=np.uint64)
        for i in range(0, len(masks), B):
            b = ((masks[i:i + B, None] >> sh) & np.uint64(1)).astype(np.float32)
            out[i:i + B] = np.rint(2 * (b @ Wf) - ws).astype(np.int32)
        return out


def group_masks(masks, splits, nbits, B=1 << 16, seed=11):
    """exact grouping of orbit-sign masks by their compressions on all split levels, in chunks (no n x D matrix is held):
    returns (gvec [G x D] int32 sorted lexicographically, gid [n])."""
    n = len(masks)
    R = np.random.default_rng(seed).integers(1, 2 ** 62, size=sum(sp.O for sp in splits), dtype=np.int64).astype(np.uint64)
    def keys(sl):
        return np.concatenate([sp.of_masks(masks[sl], nbits) for sp in splits], axis=1)
    hh = np.empty(n, dtype=np.uint64)
    for i in range(0, n, B):
        kc = keys(slice(i, i + B)); hh[i:i + B] = (kc.astype(np.int64).astype(np.uint64) * R).sum(1, dtype=np.uint64)
    order = np.argsort(hh, kind='stable'); hs = hh[order]; del hh
    first = np.concatenate([[True], hs[1:] != hs[:-1]]); del hs
    gid_sorted = np.cumsum(first) - 1
    rep = order[np.flatnonzero(first)]
    gvec = np.concatenate([np.concatenate([sp.of_masks(masks[rep[j:j + B]], nbits) for sp in splits], axis=1) for j in range(0, max(len(rep), 1), B)], axis=0)
    gid = np.empty(n, dtype=np.int64); gid[order] = gid_sorted; del order, gid_sorted
    for i in range(0, n, B):                      # exact verification of the grouping (guards against a 64-bit collision)
        if not np.array_equal(keys(slice(i, i + B)), gvec[gid[i:i + B]]):      # 64-bit collision (never observed): exact fallback
            allk = np.concatenate([keys(slice(j, j + B)) for j in range(0, n, B)], axis=0)
            return group_rows(allk, seed)
    lo = np.lexsort(tuple(gvec[:, j] for j in range(gvec.shape[1] - 1, -1, -1)))
    rank = np.empty(len(lo), dtype=np.int64); rank[lo] = np.arange(len(lo))
    return gvec[lo], rank[gid]


def group_rows(keys, seed=11):
    """exact grouping of integer rows: (unique rows, inverse), via a 64-bit hash with an exact re-check (falls back to np.unique)"""
    keys = np.ascontiguousarray(keys)
    n = len(keys)
    R = np.random.default_rng(seed).integers(1, 2 ** 62, size=keys.shape[1], dtype=np.int64).astype(np.uint64)
    h = (keys.astype(np.int64).astype(np.uint64) * R).sum(1, dtype=np.uint64)
    order = np.argsort(h, kind='stable'); hs = h[order]
    first = np.concatenate([[True], hs[1:] != hs[:-1]])
    gid_sorted = np.cumsum(first) - 1
    rep = order[np.flatnonzero(first)]
    if not np.array_equal(keys[order], keys[rep][gid_sorted]):
        u, inv = np.unique(keys, axis=0, return_inverse=True)
        return u, inv.ravel()
    inv = np.empty(n, dtype=np.int64); inv[order] = gid_sorted
    # deterministic order of groups: lexicographic on the rows
    u = keys[rep]
    lo = np.lexsort(tuple(u[:, j] for j in range(u.shape[1] - 1, -1, -1)))
    rank = np.empty(len(lo), dtype=np.int64); rank[lo] = np.arange(len(lo))
    return u[lo], rank[inv]


class Problem:
    def __init__(self, cfg):
        self.cfg = cfg
        self.G = G = Group(cfg['mods']); self.v = G.v
        if 'S_gens' in cfg:
            self.S_gens = [list(g) for g in cfg['S_gens']]; self.nq = int(cfg.get('nq', 0))
        else:                                              # legacy: Q = first nq coordinates
            self.nq = int(cfg['nq']); self.S_gens = []
            for j in range(self.nq, G.r):
                e = [0] * G.r; e[j] = 1; self.S_gens.append(e)
        self.cos, self.Smask, self.Qrep = coset_structure(G, self.S_gens)
        self.k = len(self.Qrep)
        self.perms = [G.perm_from_matrix(A) for A in cfg['gens']]
        self.orb, self.O = closure_partition(G.v, self.perms)
        if self.O > 64: raise ValueError("more than 64 orbits per block are not supported")
        self.sizes = np.bincount(self.orb, minlength=self.O)
        assert self.orb[0] == 0 and self.sizes[0] == 1
        cl, _ = closure_partition(G.v, self.perms + [G.neg()])
        zero = cl[0]; labels = sorted(set(cl.tolist()) - {zero})
        remap = {l: i for i, l in enumerate(labels)}
        self.cls = np.array([remap.get(int(c), -1) for c in cl]); self.C = len(labels)
        self.reps = [int(np.flatnonzero(self.cls == c)[0]) for c in range(self.C)]
        self.csize = np.bincount(self.cls[self.cls >= 0], minlength=self.C)
        if 'tgt' in cfg:                                   # explicit per-element target (tests)
            self.tgt = np.array(cfg['tgt'], dtype=np.int64)
        else:
            self.tgt = np.where(self.cos == 0, cfg['t_in'], cfg['t_out']).astype(np.int64); self.tgt[0] = 4 * self.v
        for s in range(1, self.v):                       # tgt must be class constant
            pass
        self.tgtc = np.array([self.tgt[r] for r in self.reps], dtype=np.int64)
        assert np.all(self.tgt[1:] == self.tgtc[self.cls[1:]]), "target is not constant on the H,-1 classes (H must preserve S)"
        self.S = _tensors(G, self.orb, self.O, self.cls, self.C, self.reps)
        self._Mf = np.ascontiguousarray(self.S.transpose(1, 0, 2).reshape(self.O, self.C * self.O)).astype(np.float32)
        self.ys = [np.array(y, dtype=np.int64) for y in cfg['ys']]
        self.Qlevel = Level(self, {'ker': self.S_gens}, name='Q')
        self.levels = [Level(self, kp) for kp in cfg.get('levels', [])]
        self.splits = [Level(self, kp) for kp in cfg.get('split', [])]
        self.rep_of = np.array([np.flatnonzero(self.orb == o)[0] for o in range(self.O)])
        self.yorb = [self.y_orbit_vector(y) for y in self.ys]
        self._shift = None
        self._localcache = {}
        self.normalizer = self._build_normalizer(cfg.get('normalizer', []))
        self.Rh = np.random.default_rng(20250101).integers(1, 2 ** 62, size=4096, dtype=np.int64).astype(np.uint64)

    # ---- normalizer: automorphisms nu of G with nu H nu^-1 = H, tgt o nu = tgt, y o nu = y map solutions to solutions ----
    def _build_normalizer(self, spec):
        mats = []
        if spec == 'units' or (isinstance(spec, list) and 'units' in spec):
            if 'S_gens' in self.cfg: raise ValueError("normalizer 'units' is only defined for the legacy coordinate form (nq); give matrices")
            for j in range(self.nq, self.G.r):
                m = int(self.G.mods[j])
                # a generator of the unit group of Z_m for m an odd prime power or prime (primitive root); other m: all units < m coprime
                cands = [u for u in range(2, m) if math.gcd(u, m) == 1]
                gens = []
                grp = {1}
                for u in cands:
                    if u not in grp:
                        gens.append(u)
                        new = set(grp)
                        frontier = list(grp)
                        while frontier:
                            x = frontier.pop()
                            for g in gens:
                                y = x * g % m
                                if y not in new: new.add(y); frontier.append(y)
                        grp = new
                for u in gens:
                    A = np.eye(self.G.r, dtype=np.int64); A[j, j] = u; mats.append(A)
            spec = [s for s in (spec if isinstance(spec, list) else []) if s != 'units']
        mats += [np.array(A, dtype=np.int64) for A in (spec if isinstance(spec, list) else [])]
        out = []
        for A in mats:
            nu = self.G.perm_from_matrix(A)
            # nu maps H-orbits onto H-orbits
            for o in range(self.O):
                if len(np.unique(self.orb[nu[self.orb == o]])) != 1: raise ValueError("normalizer element does not normalize H")
            if not np.array_equal(self.tgt[nu], self.tgt): raise ValueError("normalizer element does not preserve the target")
            qp = self.level_perm(self.Qlevel, nu)
            if any(not np.array_equal(yo[qp], yo) for yo in self.yorb): raise ValueError("normalizer element does not preserve the coset sums")
            out.append(nu)
        return out

    def level_perm(self, L, nu):
        """coordinate permutation of level L induced by nu:  c'(u) = c(perm[u]);  checks that nu preserves the kernel"""
        lab = L.lab; q = -np.ones(L.GK.v, dtype=np.int64); q[lab] = lab[nu]
        if not np.array_equal(q[lab], lab[nu]): raise ValueError("normalizer element does not preserve the kernel of level %s" % L.name)
        perm = np.zeros(L.O, dtype=np.int64)
        for u in range(L.O):
            a = int(np.flatnonzero(L.orb == u)[0]); perm[u] = L.orb[q[a]]
        return perm

    def normalizer_group(self, L):
        """all distinct coordinate permutations of level L generated by the normalizer elements (identity included)"""
        gens = [tuple(self.level_perm(L, nu).tolist()) for nu in self.normalizer]
        ident = tuple(range(L.O)); grp = {ident}; frontier = [ident]
        while frontier:
            x = frontier.pop()
            for g in gens:
                y = tuple(x[g[i]] for i in range(L.O))
                if y not in grp: grp.add(y); frontier.append(y)
        return [np.array(g, dtype=np.int64) for g in sorted(grp)]

    # ---- patterns ----
    def y_orbit_vector(self, y):
        """coset sums -> targets on the Q-level orbit coordinates (checks H-invariance of the pattern)"""
        Q = self.Qlevel; out = np.zeros(Q.O, dtype=np.int64); seen = np.zeros(Q.O, dtype=bool)
        for c in range(Q.GK.v):
            u = Q.orb[c]
            if seen[u] and out[u] != y[c]: raise ValueError("coset sums are not constant on the H-orbits of Q")
            out[u] = y[c]; seen[u] = True
        return out

    def level0_check(self):
        """sum_i PAF of the coset sums = prescribed values on Q"""
        Q = self.Qlevel
        F = sum(Q.paf(self.yorb[i][None, :])[0].astype(np.int64) for i in range(4))
        return bool(np.array_equal(F, Q.T)), F, Q.T

    # ---- masks -> sequences / PAF classes ----
    def bits(self, masks):
        return ((masks[:, None] >> np.arange(self.O, dtype=np.uint64)) & np.uint64(1))

    def class_values(self, masks, B=8192):
        """integer PAF at the class representatives for orbit-sign masks (bit 1 = +1)"""
        n = len(masks); out = np.empty((n, self.C), dtype=np.int32)
        for i in range(0, n, B):
            Y = (2 * self.bits(masks[i:i + B]).astype(np.float32) - 1)
            Z = (Y @ self._Mf).reshape(len(Y), self.C, self.O)
            out[i:i + B] = np.rint(np.einsum('ncp,np->nc', Z, Y)).astype(np.int32)
        return out

    def sequence(self, mask):
        b = ((int(mask) >> np.arange(self.O)) & 1)
        return (2 * b - 1)[self.orb].astype(np.int64)

    def verify(self, masks):
        """exact verification over G: row/coset sums and sum of PAFs. Returns (ok, message)."""
        G = self.G; v = self.v
        if self._shift is None:
            self._shift = np.array([G.translate(s) for s in range(v)], dtype=np.int32)
        seqs = [self.sequence(m) for m in masks]
        tot = np.zeros(v, dtype=np.int64)
        for x in seqs:
            tot += (x[self._shift] * x[None, :]).sum(1)
        if not np.array_equal(tot, self.tgt): return False, 'PAF sum differs from target at %d places' % int((tot != self.tgt).sum())
        for i, x in enumerate(seqs):
            cs = np.bincount(self.cos, weights=x, minlength=self.k).round().astype(np.int64)
            if not np.array_equal(cs, self.ys[i]): return False, 'coset sums of block %d differ' % i
        for i, x in enumerate(seqs):
            for p in self.perms:
                if not np.array_equal(x[p], x): return False, 'block %d is not H-invariant' % i
        return True, 'ok'

    # ---- DP over orbits ----
    def dp(self, y_orbit, fixed, new, max_states=60_000_000, order_mode='greedy', strategy='auto'):
        """strategy 'orbit': DP over single orbits; 'grouped': items = the orbit groups of the finest fixed level (exact group sums enumerated
        once and cached), coarser fixed levels dropped as redundant; 'auto': grouped when a fixed tree level has >= 3 coordinates."""
        if strategy == 'auto':
            finest = max((l for l, _ in fixed), key=lambda l: l.O) if fixed else None
            strategy = 'grouped' if fixed and any(l.O >= 3 for l, _ in fixed) and (new is None or not new.implied_by(finest)) else 'orbit'
        if strategy == 'grouped':
            return self.dp_grouped(y_orbit, fixed, new, max_states)
        return self.dp_orbit(y_orbit, fixed, new, max_states, order_mode)

    def dp_orbit(self, y_orbit, fixed, new, max_states=60_000_000, order_mode='greedy'):
        """Distinct compressed vectors on `new` (a Level or None) with multiplicities, over all sign vectors of the orbits whose
        compressions on the fixed levels hit their targets and whose coset sums hit y_orbit.
        fixed: list of (Level, target vector).  Returns (K [n x O_new] int16, cnt [n] float64, peak)."""
        lv = [(self.Qlevel, y_orbit)] + list(fixed)
        alllv = [l for l, _ in lv] + ([new] if new is not None else [])
        offs = np.concatenate([[0], np.cumsum([l.O for l in alllv])]); D = int(offs[-1])
        O = self.O; Lmax = len(alllv)
        co = np.zeros((O, Lmax), dtype=np.int32); cw = np.zeros((O, Lmax), dtype=np.int32); nco = np.full(O, Lmax, dtype=np.int32)
        for t, l in enumerate(alllv):
            co[:, t] = offs[t] + l.uof; cw[:, t] = l.w
        fixedf = np.zeros(D, dtype=np.int32); tgt = np.zeros(D, dtype=np.int32)
        for t, (l, tv) in enumerate(lv):
            fixedf[offs[t]:offs[t + 1]] = 1; tgt[offs[t]:offs[t + 1]] = np.asarray(tv, dtype=np.int32)
        order = self._order(alllv, offs, new is not None, order_mode)
        nout = new.O if new is not None else 0
        outidx = (offs[-2] + np.arange(nout)).astype(np.int32) if new is not None else np.zeros(1, dtype=np.int32)
        peak = ctypes.c_int64(0)
        n = LIB.dp_run(O, D, Lmax, _p(order), _p(nco), _p(co), _p(cw), _p(fixedf), _p(tgt), nout, _p(outidx), max_states, ctypes.byref(peak))
        if n == -1: raise OverflowError("dp state explosion (> %d)" % max_states)
        if n < 0: raise MemoryError("dp allocation failure")
        K = np.zeros((n, max(nout, 1)), dtype=np.int16); cnt = np.zeros(n, dtype=np.float64)
        LIB.dp_fetch(_p(K), _p(cnt))
        if nout == 0:
            return None, cnt, peak.value
        # deterministic order
        o2 = np.lexsort(tuple(K[:, j] for j in range(nout - 1, -1, -1)))
        return K[o2], cnt[o2], peak.value

    def dp_grouped(self, y_orbit, fixed, new, max_states=60_000_000):
        lv = [(self.Qlevel, y_orbit)] + list(fixed)
        gi = max(range(len(lv)), key=lambda t: (lv[t][0].O, -t))
        gl, gt = lv[gi]
        others = [(l, tv) for t, (l, tv) in enumerate(lv) if t != gi and not l.implied_by(gl)]      # coarser levels are implied by the group sums
        coordlv = [l for l, _ in others] + ([new] if new is not None else [])
        offs = np.concatenate([[0], np.cumsum([l.O for l in coordlv])]).astype(int); D = int(offs[-1]); De = max(D, 1)
        nfx = int(offs[len(others)])
        opts = []; counts = []
        for u in range(gl.O):
            uq, ct = self._options(gl, u, gt[u], coordlv)
            if len(uq) == 0:
                nout = new.O if new is not None else 0
                return (np.zeros((0, nout), dtype=np.int16), np.zeros(0), 0) if new is not None else (None, np.zeros(0), 0)
            opts.append(uq); counts.append(ct)
        optstart = np.concatenate([[0], np.cumsum([len(o) for o in opts])]).astype(np.int64)
        delta = np.zeros((int(optstart[-1]), De), dtype=np.int16)
        for s, o in enumerate(opts):
            if D: delta[optstart[s]:optstart[s + 1], :D] = o
        mult = np.concatenate(counts).astype(np.float64)
        fixedf = np.zeros(De, dtype=np.int32); tgt = np.zeros(De, dtype=np.int32)
        fixedf[:nfx] = 1
        if nfx: tgt[:nfx] = np.concatenate([np.asarray(tv, dtype=np.int32) for _, tv in others])
        if D == 0: fixedf[0] = 1
        nout = new.O if new is not None else 0
        outidx = (nfx + np.arange(nout)).astype(np.int32) if nout else np.zeros(1, dtype=np.int32)
        peak = ctypes.c_int64(0)
        n = LIB.dp_items(gl.O, De, _p(optstart), _p(delta), _p(mult), _p(fixedf), _p(tgt), nout, _p(outidx), max_states, ctypes.byref(peak))
        if n == -1: raise OverflowError("dp state explosion (> %d)" % max_states)
        if n < 0: raise MemoryError("dp allocation failure")
        K = np.zeros((n, max(nout, 1)), dtype=np.int16); cnt = np.zeros(n, dtype=np.float64)
        LIB.dp_fetch(_p(K), _p(cnt))
        if nout == 0: return None, cnt, peak.value
        o2 = np.lexsort(tuple(K[:, j] for j in range(nout - 1, -1, -1)))
        return K[o2], cnt[o2], peak.value

    def _options(self, gl, u, tval, coordlv):
        """distinct contribution vectors (over the concatenated coordinates of coordlv) of the sign assignments of the orbits over
        coordinate u of level gl with exact weighted sum tval, with multiplicities (cached)"""
        key = ('opt', id(gl), u, int(tval), tuple(id(l) for l in coordlv))
        hit = self._localcache.get(key)
        if hit is not None: return hit
        masks, contrib = self._local(gl, u, tval, coordlv)
        if len(masks) == 0 or contrib.shape[1] == 0:
            res = (np.zeros((len(masks), contrib.shape[1]), dtype=np.int16) if len(masks) == 0 else np.zeros((1, 0), dtype=np.int16), np.array([len(masks)], dtype=np.float64) if len(masks) else np.zeros(0))
        else:
            uq, ct = np.unique(contrib, axis=0, return_counts=True)
            res = (uq.astype(np.int16), ct.astype(np.float64))
        self._localcache[key] = res
        return res

    def _order(self, alllv, offs, has_new, mode):
        """processing order of the orbits.  'greedy': repeatedly take the orbit that leaves the fewest coordinates open (touched but not
        completed), preferring orbits that complete coordinates; 'primary': group by the level with most coordinates."""
        O = self.O
        if mode == 'primary':
            prim = max(range(len(alllv)), key=lambda t: (alllv[t].O, -t))
            keys = [alllv[prim].uof] + [l.uof for t, l in enumerate(alllv) if t != prim]
            return np.lexsort(tuple(reversed(keys + [np.arange(O)]))).astype(np.int32)
        coords = [frozenset(int(offs[t] + l.uof[o]) for t, l in enumerate(alllv)) for o in range(O)]
        remaining = {}
        for o in range(O):
            for c in coords[o]: remaining[c] = remaining.get(c, 0) + 1
        opn = set(); left = set(range(O)); order = []
        while left:
            best = None
            for o in sorted(left):
                no = opn | coords[o]
                closed = {c for c in coords[o] if remaining[c] == 1}
                cost = (len(no) - len(closed), -len(closed), o)
                if best is None or cost < best[0]: best = (cost, o)
            o = best[1]; order.append(o); left.discard(o)
            for c in coords[o]:
                remaining[c] -= 1; opn.add(c)
                if remaining[c] == 0: opn.discard(c)
        return np.array(order, dtype=np.int32)

    def fibre_count(self, y_orbit, fixed):
        _, cnt, _ = self.dp(y_orbit, fixed, None)
        return float(cnt.sum()) if len(cnt) else 0.0

    # ---- exact four-list join ----
    @staticmethod
    def join4(Fs, T, maxout=2_000_000, stop_at=0, budget=500_000, verbose=False):
        Fs = [np.ascontiguousarray(F, dtype=np.int32) for F in Fs]
        T = np.ascontiguousarray(T, dtype=np.int32)
        C = Fs[0].shape[1]
        stats = np.zeros(8)
        while True:
            out = np.empty((maxout, 4), dtype=np.uint32)
            tot = LIB.join4(_p(Fs[0]), len(Fs[0]), _p(Fs[1]), len(Fs[1]), _p(Fs[2]), len(Fs[2]), _p(Fs[3]), len(Fs[3]),
                            C, _p(T), _p(out), maxout, stop_at, budget, int(verbose), _p(stats))
            if tot < 0: raise MemoryError("join4 failed (%d)" % tot)
            if tot <= maxout or stop_at: break
            maxout = int(tot)
        return int(tot), out[:min(tot, maxout)].astype(np.int64), stats

    # ---- enumeration of a fibre as orbit-sign masks (meet in the middle over the groups of one level) ----
    def _local(self, gl, ul, tval, others):
        """sign assignments of the orbits over coordinate ul of level gl with weighted sum tval; returns (masks, contrib)"""
        key = (id(gl), ul, int(tval), tuple(id(o) for o in others))
        hit = self._localcache.get(key)
        if hit is not None: return hit
        orbs = np.flatnonzero(gl.uof == ul); m = len(orbs)
        if m > 24: raise ValueError("a group of %d orbits is too large to enumerate" % m)
        idx = np.arange(1 << m, dtype=np.int64)
        sg = 1 - 2 * ((idx[:, None] >> np.arange(m)) & 1)                # +1 when bit is 0
        ok = (sg @ gl.w[orbs]) == tval
        sg = sg[ok]
        masks = ((sg > 0).astype(np.uint64) << orbs.astype(np.uint64)[None, :]).sum(1, dtype=np.uint64) if len(sg) else np.zeros(0, dtype=np.uint64)
        offs = np.concatenate([[0], np.cumsum([l.O for l in others])]); D = int(offs[-1])
        Wo = np.zeros((m, D), dtype=np.int64)
        for t, l in enumerate(others):
            for j, o in enumerate(orbs): Wo[j, offs[t] + l.uof[o]] += l.w[o]
        contrib = (sg @ Wo).astype(np.int16)
        self._localcache[key] = (masks, contrib)
        return masks, contrib

    def enumerate_fibre(self, y_orbit, fixed, maxside=30_000_000):
        """All orbit-sign masks (uint64, bit o = +1) with the given compressions on the fixed levels; exact (the hash
        match is re-checked on the contribution vectors)."""
        lv = [(self.Qlevel, y_orbit)] + list(fixed)
        gi = max(range(len(lv)), key=lambda t: (lv[t][0].O, -t))
        gl, gt = lv[gi]
        others = [l for t, (l, _) in enumerate(lv) if t != gi]; otg = [tv for t, (_, tv) in enumerate(lv) if t != gi]
        tother = np.concatenate([np.asarray(t, dtype=np.int64) for t in otg]) if otg else np.zeros(0, dtype=np.int64)
        groups = []
        for u in range(gl.O):
            m, c = self._local(gl, u, gt[u], others)
            if len(m) == 0: return np.zeros(0, dtype=np.uint64)
            groups.append((m, c))
        sizes = [len(g[0]) for g in groups]
        ng = len(groups)
        # balanced split of the groups into two sides
        logs = [math.log(s) for s in sizes]; best = None
        if ng <= 18:
            tot = sum(logs)
            for sub in range(1 << ng):
                a = sum(logs[j] for j in range(ng) if sub >> j & 1)
                sc = max(a, tot - a)
                if best is None or sc < best[0] - 1e-12: best = (sc, sub)
            left = [j for j in range(ng) if best[1] >> j & 1]
        else:
            left = []; a = 0.0; tot = sum(logs)
            for j in sorted(range(ng), key=lambda j: -logs[j]):
                if a + logs[j] <= tot / 2: left.append(j); a += logs[j]
        right = [j for j in range(ng) if j not in left]

        def expand(js):
            masks = np.zeros(1, dtype=np.uint64); con = np.zeros((1, len(tother)), dtype=np.int16)
            for j in js:
                m, c = groups[j]
                if len(masks) * len(m) > maxside: raise OverflowError("fibre half-list exceeds %d" % maxside)
                masks = (masks[:, None] | m[None, :]).ravel()
                con = (con[:, None, :] + c[None, :, :]).reshape(-1, con.shape[1])
            return masks, con
        ml, cl = expand(left); mr, cr = expand(right)
        R = self.Rh[:max(len(tother), 1)]
        hl = (cl.astype(np.int64).astype(np.uint64) * R[None, :len(tother)]).sum(1, dtype=np.uint64)
        hr = (cr.astype(np.int64).astype(np.uint64) * R[None, :len(tother)]).sum(1, dtype=np.uint64)
        ht = (tother.astype(np.uint64) * R[:len(tother)]).sum(dtype=np.uint64) if len(tother) else np.uint64(0)
        order = np.argsort(hr, kind='stable'); hrs = hr[order]
        want = ht - hl
        lo = np.searchsorted(hrs, want, 'left'); hi = np.searchsorted(hrs, want, 'right')
        cnt = hi - lo
        nz = np.flatnonzero(cnt)
        outs = []
        for c0 in range(0, len(nz), 1 << 16):
            ii = nz[c0:c0 + (1 << 16)]; k = cnt[ii]
            I = np.repeat(ii, k)
            off = np.arange(int(k.sum())) - np.repeat(np.cumsum(k) - k, k)
            J = order[lo[I] + off]
            ok = np.all(cl[I].astype(np.int64) + cr[J] == tother[None, :], axis=1)
            I, J = I[ok], J[ok]
            if len(I): outs.append(ml[I] | mr[J])
        return np.concatenate(outs) if outs else np.zeros(0, dtype=np.uint64)

    def fibre_size_hint(self, y_orbit, fixed):
        return self.fibre_count(y_orbit, fixed)
